
DROP TABLE IF EXISTS `sourcelead`.`countries`;
CREATE TABLE `sourcelead`.`countries` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  Code VARCHAR(3) DEFAULT NULL,
  Name VARCHAR(52) DEFAULT NULL,
  Continent VARCHAR(50) DEFAULT NULL,
  Region VARCHAR(30) DEFAULT NULL,
  LocalName VARCHAR(45) DEFAULT NULL,
  Code2 VARCHAR(2) DEFAULT NULL,
  flagPath varchar(250) DEFAULT NULL,
  PRIMARY KEY (`ID`) 
); 

DROP TABLE IF EXISTS `sourcelead`.`states`;
CREATE TABLE `sourcelead`.`states` (
  ID BIGINT(20) NOT NULL AUTO_INCREMENT,
  countryCode VARCHAR(5) NOT NULL,
  stateCode VARCHAR(20) NOT NULL,
  stateName VARCHAR(100) DEFAULT NULL,
  PRIMARY KEY (`ID`)
) ;

DROP TABLE IF EXISTS `sourcelead`.`cities`;
CREATE TABLE `sourcelead`.`cities` (
  countryCode VARCHAR(10) NOT NULL,
  stateCode VARCHAR(10) NOT NULL,
  cityName VARCHAR(100) NOT NULL,
  PRIMARY KEY (`countryCode`,`stateCode`,`cityName`),
  KEY `countryCode` (`countryCode`,`stateCode`,`cityName`)
);


DROP TABLE IF EXISTS `sourcelead`.`timezone`;
CREATE TABLE `sourcelead`.`timezone` (
  `countryCode` varchar(2)  DEFAULT NULL,
  `timezoneid` varchar(255)  DEFAULT NULL,
  `gmtoffset` float DEFAULT NULL,
  `dstoffest` float DEFAULT NULL,
  `rawoffset` float DEFAULT NULL
);


DROP TABLE IF EXISTS `sourcelead`.`ORG`;
CREATE TABLE `sourcelead`.`ORG` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_NAME VARCHAR(50) DEFAULT NULL,
  WEBSITE VARCHAR(100) DEFAULT NULL,
  ORG_TYPE VARCHAR(50) DEFAULT NULL,
  ORG_CODE VARCHAR(10) DEFAULT NULL,
  STATUS VARCHAR(20),
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`)
) ;



DROP TABLE IF EXISTS `sourcelead`.`USER`;
CREATE TABLE `sourcelead`.`USER` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  FIRST_NAME VARCHAR(50)  DEFAULT NULL,
  LAST_NAME VARCHAR(50)  DEFAULT NULL,
  EMAIL VARCHAR(100) DEFAULT NULL,
  WORK_PHONE VARCHAR(20) DEFAULT NULL,
  MOBILE_PHONE VARCHAR(20) DEFAULT NULL,
  USER_STATE VARCHAR(30) DEFAULT NULL,
  USER_TYPE VARCHAR(20),
  USER_NAME VARCHAR(50),
  PASSWORD VARCHAR(250),
  DOC_FILE MEDIUMBLOB,
  FILE_CONTENT_TYPE VARCHAR(50),
  STATUS VARCHAR(20),
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`)
) ;




DROP TABLE IF EXISTS `sourcelead`.`ORG_LOCATIONS`;
CREATE TABLE `sourcelead`.`ORG_LOCATIONS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_ID BIGINT,
  PRIMARY_CONTACT_USER_ID BIGINT,
  COUNTRY VARCHAR(50) DEFAULT NULL,
  STATE VARCHAR(50) DEFAULT NULL,
  CITY VARCHAR(50) DEFAULT NULL,
  ZIP_CODE VARCHAR(20),
  STATUS VARCHAR(20),
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_ID) REFERENCES `sourcelead`.`ORG`(ID),
  FOREIGN KEY(PRIMARY_CONTACT_USER_ID) REFERENCES `sourcelead`.`USER`(ID)
) ;



DROP TABLE IF EXISTS `sourcelead`.`EMPLOYEE`;
CREATE TABLE `sourcelead`.`EMPLOYEE` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  USER_ID BIGINT,
  HIRE_DATE DATE DEFAULT NULL,
  DOB DATE DEFAULT NULL,
  COUNTRY VARCHAR(50) DEFAULT NULL,
  STATE VARCHAR(50) DEFAULT NULL,
  CITY VARCHAR(50) DEFAULT NULL,
  EMPLOYEE_STATE VARCHAR(30) DEFAULT NULL,
  STATUS VARCHAR(20),
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(USER_ID) REFERENCES `sourcelead`.`USER`(ID)
) ;



DROP TABLE IF EXISTS `sourcelead`.`PROJECTS`;
CREATE TABLE `sourcelead`.`PROJECTS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  PROJECT_NAME VARCHAR(100),
  DESCRIPTION TEXT DEFAULT NULL,
  START_DATE DATE DEFAULT NULL,
  END_DATE DATE DEFAULT NULL,
  TIMESHEET_FREQUENCY VARCHAR(50) DEFAULT NULL,
  PROJECT_MANAGER_USER_ID BIGINT,
  CLIENT_ORG_ID BIGINT,
  SUPERIOR_USER_ID BIGINT,
  PROJECT_STATUS VARCHAR(30),
  STATUS VARCHAR(20),
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(PROJECT_MANAGER_USER_ID) REFERENCES `sourcelead`.`USER`(ID),
  FOREIGN KEY(CLIENT_ORG_ID) REFERENCES `sourcelead`.`ORG`(ID),
  FOREIGN KEY(SUPERIOR_USER_ID) REFERENCES `sourcelead`.`USER`(ID)
) ;




