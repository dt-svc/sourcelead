DROP TABLE IF EXISTS `sourcelead`.`USER_LOGIN_ATTEMPTS`;
CREATE TABLE `sourcelead`.`USER_LOGIN_ATTEMPTS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  USER_ID BIGINT,
  ATTEMPTS_COUNT INT,
  STATUS VARCHAR(20),
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(USER_ID) REFERENCES `sourcelead`.`USER`(ID)
) ;