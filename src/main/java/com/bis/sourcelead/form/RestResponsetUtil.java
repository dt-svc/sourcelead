package com.bis.sourcelead.form;

public class RestResponsetUtil {
	
	
	private String status;
	
	private String loginResponse;

	private String resetResponse;
	
	private String token;
	
	public String getStatus() {
		return status;
	}

	public void setStatus(String status) {
		this.status = status;
	}

	public String getLoginResponse() {
		return loginResponse;
	}

	public void setLoginResponse(String loginResponse) {
		this.loginResponse = loginResponse;
	}

	public String getResetResponse() {
		return resetResponse;
	}

	public void setResetResponse(String resetResponse) {
		this.resetResponse = resetResponse;
	}

	public String getToken() {
		return token;
	}

	public void setToken(String token) {
		this.token = token;
	} 
		

}
