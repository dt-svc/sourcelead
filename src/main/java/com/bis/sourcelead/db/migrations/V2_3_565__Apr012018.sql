CREATE TABLE `PROJECT_MEMBERS_RATE_HISTORY` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  PROJECT_MEMBER_ID BIGINT DEFAULT NULL,
  CANDIDATE_ID BIGINT DEFAULT NULL,
  BILL_RATE DOUBLE DEFAULT NULL,
  BILL_RATE_TYPE VARCHAR(50) DEFAULT NULL,
  BILL_RATE_CURRENCY VARCHAR(50) DEFAULT NULL,
  BILL_RATE_START_DATE DATE,
  BILL_RATE_END_DATE DATE,
  PAY_RATE DOUBLE DEFAULT NULL,
  PAY_RATE_TYPE VARCHAR(50) DEFAULT NULL,
  PAY_RATE_CURRENCY VARCHAR(50) DEFAULT NULL,
  PAY_RATE_START_DATE DATE,
  PAY_RATE_END_DATE DATE,
  STATUS INT DEFAULT NULL,
  CREATED_BY BIGINT DEFAULT NULL,
  CREATED_DATE DATE,
  UPDATED_DATE DATE,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(PROJECT_MEMBER_ID) REFERENCES `PROJECT_MEMBERS`(ID),
  FOREIGN KEY(CANDIDATE_ID) REFERENCES `CANDIDATE`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID)
) ;


