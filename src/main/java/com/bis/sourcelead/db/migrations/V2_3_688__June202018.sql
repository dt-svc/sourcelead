#APPLIED_LEAVE_DATE

DROP TABLE IF EXISTS `sourcelead`.`APPLIED_LEAVE_DATE`;
CREATE TABLE `APPLIED_LEAVE_DATE` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  LEAVE_ID BIGINT,
  APPLY_LEAVE_DATE DATE,
  APPLY_MONTH_NAME VARCHAR(10),
  IS_PAYROLL_INCLUDE VARCHAR(10),
  STATUS int,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(LEAVE_ID) REFERENCES `USER_LEAVE`(ID)
) ;

#APPLIED_LEAVE_DATE_VIEW
CREATE OR REPLACE VIEW APPLIED_LEAVE_DATE_VIEW AS
SELECT uLeave.USER_ID,
       uLeave.ORGLOCATION_ID,
       uLeave.STATUS as LEAVE_STATUS,
       uLeave.REASON AS REASON,
       aLeaveDate.APPLY_LEAVE_DATE,
       aLeaveDate.APPLY_MONTH_NAME,
       aLeaveDate.IS_PAYROLL_INCLUDE,
       aLeaveDate.STATUS
FROM sourcelead.USER_LEAVE uLeave,APPLIED_LEAVE_DATE aLeaveDate
where uLeave.ID = aLeaveDate.LEAVE_ID;

