  ID BIGINT NOT NULL AUTO_INCREMENT,
  SUBSCRIPTION_TYPE_ID BIGINT DEFAULT NULL,
  USER_SUBSCRIPTION_TYPE_ID BIGINT DEFAULT NULL,
  SUBSCRIPTION_RATE DOUBLE DEFAULT NULL,
  PRIMARY KEY (`ID`), 
