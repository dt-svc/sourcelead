# US_PAY_SCHEDULE_DATE

DROP TABLE IF EXISTS `US_PAY_SCHEDULE_DATE`;
CREATE TABLE `US_PAY_SCHEDULE_DATE` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  SCHEDULE_ID BIGINT,
  PAY_PERIOD_SDATE DATE,
  PAY_PERIOD_EDATE DATE,
  PAY_CHECK_DATE DATE,
  PAY_RUN_DATE DATE,
  STATUS int,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(SCHEDULE_ID) REFERENCES `ORG_LOCATIONS`(ID) 
) ;

