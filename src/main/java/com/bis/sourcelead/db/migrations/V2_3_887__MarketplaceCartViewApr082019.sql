 
CREATE OR REPLACE VIEW CANDIDATE_MARKET_PLACE_CART_VIEW AS

SELECT 
	MARKETPLACE.ID AS ID,
    MARKETCART.SOURCE_ORG_LOCATION_ID AS SOURCE_ORG_LOCATION_ID,
    MARKETCART.TARGET_ORG_LOCATION_ID AS TARGET_ORG_LOCATION_ID,
    MARKETCART.CART_STATUS AS CART_STATUS,
    MARKETPLACE.CANDIDATE_ID AS CANDIDATE_ID,
    MARKETPLACE.CANDIDATE_UUID AS CANDIDATE_UUID,
    CONCAT(IF(CANDI.FIRST_NAME IS NULL,'',CANDI.FIRST_NAME),' ',IF(CANDI.MIDDLE_NAME IS NULL,'',CANDI.MIDDLE_NAME),' ',IF(CANDI.LAST_NAME IS NULL,'',CANDI.LAST_NAME)) AS FULLNAME,
    CANDI.LOCATION AS LOCATION,
    CANDI.FILE_URL AS IMAGEURL,
    CANDI.SKILLS_NAME AS SKILLSNAME,
    CANDI.DESIGNATION AS DESIGNATION,
    CANDI.CURRENT_RATE AS CURRENT_RATE,
    CANDI.CURRENT_RATE_CURRENCY AS CURR_RATE_CUR,
    CANDI.CURRENT_RATE_TYPE AS CURRENT_RATE_TYPE,
    CANDI.EXPECTED_RATE AS EXPECTED_RATE,
    CANDI.EXPECTED_RATE_CURRENCY AS EXP_RATE_CUR,
    CANDI.RATE_TYPE AS EXP_RATE_TYPE,
    CANDI.EXPERIENCE_YEARS AS EXP_IN_YEARS,
    CANDI.EXPERIENCE_MONTHS AS EXP_IN_MONTHS,
    MARKETPLACE.MARKET_PRICE AS MARKET_PRICE,
    MARKETPLACE.MARKET_RATE_CURRENCY AS MARKET_CURRENCY,
    CANDI.PROFILE_PERCENTAGE AS PROFILE_PERCENTAGE,
    MARKETCART.CREATED_DATE AS CREATED_DATE,
    MARKETCART.CREATED_BY AS CREATED_BY,
    (SELECT 
            CONCAT(USER.FIRST_NAME, ' ', USER.LAST_NAME)
        FROM
            USER
        WHERE
            USER.ID = MARKETPLACE.CREATED_BY) AS CREATED_BY_NAME
FROM
    CANDIDATE_MARKET_PLACE MARKETPLACE,
    CANDIDATE_MARKET_CART MARKETCART,
    CANDIDATE CANDI
WHERE
    MARKETPLACE.ID = MARKETCART.MARKETPLACE_ID AND CANDI.ID = MARKETPLACE.CANDIDATE_ID;
    
