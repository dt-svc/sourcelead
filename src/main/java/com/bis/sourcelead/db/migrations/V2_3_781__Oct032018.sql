DROP TABLE IF EXISTS `EMAIL_ACCOUNT_SETTINGS`;
CREATE TABLE `EMAIL_ACCOUNT_SETTINGS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  USER_ID BIGINT,
  EMAIL VARCHAR(100),
  PASSWORD VARCHAR(100),
  INCOMING_SERVER VARCHAR(50),
  INCOMING_PORT VARCHAR(10),
  INCOMING_SSL BOOLEAN DEFAULT FALSE,
  OUTGOING_SERVER VARCHAR(50),
  OUTGOING_PORT VARCHAR(10),
  OUTGOING_SSL BOOLEAN DEFAULT FALSE,
  EMAIL_TYPE VARCHAR(10),
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(50),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(50),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(USER_ID) REFERENCES `USER`(ID)
);