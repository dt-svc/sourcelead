DROP TABLE IF EXISTS `TDS`;
DROP TABLE IF EXISTS `CENTRAL_TAX`;
CREATE TABLE `CENTRAL_TAX` (
    ID BIGINT NOT NULL AUTO_INCREMENT,
	CEIL_VALUE_PF  INT NOT NULL,
	NO_OF_EMPLOYEES DOUBLE  ,
	EMPLOYEE_PF DOUBLE ,
	EMPLOYER_PF DOUBLE ,
	CEIL_VALUE_ESI INT NOT NULL,
	EMPLOYEE_ESI DOUBLE ,
	EMPLOYER_ESI DOUBLE ,
	TAX_TYPE_ID BIGINT DEFAULT NULL,
	ACTIVE BOOLEAN DEFAULT TRUE,
	CENTRALTAX_UUID VARCHAR(20);
	CT_FINANCIAL_YEAR VARCHAR(15),
	
	
	PRIMARY KEY (`ID`),
	FOREIGN KEY(TAX_TYPE_ID) REFERENCES `SOURCELEAD_TAX_TYPE`(ID)
	
);

CREATE TABLE `TDS` (
    ID BIGINT NOT NULL AUTO_INCREMENT,
	CENTRAL_TAX_ID BIGINT DEFAULT NULL,
    AGE VARCHAR(255) DEFAULT NULL,
    FROM_AMOUNT INT DEFAULT NULL,
    TO_AMOUNT INT DEFAULT NULL,
    PERCENTAGE  DOUBLE NOT NULL,
    EDUCATION_CEISS DOUBLE NOT NULL,
    SURCHARGE DOUBLE NOT NULL,
    PRIMARY KEY (`ID`),
    FOREIGN KEY(CENTRAL_TAX_ID) REFERENCES `CENTRAL_TAX`(ID)
);