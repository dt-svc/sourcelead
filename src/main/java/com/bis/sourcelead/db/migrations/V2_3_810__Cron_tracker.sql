DROP TABLE IF EXISTS `CRON_TRACKER`;
CREATE TABLE `CRON_TRACKER` (
  `Id` BIGINT NOT NULL AUTO_INCREMENT,
  `MODULE_NAME` VARCHAR(250) NOT NULL,
  `METHOD_NAME` VARCHAR(250) NOT NULL,
  `CRON_EXPRESSION` VARCHAR(20) NOT NULL,
  `CRON_TYPE` VARCHAR(50) NOT NULL,
  `CRON_RUN_DATE_TIME` DATETIME NOT NULL,
  PRIMARY KEY (`Id`));