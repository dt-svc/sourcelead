# CAMPAIGN_SENDER
DROP TABLE IF EXISTS `CAMPAIGN_SENDER`;
CREATE TABLE `CAMPAIGN_SENDER` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORGLOCATION_ID BIGINT,
  FROM_NAME VARCHAR(250) NULL,
  FROM_MAIL VARCHAR(250) NULL,
  REPLY_TO VARCHAR(250) NULL,
  NICK_NAME VARCHAR(250) NULL,
  IS_SENDER_EMAIKL_VERIFIED VARCHAR(250) NULL,
  SENDER_ID VARCHAR(250) NULL,
  SELECTED_SENDER VARCHAR(250) NULL,
  CITY VARCHAR(250) NULL,
  ZIP VARCHAR(205) NULL,
  COUNTRY VARCHAR(250) NULL,
  STATE VARCHAR(250),
  ADDRESS VARCHAR(250),
  STATUS INT(20) NULL,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(100),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORGLOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
);


#CAMPAIGN_LIST
DROP TABLE IF EXISTS `CAMPAIGN_LIST`;
CREATE TABLE `CAMPAIGN_LIST` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORGLOCATION_ID BIGINT,
  LIST_ID VARCHAR(250) NULL,
  LIST_NAME VARCHAR(250) NULL,
  CAMPAIGN_TYPE INT(20) NULL,
  STATUS INT(20) NULL,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(100),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORGLOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID)
);

#RECIPIENT_LIST
DROP TABLE IF EXISTS `CAMPAIGN_RECIPIENT`;
CREATE TABLE `CAMPAIGN_RECIPIENT` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  FIRST_NAME VARCHAR(250) NULL,
  LAST_NAME VARCHAR(250) NULL,
  EMAIL VARCHAR(250) NULL,
  CAMPAIGN_LIST_ID BIGINT,
  RECIPIENT_ID VARCHAR(250) NULL,
  STATUS INT(20) NULL,
  CREATED_DATE DATE,
  CREATED_BY  BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(100),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID)
);


#CAMPAIGN
DROP TABLE IF EXISTS `CAMPAIGN`;
CREATE TABLE `CAMPAIGN` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORGLOCATION_ID BIGINT,
  CAMPAIGN_SUBJECT VARCHAR(250) NULL,
  CAMPAIGN_TITLE VARCHAR(250) NULL,
  CAMPAIGN_CATEGORY VARCHAR(250) NULL,
  LIST_IDS VARCHAR(250) NULL,
  SENDER_ID VARCHAR(250) NULL,
  CAMPAIGN_ID VARCHAR(250) NULL,
  CAMPAIGN_TYPE INT(20) NULL,
  IP_POOL VARCHAR(250) NULL,
  HTML_CONTENT TEXT,
  PLAIN_CONTENT TEXT,
  STATUS INT(20) NULL,
  CAMPAIGN_SCHEDULE_ID VARCHAR(250) NULL,
  CAMPAIGN_SCHEDULE_STAUS VARCHAR(250) NULL,
  CREATED_DATE DATE,
  CREATED_BY  BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(100),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORGLOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID)
);


