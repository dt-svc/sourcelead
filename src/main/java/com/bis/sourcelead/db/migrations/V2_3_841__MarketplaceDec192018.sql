DROP TABLE IF EXISTS `CANDIDATE_MARKET_WALLET`;
CREATE TABLE `CANDIDATE_MARKET_WALLET`(
ID BIGINT NOT NULL AUTO_INCREMENT,
TRANSACTION_ID VARCHAR(45) DEFAULT NULL,
AMOUNT DOUBLE DEFAULT NULL,
AMOUNT_TYPE VARCHAR(20) DEFAULT NULL,
PAYMENT_STATUS VARCHAR(20) DEFAULT NULL,
ORG_LOCATION_ID BIGINT NOT NULL,
PAYMENT_TRANSACTION_HISTORY_ID BIGINT NOT NULL,
WALLET_UUID VARCHAR(50),
DESCRIPTION LONGTEXT DEFAULT NULL,
TRANSACTION_DATE DATETIME,

PRIMARY KEY (`ID`), 

FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
FOREIGN KEY(PAYMENT_TRANSACTION_HISTORY_ID) REFERENCES `CANDIDATE_MARKET_PLACE_PAYMENT_TRANSACTION_HISTORY`(ID)
);