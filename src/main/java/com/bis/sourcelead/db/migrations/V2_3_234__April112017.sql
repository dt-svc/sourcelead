
DROP TABLE IF EXISTS `sourcelead`.`ON_BOARDING_DOCUMENTS`;
CREATE TABLE `sourcelead`.`ON_BOARDING_DOCUMENTS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  DOCUMENT_NAME VARCHAR(100) DEFAULT NULL,
  DESCRIPTION TEXT,
  STATUS INT,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`)
  
) ;



DROP TABLE IF EXISTS `sourcelead`.`ON_BOARDING_RELATED_DOCUMENTS`;
CREATE TABLE `sourcelead`.`ON_BOARDING_RELATED_DOCUMENTS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ON_BOARDING_DOCUMENTS_ID BIGINT,  
  DOCUMENT_TYPE VARCHAR(50) DEFAULT NULL,
  DOC_FILE MEDIUMBLOB,
  FILE_CONTENT_TYPE VARCHAR(500),
  FILE_NAME TEXT,
  STATUS INT,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ON_BOARDING_DOCUMENTS_ID) REFERENCES `sourcelead`.`ON_BOARDING_DOCUMENTS`(ID)
 
) ;