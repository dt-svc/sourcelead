DROP TABLE IF EXISTS `INVOICE_DATA`;
CREATE TABLE `INVOICE_DATA` (
ID BIGINT NOT NULL AUTO_INCREMENT,
ORG_LOCATION_ID BIGINT DEFAULT NULL,
SKU VARCHAR(100) DEFAULT NULL,
PRODUCT_SERVICE VARCHAR(250) DEFAULT NULL,
EMP_NAME VARCHAR(250),
NUMBER VARCHAR(250),
MEMO_DESCRIPTION TEXT DEFAULT NULL,
DATE DATETIME,
LAST_MODIFIED DATETIME,
DUE_DATE DATETIME,
RATE VARCHAR(250),
QTY VARCHAR(250),
AMOUNT VARCHAR(250),
AR_PAID VARCHAR(250),
OLD_NEW VARCHAR(250),
FROM_DATE DATETIME,
TO_DATE DATETIME,
BATCH_NUMBER VARCHAR(100),
STATUS VARCHAR(20),
CREATED_DATE DATETIME,
CREATED_BY VARCHAR(10),
UPDATED_DATE DATETIME,
UPDATED_BY VARCHAR(10),
PRIMARY KEY (`ID`),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
);



