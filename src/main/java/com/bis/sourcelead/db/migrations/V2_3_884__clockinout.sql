#CLOCK_INOUT_CONF

DROP TABLE IF EXISTS `CLOCK_INOUT_CONF`;
CREATE TABLE `CLOCK_INOUT_CONF` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  TRACK_EMP_LOCATION BOOLEAN,
  TRACK_TASK_ASSIGNED BOOLEAN,
  IS_JOBS_CHECKED BOOLEAN,
  IS_PROJECT_TASKS_CHECKED BOOLEAN,
  IS_GENERAL_TASKS_CHECKED BOOLEAN,
  IS_GOALS_CHECKED BOOLEAN,
  IS_OTHER_CHECKED BOOLEAN,
  CLOCK_IN_COMMENT BOOLEAN,
  BREAKS BOOLEAN,
  AUTOMATIC_CLOCKOUT BOOLEAN,
  ORG_LOCATION_ID BIGINT,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
) ;


#CLOCK_INOUT

DROP TABLE IF EXISTS `CLOCK_INOUT`;
CREATE TABLE `CLOCK_INOUT` (
ID BIGINT NOT NULL AUTO_INCREMENT,
ORG_LOCATION_ID BIGINT,
USER_ID BIGINT,
CLOCK_IN_DATE DATE,
CLOCK_OUT_DATE DATE,
CLOCK_IN_TIME TIME, #HH:MM:SS
CLOCK_OUT_TIME TIME,
TOTAL_CLOCK_TIME TIME,
JOBS_TASK_ID BIGINT,
PROJECT_ID BIGINT,
PROJECTS_TASK_ID BIGINT,
GENERAL_TASK_ID BIGINT,
COMMENTS TEXT,
CREATED_DATE DATE,
CREATED_BY BIGINT,
UPDATED_DATE DATE,
UPDATED_BY BIGINT,
PRIMARY KEY (`ID`),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
FOREIGN KEY(PROJECT_ID) REFERENCES `PROJECTS`(ID),
FOREIGN KEY(PROJECTS_TASK_ID) REFERENCES `PROJECT_TASKS`(ID),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `TASKS`(ID),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
) ;

#CLOCK_BREAK_INOUT

DROP TABLE IF EXISTS `CLOCK_BREAK_INOUT`;
CREATE TABLE `CLOCK_BREAK_INOUT` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  CLOCK_INOUT_ID BIGINT,
  BREAK_DATE DATE,
  BREAK_START_TIME TIME,
  BREAK_END_TIME TIME,
  TOTAL_BREAK_TIME TIME,
  COMMENTS TEXT,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(CLOCK_INOUT_ID) REFERENCES `CLOCK_INOUT`(ID)
) ;


