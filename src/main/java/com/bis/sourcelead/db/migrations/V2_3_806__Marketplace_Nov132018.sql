CREATE OR REPLACE VIEW CANDIDATE_MARKET_PLACE_CART_VIEW AS

SELECT 
	MARKETPLACE.ID,
    MARKETCART.SOURCE_ORG_LOCATION_ID AS SOURCE_ORG_LOCATION_ID,
    MARKETCART.TARGET_ORG_LOCATION_ID AS TARGET_ORG_LOCATION_ID,
    MARKETPLACE.CANDIDATE_ID AS CANDIDATE_ID,
    MARKETPLACE.CANDIDATE_UUID AS CANDIDATE_UUID,
    MARKETPLACE.NAME AS FULLNAME,
    MARKETPLACE.LOCATION AS LOCATION,
    MARKETPLACE.IMAGE_URL AS IMAGEURL,
    MARKETPLACE.SKILLS_NAME AS SKILLSNAME,
    MARKETPLACE.DESIGNATION AS DESIGNATION,
    MARKETPLACE.CURRENT_RATE AS CURRENT_RATE,
    MARKETPLACE.CURRENT_RATE_CURRENCY AS CURR_RATE_CUR,
    MARKETPLACE.EXPECTED_RATE AS EXPECTED_RATE,
    MARKETPLACE.EXPECTED_RATE_CURRENCY AS EXP_RATE_CUR,
    MARKETPLACE.EXPERIENCE_YEARS AS EXP_IN_YEARS,
    MARKETPLACE.EXPERIENCE_MONTHS AS EXP_IN_MONTHS,
    MARKETPLACE.MARKET_PRICE AS MARKET_PRICE,
    MARKETPLACE.MARKET_RATE_CURRENCY AS MARKET_CURRENCY,
    MARKETPLACE.PROFILE_PERCENTAGE AS PROFILE_PERCENTAGE,
    MARKETPLACE.CREATED_DATE AS CREATED_DATE,
    MARKETCART.CREATED_BY AS CREATED_BY,
    (SELECT 
            CONCAT(USER.FIRST_NAME, ' ', USER.LAST_NAME)
        FROM
            USER
        WHERE
            USER.ID = MARKETPLACE.CREATED_BY) AS CREATED_BY_NAME
FROM
    CANDIDATE_MARKET_PLACE MARKETPLACE,
    CANDIDATE_MARKET_CART MARKETCART
WHERE
    MARKETPLACE.ID = MARKETCART.MARKETPLACE_ID