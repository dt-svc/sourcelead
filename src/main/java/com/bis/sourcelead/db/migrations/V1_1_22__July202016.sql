DROP TABLE IF EXISTS `TABS`;
CREATE TABLE `TABS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  TAB_NAME VARCHAR(50) DEFAULT NULL,
  TAB_ID BIGINT,
  SUB_TAB_ORDER BIGINT,
  TAB_ORDER BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(TAB_ID) REFERENCES `TABS`(ID)
) ;



DROP TABLE IF EXISTS `TABS_ACTIONS`;
CREATE TABLE `TABS_ACTIONS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ACTION_NAME TEXT DEFAULT NULL,
  TAB_ID BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(TAB_ID) REFERENCES `TABS`(ID)
) ;


DROP TABLE IF EXISTS `ACTION_ROLES`;
CREATE TABLE `ACTION_ROLES` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ACTION_ID BIGINT,
  ROLE_ID BIGINT,
  IS_NOTIFY VARCHAR(10),
  ORG_ID BIGINT,
  ORGLOCATION_ID BIGINT,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ACTION_ID) REFERENCES `TABS_ACTIONS`(ID),
  FOREIGN KEY(ROLE_ID) REFERENCES `ROLES`(ID),
  FOREIGN KEY(ORG_ID) REFERENCES `ORG`(ID),
  FOREIGN KEY(ORGLOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
) ;





