#Holiday & Restrict Days
DROP TABLE IF EXISTS `sourcelead`.`HOLIDAY_RESTRICT_DAYS`;
CREATE TABLE `sourcelead`.`HOLIDAY_RESTRICT_DAYS` (
  ID VARCHAR(100),
  ORGLOCATION_ID BIGINT,
  HOLIDAY_ID VARCHAR(100),
  RESTRICTDAY_ID VARCHAR(100),
  DAY DATE,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`)

) ;
    ALTER TABLE `sourcelead`.`HOLIDAY_RESTRICT_DAYS` 
	ADD INDEX `SOURCELEAD_FK_HRD_1_idx` (`ORGLOCATION_ID` ASC),
	ADD INDEX `SOURCELEAD_FK_HRD_2_idx` (`HOLIDAY_ID` ASC),
	ADD INDEX `SOURCELEAD_FK_HRD_3_idx` (`RESTRICTDAY_ID` ASC);
	ALTER TABLE `sourcelead`.`HOLIDAY_RESTRICT_DAYS` 
	ADD CONSTRAINT `SOURCELEAD_FK_HRD_1`
 	FOREIGN KEY (`ORGLOCATION_ID`)
 	REFERENCES `sourcelead`.`ORG_LOCATIONS` (`ID`)
  	ON DELETE NO ACTION
  	ON UPDATE NO ACTION,
	ADD CONSTRAINT `SOURCELEAD_FK_HRD_2`
  	FOREIGN KEY (`HOLIDAY_ID`)
  	REFERENCES `sourcelead`.`HOLIDAY` (`ID`)
  	ON DELETE NO ACTION
  	ON UPDATE NO ACTION,
	ADD CONSTRAINT `SOURCELEAD_FK_HRD_3`
  	FOREIGN KEY (`RESTRICTDAY_ID`)
  	REFERENCES `sourcelead`.`RESTRICT_DAY` (`ID`)
  	ON DELETE NO ACTION
  	ON UPDATE NO ACTION;
