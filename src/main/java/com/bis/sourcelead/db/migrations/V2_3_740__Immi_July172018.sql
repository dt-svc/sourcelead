# Tables for The Labor Condition Application (LCA)
	DROP TABLE IF EXISTS `LCA`;
	CREATE TABLE `LCA` (
	  
	  ID BIGINT NOT NULL AUTO_INCREMENT,
	  ORG_LOCATION_ID BIGINT DEFAULT NULL,
	  LCA_NO varchar(25) DEFAULT NULL,
	  LCA_TITLE varchar(250) DEFAULT NULL,
	  LCA_STATUS  varchar(50) DEFAULT NULL,
	  START_DATE DATE,
	  END_DATE DATE,
	  NO_OF_POSITIONS INT(10) DEFAULT NULL,
	  WAGES_LEVEL  varchar(20) DEFAULT NULL,
	  
	  PREVAILING_WAGE varchar(100) DEFAULT NULL,
	  PRIVILING_WAGE_RATETYPE VARCHAR(20) DEFAULT NULL,
      PRIVILING_WAGE_CURRENCY VARCHAR(20) DEFAULT NULL,
      
	  EMPLOYEE varchar(250) DEFAULT NULL,
	  STATUS INT(10) DEFAULT NULL,
	  JOB_TITLE varchar(250)DEFAULT NULL,
	  SOC_CODE  varchar(50)DEFAULT NULL,
	  SOC_OCCUPATION_TITLE varchar(250)DEFAULT NULL,
	 
	  OFFERED_WAGE varchar(150)DEFAULT NULL,
	  OFFERED_WAGE_RATETYPE VARCHAR(20) DEFAULT NULL,
      OFFERED_WAGE_CURRENCY VARCHAR(20) DEFAULT NULL,
      
	  LCA_UUID VARCHAR(20) DEFAULT NULL,
	  
	  CREATED_DATE DATETIME, 
	  CREATED_BY BIGINT DEFAULT NULL, 
	  UPDATED_DATE DATETIME, 
	  UPDATED_BY BIGINT DEFAULT NULL,
	  
	  PRIMARY KEY (`ID`),
	  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID), 
	  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID),
	  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
	) ;
	
	DROP TABLE IF EXISTS `LCA_VISA_CLARIFICATIONS`;
	CREATE TABLE `LCA_VISA_CLARIFICATIONS` (
	  
	  ID BIGINT NOT NULL AUTO_INCREMENT,
	  LCA_ID BIGINT DEFAULT NULL,
	  
	  NEW_EMPLOYMENT varchar(25) DEFAULT NULL,
	  NEW_EMPLOYMENT_COUNT INT(10) DEFAULT NULL,
	  CONCURRENT_EMPLOYMENT varchar(250) DEFAULT NULL,
	  CONCURRENT_EMPLOYMENT_COUNT INT(10) DEFAULT NULL,
	  EXTENTION  varchar(50) DEFAULT NULL,
	  EXTENTION_COUNT INT(10) DEFAULT NULL,
	  CHANGE_IN_EMPLOYER  varchar(50) DEFAULT NULL,
	  CHANGE_IN_EMPLOYER_COUNT INT(10) DEFAULT NULL,
	  CHANGE_IN_PREVIOUS_APPROVED_EMPLOYMENT  varchar(50) DEFAULT NULL,
	  CHANGE_IN_PREVIOUS_APPROVED_EMPLMT_COUNT INT(10) DEFAULT NULL,
	  AMENDMENT varchar(50) DEFAULT NULL,
	  AMENDMENT_COUNT INT(10) DEFAULT NULL,
	 
	  
	  STATUS INT(10) DEFAULT NULL, 
	  
	  CREATED_DATE DATETIME, 
	  CREATED_BY BIGINT DEFAULT NULL, 
	  UPDATED_DATE DATETIME, 
	  UPDATED_BY BIGINT DEFAULT NULL, 
	  
	  PRIMARY KEY (`ID`),
	  FOREIGN KEY(LCA_ID) REFERENCES `LCA`(ID),
	  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID), 
	  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
	) ;
	
	DROP TABLE IF EXISTS `LCA_PLACE_OF_EMPLOYMENT`;
	CREATE TABLE `LCA_PLACE_OF_EMPLOYMENT` (
	  
	  ID BIGINT NOT NULL AUTO_INCREMENT,
	  LCA_ID BIGINT DEFAULT NULL,
	  LOCATION TEXT DEFAULT NULL,
	  ADDRESS_LINE1 TEXT DEFAULT NULL,
	  ADDRESS_LINE2 TEXT DEFAULT NULL,
	  COUNTRY TEXT DEFAULT NULL,
	  STATE TEXT DEFAULT NULL,
	  CITY TEXT DEFAULT NULL,
	  ZIP_CODE varchar(20) DEFAULT NULL,
	  STATUS INT(10) DEFAULT NULL, 
	  
	  CREATED_DATE DATETIME, 
	  CREATED_BY BIGINT DEFAULT NULL, 
	  UPDATED_DATE DATETIME, 
	  UPDATED_BY BIGINT DEFAULT NULL, 
	  
	  PRIMARY KEY (`ID`),
	  FOREIGN KEY(LCA_ID) REFERENCES `LCA`(ID),
	  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID), 
	  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
	) ;
	
	DROP TABLE IF EXISTS `LCA_DOCUMENT_HISTORY`;
	CREATE TABLE `LCA_DOCUMENT_HISTORY` (
	  
	  ID BIGINT NOT NULL AUTO_INCREMENT,
	  LCA_ID BIGINT DEFAULT NULL,
	  DOCUMENT_TITLE varchar(250) DEFAULT NULL,
	  FILE_URL VARCHAR(2000) DEFAULT NULL,
	  FILE_CONTENT_TYPE VARCHAR(500),
	  FILE_NAME TEXT,
	  DOCUMENT_UUID VARCHAR(20) DEFAULT NULL,
	  DESCRIPTION TEXT DEFAULT NULL,
	  STATUS INT(10) DEFAULT NULL, 
	  
	  CREATED_DATE DATETIME, 
	  CREATED_BY BIGINT DEFAULT NULL, 
	  UPDATED_DATE DATETIME, 
	  UPDATED_BY BIGINT DEFAULT NULL, 
	  
	  PRIMARY KEY (`ID`),
	  FOREIGN KEY(LCA_ID) REFERENCES `LCA`(ID),
	  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID), 
	  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
	) ;
	
