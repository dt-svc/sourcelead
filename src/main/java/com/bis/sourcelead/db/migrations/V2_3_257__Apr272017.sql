DROP TABLE IF EXISTS `sourcelead`.`INVOICE`;
CREATE TABLE `sourcelead`.`INVOICE` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  CLIENT_ORG_RELATION_ID BIGINT,
  CLIENT_CONTACT_USER_ID BIGINT,
  ORG_LOCATION_ID BIGINT,
  INVOICE_ID varchar(50),
  INVOICE_DATE DATE,
  DUE_DATE DATE,
  BILLING_ADDRESS TEXT DEFAULT NULL,
  DISCOUNT_AMOUNT varchar(100),
  SUB_TOTAL varchar(100),
  TOTAL varchar(100),
  DUE_AMOUNT varchar(100),
  INVOICE_COMMENT  TEXT DEFAULT NULL,
  STATUS VARCHAR(100),
  INVOICE_STATUS VARCHAR(50),
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(100),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(100),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(CLIENT_ORG_RELATION_ID) REFERENCES `sourcelead`.`ORG_RELATIONS`(ID),
  FOREIGN KEY(CLIENT_CONTACT_USER_ID) REFERENCES `sourcelead`.`USER`(ID),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `sourcelead`.`ORG_LOCATIONS`(ID)
);


DROP TABLE IF EXISTS `sourcelead`.`INVOICE_LINE_ITEMS`;
CREATE TABLE `sourcelead`.`INVOICE_LINE_ITEMS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  START_DATE DATE,
  END_DATE DATE,
  CANDIDATE_ID BIGINT,
  CONTRACT_ID BIGINT,
  INVOICE_ID BIGINT,
  ORG_LOCATION_ID BIGINT,
  RATE varchar(100),
  TOTAL_HOURS varchar(100),
  EXPENSES varchar(100),
  SEPERATE_INVOCE varchar(50),
  AMOUNT varchar(100),
  STATUS VARCHAR(100),
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(100),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(100),
  PRIMARY KEY (`ID`),
 FOREIGN KEY(CANDIDATE_ID) REFERENCES `sourcelead`.`CANDIDATE`(ID),
 FOREIGN KEY(CONTRACT_ID) REFERENCES `sourcelead`.`CONTRACTS`(ID),
 FOREIGN KEY(INVOICE_ID) REFERENCES `sourcelead`.`INVOICE`(ID),
 FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `sourcelead`.`ORG_LOCATIONS`(ID)
);



