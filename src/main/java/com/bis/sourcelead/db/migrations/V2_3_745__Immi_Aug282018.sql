CREATE OR REPLACE VIEW LCA_LIST_EXPORT_VIEW AS
SELECT 
    TEMP.ID,
    TEMP.ORG_LOCATION_ID,
    TEMP.LCA_NO,
    TEMP.LCA_TITLE,
    TEMP.START_DATE,
    TEMP.END_DATE,
    TEMP.PRIVILING_WAGE_CURRENCY,
    TEMP.PREVAILING_WAGE,
    TEMP.PRIVILING_WAGE_RATETYPE,
    TEMP.WAGES_LEVEL,
    TEMP.SOC_CODE,
    TEMP.SOC_OCCUPATION_TITLE,
    TEMP.NO_OF_POSITIONS,
    TEMP.JOB_TITLE,
    TEMP.LCA_STATUS,
    IF(TEMP.STATUS=1, "Active", "In-Active") AS STATUS,
     GROUP_CONCAT(LCAEMPT.LOCATION SEPARATOR '\n') AS LOCATION
FROM
    `LCA` TEMP
        LEFT JOIN
    `LCA_PLACE_OF_EMPLOYMENT` LCAEMPT ON LCAEMPT.LCA_ID = TEMP.ID

GROUP BY TEMP.ID
ORDER BY TEMP.UPDATED_DATE DESC;