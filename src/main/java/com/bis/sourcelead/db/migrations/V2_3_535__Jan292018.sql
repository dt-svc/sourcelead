DROP TABLE IF EXISTS `MONTHLY_LEAVES`;
CREATE TABLE `MONTHLY_LEAVES` (
  ID VARCHAR(100),
  LEAVE_ID VARCHAR(100),
  JANUARY_LEAVES INTEGER,
  FEBRUARY_LEAVES INTEGER,
  MARCH_LEAVES INTEGER,
  APRIL_LEAVES INTEGER,
  MAY_LEAVES INTEGER,
  JUNE_LEAVES INTEGER,
  JULY_LEAVES INTEGER,
  AUGUST_LEAVES INTEGER,
  SEPTEMBER_LEAVES INTEGER,
  OCTOBER_LEAVES INTEGER,
  NOVEMBER_LEAVES INTEGER,
  DECEMBER_LEAVES INTEGER,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(LEAVE_ID) REFERENCES `USER_LEAVE`(ID)
) ;
