  ORG_LOCATION_ID BIGINT DEFAULT NULL,
  MSP_VENDOR_ORG_LOCATION_ID BIGINT DEFAULT NULL,
  MSP_RELATION_ID BIGINT DEFAULT NULL,
  ORG_RELATION_IDS TEXT,
  MSP_ORG_RELATION_IDS TEXT,
  STATUS INT,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
