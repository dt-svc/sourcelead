DROP TABLE IF EXISTS `USER_PYAROLL`;
CREATE TABLE `USER_PYAROLL` (
ID BIGINT NOT NULL AUTO_INCREMENT,      
EMP_ID VARCHAR(250),
EMPLOYEE_NAME VARCHAR(250),
ORG_LOCATION_ID BIGINT DEFAULT NULL,
USER_ID BIGINT DEFAULT NULL,
PAYROLL_START_DATE DATE,
PAYROLL_END_DATE DATE,
TOTAL_HOURS VARCHAR(250),
HALF_HOURS VARCHAR(250),       
PAY_RATE VARCHAR(250),       
AMOUNT VARCHAR(250),       
PRE_DEDUCTINS VARCHAR(250),   
FINAL_AMOUNT VARCHAR(250),        
POST_DEDUCTIONS VARCHAR(250),              
REIMBURSEMENT VARCHAR(250), 
COMMENTS TEXT DEFAULT NULL,        
STATUS VARCHAR(50),
CREATED_DATE DATETIME,
CREATED_BY VARCHAR(10),
UPDATED_DATE DATETIME,
UPDATED_BY VARCHAR(10),
PRIMARY KEY (`ID`),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
FOREIGN KEY(USER_ID) REFERENCES `USER`(ID)
);

