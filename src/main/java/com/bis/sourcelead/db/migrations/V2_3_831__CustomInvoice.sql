DROP TABLE IF EXISTS `CUSTOM_INVOICE_TEMPLATE`;
CREATE TABLE `CUSTOM_INVOICE_TEMPLATE` (
	ID BIGINT NOT NULL AUTO_INCREMENT,
	UUID VARCHAR(20),
	NAME VARCHAR(100),
	DESCRIPTION VARCHAR(1000),
    ITEMS VARCHAR(10000),
    STATUS INT,
    ORG_RELATION_ID BIGINT DEFAULT NULL,
    ORG_LOCATION_ID BIGINT DEFAULT NULL,
    CREATED_DATE DATETIME,
 	CREATED_BY BIGINT DEFAULT NULL,
  	UPDATED_DATE DATETIME,
  	UPDATED_BY BIGINT DEFAULT NULL,
	PRIMARY KEY (`ID`),
	FOREIGN KEY (CREATED_BY) REFERENCES `USER`(ID),
	FOREIGN KEY (UPDATED_BY) REFERENCES `USER`(ID),
    FOREIGN KEY (ORG_RELATION_ID) REFERENCES `ORG_RELATIONS`(ID),
    FOREIGN KEY (ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
);