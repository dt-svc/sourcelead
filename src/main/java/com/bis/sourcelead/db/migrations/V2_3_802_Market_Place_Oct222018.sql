# CREATED BY SRINIVAS SABBU ON OCT 23 2018 FOR CANDIDATE MARKET CART.

DROP TABLE IF EXISTS `CANDIDATE_MARKET_CART`; 
CREATE TABLE `CANDIDATE_MARKET_CART` ( 
ID BIGINT NOT NULL AUTO_INCREMENT,
MARKETPLACE_ID BIGINT DEFAULT NULL,
MARKETPLACE_UUID VARCHAR(50) DEFAULT NULL,
CANDIDATE_ID BIGINT DEFAULT NULL,
MASTER_CANDIDATE_ID BIGINT DEFAULT NULL,
CANDIDATE_UUID VARCHAR(20) DEFAULT NULL,
UUID VARCHAR(50) DEFAULT NULL,
ORG_LOCATION_ID BIGINT,
STATUS INT(10) DEFAULT NULL, 
CREATED_DATE DATETIME, 
CREATED_BY BIGINT DEFAULT NULL, 
UPDATED_DATE DATETIME, 
UPDATED_BY BIGINT DEFAULT NULL, 
PRIMARY KEY (`ID`),
FOREIGN KEY(MARKETPLACE_ID) REFERENCES `CANDIDATE_MARKET_PLACE`(ID),
FOREIGN KEY(CANDIDATE_ID) REFERENCES `CANDIDATE`(ID), 
FOREIGN KEY(MASTER_CANDIDATE_ID) REFERENCES `MASTER_CANDIDATE`(ID),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID), 
FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
);