DROP TABLE IF EXISTS `sourcelead`.`REQUIREMENT_INTERVIEW`;
CREATE TABLE `sourcelead`.`REQUIREMENT_INTERVIEW` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  SUBMISSION_ID BIGINT DEFAULT NULL,
  INTERVIEW_TYPE VARCHAR(50),
  START_TIME VARCHAR(10),
  END_TIME VARCHAR(10),
  COUNTRY VARCHAR(50) DEFAULT NULL,
  STATE VARCHAR(50) DEFAULT NULL,
  CITY VARCHAR(50) DEFAULT NULL,
  NOTIFICATION_TO_APPLICANT VARCHAR(10),
  NOTIFICATION_TO_SPOC VARCHAR(10),
  REMAINED_BEFORE VARCHAR(20),
  STATUS INT,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(SUBMISSION_ID) REFERENCES `sourcelead`.`REQUIREMENT_SUBMISSION`(ID)
);	


DROP TABLE IF EXISTS `sourcelead`.`REQUIREMENT_INTERVIEWER`;
CREATE TABLE `sourcelead`.`REQUIREMENT_INTERVIEWER` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  INTERVIEW_ID BIGINT DEFAULT NULL,
  INTERVIEWER_USER_ID BIGINT DEFAULT NULL,
  STATUS INT,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(INTERVIEW_ID) REFERENCES `sourcelead`.`REQUIREMENT_INTERVIEW`(ID),
  FOREIGN KEY(INTERVIEWER_USER_ID) REFERENCES `sourcelead`.`USER`(ID)
);	


DROP TABLE IF EXISTS `sourcelead`.`INTERVIEW_REMAINDER`;
CREATE TABLE `sourcelead`.`INTERVIEW_REMAINDER` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  INTERVIEW_ID BIGINT DEFAULT NULL,
  NOTIFIED_TO BIGINT DEFAULT NULL,
  NOTIFIED_TO_OTHERS TEXT DEFAULT NULL,
  STATUS INT,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(INTERVIEW_ID) REFERENCES `sourcelead`.`REQUIREMENT_INTERVIEW`(ID),
  FOREIGN KEY(NOTIFIED_TO) REFERENCES `sourcelead`.`USER`(ID)
);	

