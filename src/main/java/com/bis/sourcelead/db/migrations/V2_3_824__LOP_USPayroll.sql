# Table PAYROLL_LOP_HIS
DROP TABLE IF EXISTS `PAYROLL_LOP_HIS`;
CREATE TABLE `PAYROLL_LOP_HIS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  PAYROLL_ID BIGINT,
  LEAVE_TYPE_ID BIGINT,
  LEAVE_TYPE_NAME VARCHAR(100),
  TOTAL_BALANCE_LEAVES  FLOAT(20,3),
  TOTAL_APPLIED_LEAVES  FLOAT(20,3),
  LOP_LEAVES FLOAT(20,3),
  LOP_AMOUNT DECIMAL(20,3),
  PAYROLL_START_DATE DATE,
  PAYROLL_END_DATE DATE,
  PAYROLL_LOP_HIS_UUID VARCHAR(20),
  LOP_EXEMPT VARCHAR(20),
  STATUS INT,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(PAYROLL_ID) REFERENCES `US_EMP_PAYROLL`(ID),
  FOREIGN KEY(LEAVE_TYPE_ID) REFERENCES `LEAVE_TYPE`(ID)
) ;
CALL AlterTableAddColumn ('US_EMP_PAYROLL','LOP_AMOUNT','DECIMAL(20,3)  DEFAULT NULL AFTER `EXPENSES_AMOUNT`');
CALL AlterTableAddColumn ('PAY_ADJUSTMENT_HISTORY','PRE_LOP_AMOUNT','DECIMAL(20,3)  DEFAULT NULL AFTER `OVERTIME_HOURS_AMOUNT`');
CALL AlterTableAddColumn ('PAY_ADJUSTMENT_HISTORY','LOP_AMOUNT','DECIMAL(20,3)  DEFAULT NULL AFTER `PRE_LOP_AMOUNT`');

