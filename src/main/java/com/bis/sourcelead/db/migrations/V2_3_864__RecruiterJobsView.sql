CREATE OR REPLACE VIEW RECRUITER_JOBS_REPORT_VIEW AS 
SELECT 
MAX(RSH.ID) AS RSH_ID, 
DATE_FORMAT(RSH.CREATED_DATE ,"%Y-%m-%d") AS CREATED_DATE, 
RSH.MASTER_USER_CODE AS USER_CODE, 
SUM(CASE 
WHEN UPPER(RSH.TO_STAGE) = 'SUBMISSION' AND (UPPER(RSH.FROM_STAGE) = 'NEW' || UPPER(RSH.FROM_STAGE) = 'request_sent') THEN 1 
ELSE 0 
END) AS APPLICANT_SUBMISSION_COUNT, 
SUM(CASE 
WHEN UPPER(RSH.TO_STAGE) = 'SHORTLIST' THEN 1 
ELSE 0 
END) AS APPLICANT_SHORTLISTED_COUNT, 
SUM(CASE 
WHEN UPPER(RSH.TO_STAGE) = 'SUBMIT_TO_CLIENT' THEN 1 
ELSE 0 
END) AS APPLICANT_SUBMIT_TO_CLIENT_COUNT, 
SUM(CASE 
WHEN UPPER(RSH.TO_STAGE) = 'INTERVIEW' THEN 1 
ELSE 0 
END) AS APPLICANT_INTERVIEW_COUNT, 
SUM(CASE 
WHEN UPPER(RSH.TO_STAGE) = 'OFFERMADE' THEN 1 
ELSE 0 
END) AS APPLICANT_OFFERMADE_COUNT, 
SUM(CASE 
WHEN UPPER(RSH.TO_STAGE) = 'REJECTED' THEN 1 
ELSE 0 
END) AS APPLICANT_REJECTED_COUNT, 
SUM(CASE 
WHEN UPPER(RSH.TO_STAGE) = 'BACKOUT' THEN 1 
ELSE 0 
END) AS APPLICANT_BACKOUT_COUNT, 
SUM(CASE 
WHEN UPPER(RSH.TO_STAGE) = 'JOINED' THEN 1 
ELSE 0 
END) AS APPLICANT_JOINED_COUNT, 
SUM(CASE 
WHEN UPPER(RSH.TO_STAGE) = 'ONHOLD' THEN 1 
ELSE 0 
END) AS APPLICANT_ONHOLD_COUNT, 
SUM(CASE 
WHEN UPPER(RSH.TO_STAGE) = 'NORESPONSE' THEN 1 
ELSE 0 
END) AS APPLICANT_NORESPONSECOUNT_COUNT, 
(SELECT RS.ORG_LOCATION_ID 
FROM 
REQUIREMENT_SUBMISSION RS 
WHERE RS.ID =RSH.REQUIREMENT_SUBMISSION_ID) AS ORG_LOCATION_ID, 
(SELECT R.ID 
FROM REQUIREMENT R 
WHERE R.ID=(SELECT RS.REQUIREMENT_ID FROM REQUIREMENT_SUBMISSION RS WHERE RS.ID = RSH.REQUIREMENT_SUBMISSION_ID)) AS REQUIREMENT_ID 
FROM 
REQUIREMENT_SUBMISSION_HISTORY RSH 
GROUP BY RSH.ID, 
DATE_FORMAT(RSH.CREATED_DATE ,"%Y-%m-%d"); 