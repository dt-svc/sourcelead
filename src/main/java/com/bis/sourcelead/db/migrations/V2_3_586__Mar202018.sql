DROP TABLE IF EXISTS `sourcelead`.`EMPLOYEE_VERIFICATION_TEMPLATE`;
CREATE TABLE `sourcelead`.`EMPLOYEE_VERIFICATION_TEMPLATE` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  TEMPLATE_NAME varchar(100),
  ORGLOCATION_ID BIGINT,
  SIGNATORY BIGINT,
  LETTER_HEAD varchar(250),
  DESCRIPTION TEXT DEFAULT NULL,
  TEMPLATE_CONTENT TEXT DEFAULT NULL,
  TEMPLATE_UUID varchar(100),
  TEMPLATE_STATUS VARCHAR(50),
  FILE_NAME VARCHAR(150), 
  FILE_TYPE VARCHAR(150), 
  FILE_URL VARCHAR(250), 
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(50),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(50),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORGLOCATION_ID) REFERENCES `sourcelead`.`ORG_LOCATIONS`(ID),
  FOREIGN KEY(SIGNATORY) REFERENCES `sourcelead`.`USER`(ID)
) ;