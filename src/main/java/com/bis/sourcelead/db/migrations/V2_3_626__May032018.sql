DROP TABLE IF EXISTS `LETTER_HEAD`;
CREATE TABLE `LETTER_HEAD` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  LETTERHEAD_NAME varchar(100),
  LETTERHEAD_DESCRIPTION TEXT DEFAULT NULL,
  ORGLOCATION_ID BIGINT,
  LETTERHEAD_UUID varchar(100),
  TEMPLATE_BACKGROUND_COLOR varchar(100),
  TEMPLATE_TYPE varchar(100),
  PADDING_LEFT VARCHAR(50),
  PADDING_RIGHT VARCHAR(50),
  PADDING_TOP VARCHAR(50),
  PADDING_BOTTOM VARCHAR(50),
  ALIGN_LOGO varchar(100),
  HEADER_BACKGROUND_COLOR VARCHAR(100),
  HEADER_TEXT TEXT DEFAULT NULL,
  FOOTER_TEXT TEXT DEFAULT NULL,
  ALIGN_HEADER_TEXT VARCHAR(100),
  ALIGN_FOOTER_TEXT VARCHAR(100),
  FOOTER_BACKGROUND_COLOR VARCHAR(100),
  FILE_NAME VARCHAR(150),
  FILE_TYPE VARCHAR(150),
  FILE_URL VARCHAR(150),
  STATUS VARCHAR(50),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORGLOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
) ;

DROP TABLE IF EXISTS `EMPLOYEE_VERIFICATION_TEMPLATE`;
CREATE TABLE `EMPLOYEE_VERIFICATION_TEMPLATE` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  TEMPLATE_NAME varchar(100),
  ORGLOCATION_ID BIGINT,
  SIGNATORY BIGINT,
  TEMPLATE_STYLE varchar(100),
  LETTER_HEAD_ID BIGINT,
  DESCRIPTION TEXT DEFAULT NULL,
  TEMPLATE_CONTENT TEXT DEFAULT NULL,
  TEMPLATE_UUID varchar(100),
  TEMPLATE_STATUS VARCHAR(50),
  FILE_NAME VARCHAR(150), 
  FILE_TYPE VARCHAR(150), 
  FILE_URL VARCHAR(250), 
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(50),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(50),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORGLOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(LETTER_HEAD_ID) REFERENCES `LETTER_HEAD`(ID),
  FOREIGN KEY(SIGNATORY) REFERENCES `USER`(ID)
) ;
