DROP TABLE IF EXISTS `MOBILE_DEVICE_TOKEN_INFORMATION`;
CREATE TABLE `MOBILE_DEVICE_TOKEN_INFORMATION` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  USER_ID BIGINT,
  DEVICE_TOKEN VARCHAR(500),
  DEVICE_TYPE VARCHAR(100),
  DEVICE_STATUS INT,
  DEVICE_UUID VARCHAR(50),
  CREATED_DATE DATETIME,
  CREATED_BY VARCHAR(50),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(USER_ID) REFERENCES `USER`(ID)
) ;
 

DROP TABLE IF EXISTS `MOBILE_PUSH_NOTIFICATION`;
CREATE TABLE `MOBILE_PUSH_NOTIFICATION`(
ID BIGINT NOT NULL AUTO_INCREMENT,
USER_ID BIGINT,
DEVICE_ID BIGINT,
NOTIFICATION_DESCRPTION LONGTEXT,
NOTIFICATION_STATUS INT,
CREATED_DATE DATETIME,
CREATED_BY BIGINT DEFAULT NULL,
PRIMARY KEY (`ID`),
FOREIGN KEY (USER_ID) REFERENCES `USER`(ID),
FOREIGN KEY (DEVICE_ID) REFERENCES `MOBILE_DEVICE_TOKEN_INFORMATION`(ID)
);

 