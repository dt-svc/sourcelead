#ASSET_SERVICE
DROP TABLE IF EXISTS `ASSET_SERVICE`;
CREATE TABLE `ASSET_SERVICE` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ASSET_ID BIGINT,
  SERVICE_DATE DATE,
  RECEIVED_DATE DATE,
  COST DECIMAL(20,2),
  DESCRIPTION VARCHAR(500),
  STATUS INT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ASSET_ID) REFERENCES `ASSET`(ID)
);
