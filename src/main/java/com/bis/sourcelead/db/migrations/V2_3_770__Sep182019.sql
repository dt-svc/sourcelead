
DROP TABLE IF EXISTS `UPLOAD_XLS_HISTORY`;
CREATE TABLE `UPLOAD_XLS_HISTORY`(
  ID BIGINT NOT NULL AUTO_INCREMENT,
  USER_ID BIGINT,
  ORG_LOCATION_ID BIGINT DEFAULT NULL,
  TOTAL_COUNT INT DEFAULT 0,
  SUCCESS_COUNT INT DEFAULT 0,
  FAILURE_COUNT INT DEFAULT 0,
  UPLOAD_ID VARCHAR(50),
  UPLOAD_ENTITY_TYPE VARCHAR(50),
  FILE_NAME LONGTEXT,
  FILE_URL LONGTEXT,
  FILE_CONTENT_TYPE LONGTEXT,
  UPLOAD_STATUS VARCHAR(50)  DEFAULT 'SUCCESS',
  UUID VARCHAR(20),
  SESSION_ID VARCHAR(100),
  UPLOAD_PROCESSING_STATUS VARCHAR(50),
  STATUS INT,
  CREATED_DATE DATETIME,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(USER_ID) REFERENCES `USER`(ID)
);
