DROP TABLE IF EXISTS `sourcelead`.`ORG_DOCUMENTS`;
CREATE TABLE `sourcelead`.`ORG_DOCUMENTS` (
   ID BIGINT NOT NULL AUTO_INCREMENT,
   DOC_NAME varchar(100) DEFAULT NULL,
   CONTRACT_TYPE varchar(50) DEFAULT NULL, 
   FILE_NAME text DEFAULT NULL,
   DOC_FILE MEDIUMBLOB,
   FILE_TYPE varchar(50),
   SPOC_ID BIGINT DEFAULT NULL,
   OWNER_ID BIGINT DEFAULT NULL,
   RESPONDER_LOCATION_ID BIGINT DEFAULT NULL,
   ORG_LOCATION_ID BIGINT DEFAULT NULL,
   SOURCE_TYPE varchar(50) DEFAULT NULL, 
   IS_DOC_PRIVATE varchar(20),
   DESCRIPTION text,
   STATUS VARCHAR(20),
   START_DATE DATE,
   END_DATE DATE,
   CREATED_DATE DATE,
   CREATED_BY VARCHAR(10),
   UPDATED_DATE DATE,
   UPDATED_BY VARCHAR(10),
   PRIMARY KEY (`ID`),
   FOREIGN KEY(SPOC_ID) REFERENCES `sourcelead`.`USER`(ID),
   FOREIGN KEY(OWNER_ID) REFERENCES `sourcelead`.`USER`(ID),
   FOREIGN KEY(RESPONDER_LOCATION_ID) REFERENCES `sourcelead`.`ORG_RELATIONS`(ID),
   FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `sourcelead`.`ORG_LOCATIONS`(ID)
) ;