CREATE OR REPLACE VIEW IMMIGRATON_TEMPLATE_VIEW AS 
SELECT 
       TEMP.ID,
     TEMP.NAME,
     TEMP.DESCRIPTION,
     TEMP.STATUS,
     (select COUNT(DOCS.ID) from `SOURCELEAD`.`IMMIGRATION_TEMPLATE_DOCUMENTS` DOCS where TEMP.ID = DOCS.IMMIGRATION_TEMPLATE_ID) as docscount,
     (select COUNT(FORM.ID) from `SOURCELEAD`.`IMMIGRATION_TEMPLATE_FORMS` FORM where TEMP.ID = FORM.IMMIGRATION_TEMPLATE_ID) as formCount,
    (select count(TASK.ID) from `SOURCELEAD`.`IMMIGRATION_TEMPLATE_TASKS` TASK where TEMP.ID = TASK.IMMIGRATION_TEMPLATE_ID) as taskCount
    FROM `SOURCELEAD`.`IMMIGRATION_TEMPLATE` TEMP