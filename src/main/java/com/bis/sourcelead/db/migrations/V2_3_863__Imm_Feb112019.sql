
DROP TABLE IF EXISTS `CANDIDATE_PASSPORT`; 
CREATE TABLE `CANDIDATE_PASSPORT` ( 
ID BIGINT NOT NULL AUTO_INCREMENT, 
CANDIDATE_ID BIGINT DEFAULT NULL,
PASSPORT_NUMBER  VARCHAR(100) DEFAULT NULL,
COUNTRY VARCHAR(100),
VALID_FROM_DATE DATE,
VALID_TO_DATE DATE,
STATUS INT(10) DEFAULT NULL, 
CREATED_DATE DATETIME, 
CREATED_BY BIGINT DEFAULT NULL, 
UPDATED_DATE DATETIME, 
UPDATED_BY BIGINT DEFAULT NULL, 
PRIMARY KEY (`ID`), 
FOREIGN KEY(CANDIDATE_ID) REFERENCES `CANDIDATE`(ID),
FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID), 
FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
);

DROP TABLE IF EXISTS `CANDIDATE_VISA`; 
CREATE TABLE `CANDIDATE_VISA` ( 
ID BIGINT NOT NULL AUTO_INCREMENT, 
CANDIDATE_ID BIGINT DEFAULT NULL,
VISA_NUMBER  VARCHAR(100) DEFAULT NULL,
VISA_TYPE  VARCHAR(100),
COUNTRY VARCHAR(100),
VALID_FROM_DATE DATE,
VALID_TO_DATE DATE,
STATUS INT(10) DEFAULT NULL, 
CREATED_DATE DATETIME, 
CREATED_BY BIGINT DEFAULT NULL, 
UPDATED_DATE DATETIME, 
UPDATED_BY BIGINT DEFAULT NULL, 
PRIMARY KEY (`ID`), 
FOREIGN KEY(CANDIDATE_ID) REFERENCES `CANDIDATE`(ID),
FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID), 
FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
);

DROP TABLE IF EXISTS `CANDIDATE_VISA_HISTORY`; 
CREATE TABLE `CANDIDATE_VISA_HISTORY` ( 
ID BIGINT NOT NULL AUTO_INCREMENT, 
VISA_ID BIGINT NOT NULL,
IS_CURRENT VARCHAR(10),
VALID_FROM_DATE DATE,
VALID_TO_DATE DATE,
STATUS INT(10) DEFAULT NULL, 
CREATED_DATE DATETIME, 
CREATED_BY BIGINT DEFAULT NULL, 
UPDATED_DATE DATETIME, 
UPDATED_BY BIGINT DEFAULT NULL, 
PRIMARY KEY (`ID`), 
FOREIGN KEY(VISA_ID) REFERENCES `CANDIDATE_VISA`(ID),
FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID), 
FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
);
