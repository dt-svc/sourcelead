CALL AlterTableAddColumn ('LCA','AVAILABLE_POSITIONS','INT(10) NULL AFTER `NO_OF_POSITIONS`');

CREATE OR REPLACE VIEW LCA_REPORT_VIEW AS
SELECT 
        TEMP.ID,
        TEMP.ORG_LOCATION_ID,
        TEMP.LCA_NO,
        TEMP.LCA_TITLE,
        TEMP.NO_OF_POSITIONS,
        TEMP.AVAILABLE_POSITIONS,
        TEMP.SOC_CODE,
        TEMP.SOC_OCCUPATION_TITLE,
        TEMP.JOB_TITLE,
        TEMP.WAGES_LEVEL,
        TEMP.PRIVILING_WAGE_CURRENCY,
        TEMP.PREVAILING_WAGE,
        TEMP.PRIVILING_WAGE_RATETYPE,
        TEMP.START_DATE,
        TEMP.END_DATE,
        TEMP.LCA_STATUS,
        TEMP.CREATED_DATE,
        TEMP.STATUS,
		TEMP.LCA_UUID,
        GROUP_CONCAT(LCAEMPT.LOCATION SEPARATOR '\n') AS LOCATION
        
    FROM
         `LCA` TEMP,
         `LCA_PLACE_OF_EMPLOYMENT` LCAEMPT
         WHERE  LCAEMPT.LCA_ID = TEMP.ID
         
         GROUP BY TEMP.ID
         
         ORDER BY TEMP.UPDATED_DATE DESC;
