DROP TABLE IF EXISTS `BGC_STATUS`;
DROP TABLE IF EXISTS `BGC_COMPONENT`;
DROP TABLE IF EXISTS `BGC_TEMPLATE`;
DROP TABLE IF EXISTS `BGC_COMPONENT_JSONMAP`;


DROP TABLE IF EXISTS `BGC_STATUS`;
CREATE TABLE `BGC_STATUS`(
	`ID` BIGINT NOT NULL AUTO_INCREMENT, 
	`ORG_LOCATION_ID` BIGINT,
	`STATUS_NAME` VARCHAR(100) DEFAULT NULL,
	`COLOR` VARCHAR(50)DEFAULT NULL,
	`DESCRIPTION` TEXT DEFAULT NULL,
	`CREATED_DATE` DATE,
	`CREATED_BY` BIGINT,
	`UPDATED_DATE` DATE,
	`UPDATED_BY` BIGINT,
	 PRIMARY KEY (`ID`),
	 FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
	 FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
	 FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
);
DROP TABLE IF EXISTS `BGC_COMPONENT`;
CREATE TABLE `BGC_COMPONENT`(
	`ID` BIGINT NOT NULL AUTO_INCREMENT, 
	`ORG_LOCATION_ID` BIGINT,
	`NAME`VARCHAR(100) DEFAULT NULL,
	`DESCRIPTION` TEXT DEFAULT NULL,
	`JSON_STRING` TEXT DEFAULT NULL,
	`CONFIGURE_TYPE`VARCHAR(100) DEFAULT NULL,
	`CREATED_DATE` DATE,
	`CREATED_BY` BIGINT,
	`UPDATED_DATE` DATE,
	`UPDATED_BY` BIGINT,
	 PRIMARY KEY (`ID`),
	 FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
	 FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
	 FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
);
DROP TABLE IF EXISTS `BGC_TEMPLATE`;
CREATE TABLE `BGC_TEMPLATE`(
	`ID` BIGINT  NOT NULL AUTO_INCREMENT, 
	`ORG_LOCATION_ID` BIGINT,
	`NAME`VARCHAR(50) DEFAULT NULL,
	`UUID` VARCHAR(20) DEFAULT NULL,
	`BGC_STATUS_STRING` VARCHAR(250) DEFAULT NULL,
	`BGC_COMPONENT_STRING` VARCHAR(250) DEFAULT NULL,
	`DESCRIPTION` TEXT DEFAULT NULL,
	`CONFIGURE_TYPE` VARCHAR(50) DEFAULT NULL,
	`STATUS` INT,
	`CREATED_DATE` DATE,
	`CREATED_BY` BIGINT,
	`UPDATED_DATE` DATE,
	`UPDATED_BY` BIGINT,
	 PRIMARY KEY (`ID`),
	 FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
	 FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
	 FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
);

DROP TABLE IF EXISTS `BGC_COMPONENT_JSONMAP`;
CREATE TABLE `BGC_COMPONENT_JSONMAP`(
	`ID` BIGINT NOT NULL AUTO_INCREMENT, 
	`TEMPLATE_ID` BIGINT,
	`SENT_TO` VARCHAR(100) DEFAULT NULL,
	`FORM_ID` VARCHAR(100) DEFAULT NULL,
	`JSON_STRING` TEXT DEFAULT NULL,
	`UPDATED_DATE` DATE,
	 PRIMARY KEY (`ID`),
	 FOREIGN KEY(TEMPLATE_ID) REFERENCES `BGC_TEMPLATE`(ID)	
);

