#CUSTOM_REPORTS_CONFIURATION
DROP TABLE IF EXISTS `CUSTOM_REPORTS_CONFIGURATION`;
CREATE TABLE `CUSTOM_REPORTS_CONFIGURATION` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  DASHBOARD_CONFI_ID BIGINT,
  REPORT_NAME VARCHAR(250),
  STATUS int,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(DASHBOARD_CONFI_ID) REFERENCES `DASHBOARD_CONFIGURATION`(ID)
) ;