#CUSTOM_REPORTS_CONFIURATION
DROP TABLE IF EXISTS `CUSTOM_REPORTS_CONFIGURATION`;
CREATE TABLE `CUSTOM_REPORTS_CONFIGURATION` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  DASHBOARD_CONFI_ID BIGINT,
  REPORT_NAME VARCHAR(250),
  STATUS int,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(DASHBOARD_CONFI_ID) REFERENCES `DASHBOARD_CONFIGURATION`(ID)
) ;


ALTER TABLE DASHBOARD_CONFIGURATION ADD COLUMN MAKE_DEFAULT BOOLEAN DEFAULT FALSE;

DROP TABLE IF EXISTS `ENABLE_DASHBOARD_CONFIGURATION`;
CREATE TABLE `ENABLE_DASHBOARD_CONFIGURATION` (
ID BIGINT NOT NULL AUTO_INCREMENT,
ORG_LOCATION_ID BIGINT,
ENABLE_DASHBOARD_CONF_UUID VARCHAR(45),
IS_ENABLE BOOLEAN,
STATUS int,
CREATED_DATE DATE,
CREATED_BY BIGINT,
UPDATED_DATE DATE,
UPDATED_BY BIGINT,
PRIMARY KEY (`ID`),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
) ;