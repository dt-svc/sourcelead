#ASSOCIATE_NOMINEE  
DROP TABLE IF EXISTS `ASSOCIATE_NOMINEE`;
CREATE TABLE `ASSOCIATE_NOMINEE` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_LOCATION_ID BIGINT,
  CANDIDATE_ID  BIGINT,
  NAME varchar(45),
  DATE_OF_BIRTH DATE,
  GENDER varchar(45),
  BLOOD_GROUP varchar(45),
  RELATION varchar(45),
  NOMINATION_FOR varchar(45),
  NOMINATION_PERCENTAGE int,
  ADDRESS TEXT NULL,
  ILLNESS_GUARDIAN_NAME varchar(45),
  ILLNESS_GUARDIAN_RELATION_NAME varchar(45),
  ILLNESS_GUARDIAN_ADDRESS TEXT NULL,
  ILLNESS_GUARDIAN_PHONE_NUMBER varchar(45),
  ILLNESS_GUARDIAN_EMAIL varchar(45),
  MINOR_GUARDIAN_NAME varchar(45),
  MINOR_GUARDIAN_RELATION_NAME varchar(45),
  MINOR_GUARDIAN_ADDRESS TEXT NULL,
  MINOR_GUARDIAN_PHONE_NUMBER varchar(45),
  MINOR_GUARDIAN_EMAIL varchar(45),
  STATUS int,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(CANDIDATE_ID) REFERENCES `CANDIDATE`(ID)
) ;