#APPLIED_LEAVE_DATE_VIEW
CREATE OR REPLACE VIEW APPLIED_LEAVE_DATE_VIEW AS
SELECT uLeave.USER_ID,
uLeave.ORGLOCATION_ID,
uLeave.LEAVE_TYPE_ID,
uLeave.STATUS as LEAVE_STATUS,
uLeave.REASON AS REASON,
aLeaveDate.APPLY_LEAVE_DATE,
aLeaveDate.APPLY_MONTH_NAME,
aLeaveDate.IS_PAYROLL_INCLUDE,
aLeaveDate.STATUS
FROM USER_LEAVE uLeave,APPLIED_LEAVE_DATE aLeaveDate
where uLeave.ID = aLeaveDate.LEAVE_ID;

DROP PROCEDURE IF EXISTS updateAssociateBalLeave;
DELIMITER //
CREATE PROCEDURE updateAssociateBalLeave(
totalLeaves varchar(20),
locationID BIGINT,
userID BIGINT,
leaveTypeID BIGINT
)
BEGIN
UPDATE ASSOCIATE_BALANCE_LEAVES
SET TOTAL_LEAVES = totalLeaves
WHERE ORG_LOCATION_ID = locationID and USER_ID = userID and LEAVE_TYPE_ID = leaveTypeID;
END//
DELIMITER ;



#LEAVE_CF_HISTORY

DROP TABLE IF EXISTS `LEAVE_CF_HISTORY`;
CREATE TABLE `LEAVE_CF_HISTORY` (
ID BIGINT NOT NULL AUTO_INCREMENT,
LEAVE_TYPE_ID BIGINT,
USER_ROLE_ID BIGINT,
CF_TYPE VARCHAR(10),
MONTH_DATE DATE,
MONTH_NAME VARCHAR(10),
YEAR int,
STATUS int,
CREATED_DATE DATE,
CREATED_BY BIGINT,
UPDATED_DATE DATE,
UPDATED_BY BIGINT,
PRIMARY KEY (`ID`)
) ;



#APPLIED_LEAVE_DATE

DROP TABLE IF EXISTS `APPLIED_LEAVE_DATE`;
CREATE TABLE `APPLIED_LEAVE_DATE` (
ID BIGINT NOT NULL AUTO_INCREMENT,
LEAVE_ID BIGINT,
APPLY_LEAVE_DATE DATE,
APPLY_MONTH_NAME VARCHAR(10),
IS_PAYROLL_INCLUDE VARCHAR(10),
YEAR int,
STATUS int,
CREATED_DATE DATE,
CREATED_BY BIGINT,
UPDATED_DATE DATE,
UPDATED_BY BIGINT,
PRIMARY KEY (`ID`),
FOREIGN KEY(LEAVE_ID) REFERENCES `USER_LEAVE`(ID)
) ;

