DROP TABLE IF EXISTS `sourcelead`.`REQUIRMENT_SUBMISSION`;
CREATE TABLE `sourcelead`.`REQUIRMENT_SUBMISSION` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  REQUIRMENT_ID BIGINT DEFAULT NULL,
  CANDIDATE_ID BIGINT DEFAULT NULL,
  CANDIDATE_RESUEME_ID BIGINT DEFAULT NULL,
  ORG_LOCATION_ID BIGINT DEFAULT NULL,
  SOURCE_SUBMISSION_ID  BIGINT DEFAULT NULL,
  SUBMISSION_TEMPLATE_JSON_STRING TEXT DEFAULT NULL,
  SUBMISSION_TEMPLATE_JSON_STRING_VALUES TEXT DEFAULT NULL,
  SUBMISSION_STATUS VARCHAR(50),
  STATUS INT,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(REQUIRMENT_ID) REFERENCES REQUIREMENT(ID),
  FOREIGN KEY(CANDIDATE_ID) REFERENCES CANDIDATE(ID),
  FOREIGN KEY(SOURCE_SUBMISSION_ID) REFERENCES REQUIRMENT_SUBMISSION(ID),
  FOREIGN KEY(CANDIDATE_RESUEME_ID) REFERENCES CANDIDATE_RESUMES(ID),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES ORG_LOCATIONS(ID)
);	



DROP TABLE IF EXISTS `sourcelead`.`REQUIRMENT_SUBMISSION_TEMPLATE_FIELDS`;
CREATE TABLE `sourcelead`.`REQUIRMENT_SUBMISSION_TEMPLATE_FIELDS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  REQUIRMENT_SUBMISSION_ID BIGINT DEFAULT NULL,
  FIRST_NAME VARCHAR(200) DEFAULT NULL,
  LAST_NAME VARCHAR(100) DEFAULT NULL,
  PHONE_NUMBER VARCHAR(20) DEFAULT NULL,
  ALTERNATE_NUMBER VARCHAR(20) DEFAULT NULL,
  EMAIL_ID VARCHAR(100) DEFAULT NULL,
  COUNTRY VARCHAR(50) DEFAULT NULL,
  STATE VARCHAR(50) DEFAULT NULL,
  CITY VARCHAR(50) DEFAULT NULL,
  DOB DATE,
  CURRENT_OR_LAST_CAOMPANY  VARCHAR(200) DEFAULT NULL,
  DESIGNATION VARCHAR(100) DEFAULT NULL,
  EDUCATION VARCHAR(100) DEFAULT NULL,
  WORK_EXPERIENCE VARCHAR(100) DEFAULT NULL,
  CURRENT_CTC VARCHAR(100) DEFAULT NULL,
  EXPECTED_CTC VARCHAR(100) DEFAULT NULL,
  NOTICE_PERIOD VARCHAR(100) DEFAULT NULL,
  STATUS INT,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(REQUIRMENT_SUBMISSION_ID) REFERENCES REQUIRMENT_SUBMISSION(ID)
);	