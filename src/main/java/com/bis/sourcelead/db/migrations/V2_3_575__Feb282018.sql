
ALTER TABLE `ORGLOCATION_SIGNATORY` 
ADD COLUMN `AUTHORIZED_TYPE` VARCHAR(45) NULL DEFAULT NULL AFTER `STATUS`,
ADD COLUMN `AUTHORIZED_AMOUNT` BIGINT(50) NULL DEFAULT NULL AFTER `AUTHORIZED_TYPE`;

DROP TABLE IF EXISTS `CONTRACT_APPROVER_HIERARCHY`;
CREATE TABLE `CONTRACT_APPROVER_HIERARCHY` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  CONTRACT_ID BIGINT,
  LEVEL VARCHAR(50),
  HIERARCHY_TYPE VARCHAR(30) DEFAULT NULL,
  APPROVER_USER_ID BIGINT DEFAULT NULL,
  CONTRACT_STATUS VARCHAR(20) DEFAULT NULL,
  STATUS VARCHAR(20) DEFAULT NULL,
  REJECTED_REASON VARCHAR(500),
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`), 
  FOREIGN KEY(APPROVER_USER_ID) REFERENCES `USER`(ID),
  FOREIGN KEY(CONTRACT_ID) REFERENCES `CONTRACTS`(ID)
); 