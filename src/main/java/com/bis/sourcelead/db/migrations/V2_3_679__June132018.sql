CREATE OR REPLACE VIEW SUBMISSION_REQUIREMENT_LIST_VIEW AS
SELECT
REQ.ID AS REQ_ID,
REQ.GENERATED_ID AS GENERATED_ID,
REQ.JOB_TITLE AS JOB_TITLE,
DATE_FORMAT(REQ.CREATED_DATE ,"%Y-%m-%d") AS CREATED_DATE,
REQ.REQUIREMENT_SUBMISSION_STATUS AS STATUS,
REQ.SKILLS AS SKILLS,
REQ.NOTICEPERIOD AS NOTICE_PERIOD,
REQ.ORG_RELATION_ID AS ORG_RELATION_ID,
REQ.CREATED_BY AS USER_ID,
REQ.ORG_LOCATION_ID AS ORG_LOCATION_ID,
OL.ORG_ID AS ORG_ID,     
GROUP_CONCAT(DISTINCT RL.CITY
              SEPARATOR ',') AS CITY,
 
GROUP_CONCAT(DISTINCT RL.LOCATION
              SEPARATOR '|') AS LOCATION          
    
FROM
    REQUIREMENT REQ ,
    REQUIREMENT_LOCATIONS RL,
    ORG_LOCATIONS OL
WHERE REQ.ID= RL.REQUIREMENT_ID
AND  REQ.ORG_LOCATION_ID = OL.ID

GROUP BY  REQ.ID, 
DATE_FORMAT(REQ.CREATED_DATE ,"%Y-%m-%d");