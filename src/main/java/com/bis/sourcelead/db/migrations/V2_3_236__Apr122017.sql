DROP TABLE IF EXISTS `BULK_CLIENT_DETAILS`;
CREATE TABLE `BULK_CLIENT_DETAILS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_NAME varchar(20),
  ORGLOCATION_ID BIGINT,
  WEBSITE varchar(50),
  COUNTRY varchar(20),
  STATE varchar(20),
  CITY varchar(20),
  TIER varchar(20),
  FIRST_NAME varchar(20),
  LAST_NAME varchar(20),
  EMAIL varchar(100),
  PHONE varchar(20),
  STATUS varchar(20),
  OWNER_EMAIL varchar(100),
  RECORD_STATUS varchar(20),
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORGLOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
) ;