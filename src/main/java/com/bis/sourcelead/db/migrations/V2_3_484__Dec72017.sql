DROP TABLE IF EXISTS `SOURCELEAD_FORM_FIELDS`; 
set foreign_key_checks=1;
CREATE TABLE `SOURCELEAD_FORM_FIELDS` ( 
ID BIGINT NOT NULL AUTO_INCREMENT, 
SECTION_ID BIGINT DEFAULT NULL, 
LABEL_NAME VARCHAR(500) DEFAULT NULL, 
FIELD_NAME VARCHAR(500) DEFAULT NULL, 
LABEL_INFO TEXT DEFAULT NULL,
PLACE_HOLDER TEXT DEFAULT NULL,
FIELD_TYPE VARCHAR(100) DEFAULT NULL, 
FIELD_DESC TEXT DEFAULT NULL, 
IS_FIELD_REQUIRED INT(10) DEFAULT NULL,
SL_DEPENDANT_FIELD BIGINT DEFAULT NULL, 
STATUS INT(10) DEFAULT NULL, 
CREATED_DATE DATETIME, 
CREATED_BY BIGINT DEFAULT NULL, 
UPDATED_DATE DATETIME, 
UPDATED_BY BIGINT DEFAULT NULL, 
PRIMARY KEY (`ID`), 
FOREIGN KEY(SL_DEPENDANT_FIELD) REFERENCES `SOURCELEAD_FORM_FIELDS`(ID), 
FOREIGN KEY(SECTION_ID) REFERENCES `SOURCELEAD_FORM_SECTIONS`(ID), 
FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID), 
FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID) 
); 

#This table is for sourcelead specific custom form sub fields. ie.,(For selectbox, choices and radio buttons) 
DROP TABLE IF EXISTS `SOURCELEAD_FORM_SUB_FIELDS`; 
CREATE TABLE `SOURCELEAD_FORM_SUB_FIELDS` ( 
ID BIGINT NOT NULL AUTO_INCREMENT, 
FORM_FIELD_ID BIGINT DEFAULT NULL, 
LABEL_NAME VARCHAR(500) DEFAULT NULL, 
FIELD_NAME VARCHAR(500) DEFAULT NULL, 
FIELD_DESC TEXT DEFAULT NULL, 
STATUS INT(10) DEFAULT NULL, 
PRIMARY KEY (`ID`), 
FOREIGN KEY(FORM_FIELD_ID) REFERENCES `SOURCELEAD_FORM_FIELDS`(ID) 
); 