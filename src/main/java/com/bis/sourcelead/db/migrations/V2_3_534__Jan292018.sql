
DROP TABLE IF EXISTS `sourcelead`.`JOB_SHARE_CANDIDATES`; 
CREATE TABLE `sourcelead`.`JOB_SHARE_CANDIDATES` ( 
ID BIGINT NOT NULL AUTO_INCREMENT, 
CANDIDATE_ID BIGINT DEFAULT NULL, 
JOB_ID BIGINT DEFAULT NULL,
CREATED_DATE DATETIME,
PRIMARY KEY (`ID`), 
FOREIGN KEY(CANDIDATE_ID) REFERENCES `sourcelead`.`CANDIDATE`(ID), 
FOREIGN KEY(JOB_ID) REFERENCES `sourcelead`.`REQUIREMENT`(ID) 
);
 

