DROP TABLE IF EXISTS `ASSOCIATE_BALANCE_LEAVE`;
CREATE TABLE `ASSOCIATE_BALANCE_LEAVES` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  USER_ID BIGINT,
  LEAVE_TYPE_ID BIGINT,
  TOTAL_LEAVES varchar(20),
  ASSO_BAL_LEAVE_UUID varchar(20),
  STATUS INT,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(USER_ID) REFERENCES `USER`(ID)
) ;


DELIMITER //

CREATE PROCEDURE associateBalanceLeave 
(
    IN userid bigint,
    IN leaveTypeId bigint,
    IN totalLeaves varchar(50),
	IN assBalLeaveUUID varchar(50),
    IN status INT(10),
    IN createdBy bigint,
    IN createdDate date,
    IN updatedBy bigint,
    IN updatedDate date
) 
BEGIN
	   INSERT INTO ASSOCIATE_BALANCE_LEAVES(USER_ID, LEAVE_TYPE_ID, TOTAL_LEAVES, ASSO_BAL_LEAVE_UUID, STATUS, CREATED_BY,CREATED_DATE,UPDATED_BY,UPDATED_DATE)
       values (userid, leaveTypeId, totalLeaves, assBalLeaveUUID, status, createdBy,createdDate,updatedBy,updatedDate); 


END; //

DELIMITER ;



# Associate Balance Leave view
CREATE OR REPLACE VIEW ASSOCIATE_BAL_LEAVE_VIEW AS
SELECT BAL_LEAVE.ID,
       BAL_LEAVE.USER_ID,
       BAL_LEAVE.TOTAL_LEAVES,
       BAL_LEAVE.ASSO_BAL_LEAVE_UUID,
       BAL_LEAVE.STATUS,
	   BAL_LEAVE.CREATED_DATE,
	   BAL_LEAVE.UPDATED_DATE,
	   BAL_LEAVE.LEAVE_TYPE_ID,
	(SELECT NAME FROM LEAVE_TYPE
            WHERE
                ID = BAL_LEAVE.LEAVE_TYPE_ID) AS LEAVE_TYPE_NAME,
	(SELECT FIRST_NAME FROM USER
            WHERE
		ID = BAL_LEAVE.CREATED_BY) AS CREATED_BY_FIRST_NAME,
	(SELECT LAST_NAME FROM USER
            WHERE
		ID = BAL_LEAVE.CREATED_BY) AS CREATED_BY_LAST_NAME
FROM
        ASSOCIATE_BALANCE_LEAVES BAL_LEAVE