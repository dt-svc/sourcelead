DROP TABLE IF EXISTS `ORG_LICENSE_SUBSCRIPTION`;
CREATE TABLE `ORG_LICENSE_SUBSCRIPTION` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_ID BIGINT DEFAULT NULL,
  COUNTRY VARCHAR(100) DEFAULT NULL,
  SUBSCRIPTION_TYPE BIGINT DEFAULT NULL,
  USER_SUBSCRIPTION_TYPE BIGINT DEFAULT NULL,
  STORAGE_SUBSCRIPTION_TYPE BIGINT DEFAULT NULL,
  CURRENCY VARCHAR(10) DEFAULT NULL,
  INVOICE_AMOUNT DOUBLE DEFAULT NULL,
  SUBSCRIPTION_TABS LONGTEXT DEFAULT NULL,
  FROM_DATE DATE,
  TO_DATE DATE,
  TIMEZONE_ID BIGINT DEFAULT NULL,
  IS_INVOICE_AMOUNT_PAID VARCHAR(10) DEFAULT NULL,
  UUID VARCHAR(20) DEFAULT NULL,
  STATUS INT DEFAULT NULL,
  CREATED_DATE DATE,
  CREATED_BY BIGINT DEFAULT NULL,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT DEFAULT NULL,
  PRIMARY KEY (`ID`), 
  FOREIGN KEY(ORG_ID) REFERENCES `ORG`(ID),
  FOREIGN KEY(SUBSCRIPTION_TYPE) REFERENCES `ORG_LICENSE_SUBSCRIPTION_TYPES`(ID),
  FOREIGN KEY(USER_SUBSCRIPTION_TYPE) REFERENCES `ORG_LICENSE_SUBSCRIPTION_TYPES`(ID),
  FOREIGN KEY(STORAGE_SUBSCRIPTION_TYPE) REFERENCES `ORG_LICENSE_SUBSCRIPTION_TYPES`(ID),
  FOREIGN KEY(TIMEZONE_ID) REFERENCES `TIMEZONE`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
); 



