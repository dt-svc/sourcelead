DROP TABLE IF EXISTS `IMMIGRATION_TEMPLATE`; 
CREATE TABLE `IMMIGRATION_TEMPLATE` ( 
ID BIGINT NOT NULL AUTO_INCREMENT, 
NAME  TEXT DEFAULT NULL, 
DESCRIPTION TEXT DEFAULT NULL, 
STATUS INT(10) DEFAULT NULL, 
UUID VARCHAR(20) DEFAULT NULL,
CREATED_DATE DATETIME, 
CREATED_BY BIGINT DEFAULT NULL, 
UPDATED_DATE DATETIME, 
UPDATED_BY BIGINT DEFAULT NULL, 
PRIMARY KEY (`ID`), 
FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID), 
FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID) 
);

DROP TABLE IF EXISTS `IMMIGRATION_TEMPLATE_DOCUMENTS`; 
CREATE TABLE `IMMIGRATION_TEMPLATE_DOCUMENTS` ( 
ID BIGINT NOT NULL AUTO_INCREMENT, 
IMMIGRATION_TEMPLATE_ID BIGINT DEFAULT NULL,
DOCUMENT_TYPE BIGINT DEFAULT NULL,
DOCUMENT_OTHER_TYPE VARCHAR(500) DEFAULT NULL,
DESCRIPTION TEXT DEFAULT NULL,
DOCUMENT_UUID VARCHAR(20) DEFAULT NULL,
IS_REQUIRED VARCHAR(10) DEFAULT NULL,
IS_MULTIPLE_REQUIRED VARCHAR(10) DEFAULT NULL,
STATUS INT(10) DEFAULT NULL, 
CREATED_DATE DATETIME, 
CREATED_BY BIGINT DEFAULT NULL, 
UPDATED_DATE DATETIME, 
UPDATED_BY BIGINT DEFAULT NULL, 
PRIMARY KEY (`ID`), 
FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID), 
FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY(IMMIGRATION_TEMPLATE_ID) REFERENCES `IMMIGRATION_TEMPLATE`(ID), 
FOREIGN KEY(DOCUMENT_TYPE) REFERENCES `LOOKUP_DATA`(ID)  
);
DROP TABLE IF EXISTS `IMMIGRATION_TEMPLATE_FORMS`; 
CREATE TABLE `IMMIGRATION_TEMPLATE_FORMS` ( 
ID BIGINT NOT NULL AUTO_INCREMENT, 
IMMIGRATION_TEMPLATE_ID BIGINT DEFAULT NULL,
FORM_NAME TEXT DEFAULT NULL,
DESCRIPTION TEXT DEFAULT NULL,
FORM_TYPE TEXT DEFAULT NULL,
FORM_UUID VARCHAR(20) DEFAULT NULL,
FILE_NAME TEXT DEFAULT NULL,
FILE_CONTENT_TYPE VARCHAR(250),
FILE_URL TEXT DEFAULT NULL,
IS_REQUIRED VARCHAR(10) DEFAULT NULL,
STATUS INT(10) DEFAULT NULL, 
CREATED_DATE DATETIME, 
CREATED_BY BIGINT DEFAULT NULL, 
UPDATED_DATE DATETIME, 
UPDATED_BY BIGINT DEFAULT NULL, 
PRIMARY KEY (`ID`), 
FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID), 
FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY(IMMIGRATION_TEMPLATE_ID) REFERENCES `IMMIGRATION_TEMPLATE`(ID)
);
DROP TABLE IF EXISTS `IMMIGRATION_TEMPLATE_TASKS`;
