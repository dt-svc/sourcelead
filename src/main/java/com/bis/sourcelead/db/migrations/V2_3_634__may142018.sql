
DROP TABLE IF EXISTS `PAYROLL_BONUS`;
CREATE TABLE `PAYROLL_BONUS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORGLOCATION_ID BIGINT,
  PAYMENT_DATE DATE,
  PAYMENT_MONTH VARCHAR(50),
  PAYMENT_YEAR  VARCHAR(50),
  MIN_PERCENTAGE DOUBLE,
  MAX_PERCENTAGE DOUBLE,
  FROM_MONTH VARCHAR(50),
  TO_MONTH VARCHAR(50),
  MAX_MONTH_SALARY DOUBLE,
  PAYMENT_FREQUENCY VARCHAR(50),
  DESCRIPTION TEXT,
  UUID VARCHAR(20),
  STATUS INT,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORGLOCATION_ID) REFERENCES `USER`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
);