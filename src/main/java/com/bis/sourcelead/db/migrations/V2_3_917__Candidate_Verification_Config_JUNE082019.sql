DROP TABLE IF EXISTS `CANDIDATE_VERIFICATION_CONFIG`;
CREATE TABLE `CANDIDATE_VERIFICATION_CONFIG` (
  `ID` bigint(20) NOT NULL AUTO_INCREMENT,
  `ORG_LOCATION_ID` bigint(20) DEFAULT NULL,
  `EMAIL` tinyint(1) DEFAULT NULL,
  `MOBILE_PHONE` tinyint(1) DEFAULT NULL,
  `PAN_NUMBER` tinyint(1) DEFAULT NULL,
  `AADHAR_NUMBER` tinyint(1) DEFAULT NULL,
  `SSN_NUMBER` tinyint(1) DEFAULT NULL,
  `UUID` varchar(50) DEFAULT NULL,
  `STATUS` int(11) DEFAULT NULL,
  `CREATED_DATE` date DEFAULT NULL,
  `CREATED_BY` bigint(20) DEFAULT NULL,
  `UPDATED_DATE` date DEFAULT NULL,
  `UPDATED_BY` bigint(20) DEFAULT NULL,
  PRIMARY KEY (`ID`),
  KEY `ORG_LOCATION_ID` (`ORG_LOCATION_ID`),
  KEY `CREATED_BY` (`CREATED_BY`),
  KEY `UPDATED_BY` (`UPDATED_BY`),
  FOREIGN KEY (`ORG_LOCATION_ID`) REFERENCES `ORG_LOCATIONS` (`ID`),
  FOREIGN KEY (`CREATED_BY`) REFERENCES `USER` (`ID`),
  FOREIGN KEY (`UPDATED_BY`) REFERENCES `USER` (`ID`)
  );