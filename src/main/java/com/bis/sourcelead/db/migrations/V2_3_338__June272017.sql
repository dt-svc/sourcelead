DROP TABLE IF EXISTS `SOURCELEAD_NOTES`;
CREATE TABLE `SOURCELEAD_NOTES` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_RELATION_ID BIGINT DEFAULT NULL,
  USER_ID BIGINT DEFAULT NULL,
  REQUIREMENT_ID BIGINT DEFAULT NULL,
  CONTRACT_ID BIGINT DEFAULT NULL,
  INVOICE_ID BIGINT DEFAULT NULL,
  SPOC_ID BIGINT DEFAULT NULL,
  COMMENT TEXT,
  NOTE_TYPE VARCHAR(20),
  DROPDOWN_TYPE VARCHAR(20),
  CHECK_BOX VARCHAR(2),
  CREATED_DATE DATETIME,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATETIME,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_RELATION_ID) REFERENCES `ORG_RELATIONS`(ID),
  FOREIGN KEY(REQUIREMENT_ID) REFERENCES `REQUIREMENT`(ID),
  FOREIGN KEY(CONTRACT_ID) REFERENCES `CONTRACTS`(ID),
  FOREIGN KEY(SPOC_ID) REFERENCES `ORG_SPOC`(ID),
  FOREIGN KEY(INVOICE_ID) REFERENCES `INVOICE`(ID),
  FOREIGN KEY(USER_ID) REFERENCES `USER`(ID)
) ;



