# CREATED BY SRINIVAS SABBU ON SEP 20 2018 FOR MARKET PLACE FUNCTIONALITY.

DROP TABLE IF EXISTS `CANDIDATE_MARKET_PLACE`; 
CREATE TABLE `CANDIDATE_MARKET_PLACE` ( 
ID BIGINT NOT NULL AUTO_INCREMENT, 
CANDIDATE_ID BIGINT DEFAULT NULL,
MASTER_CANDIDATE_ID BIGINT DEFAULT NULL,
CANDIDATE_UUID VARCHAR(20) DEFAULT NULL,
ORG_LOCATION_ID BIGINT,
NAME VARCHAR(100)  DEFAULT NULL,
GENDER VARCHAR(20)  DEFAULT NULL,
EMAIL VARCHAR(100) DEFAULT NULL,
ALTERNATE_EMAIL VARCHAR(100) DEFAULT NULL,
MOBILE_PHONE VARCHAR(20) DEFAULT NULL,
ALTERNATE_MOBILE_PHONE VARCHAR(20) DEFAULT NULL,
DESIGNATION VARCHAR(250) DEFAULT NULL,
EMPLOYEMENT_TYPE VARCHAR(250) DEFAULT NULL,
LOCATION VARCHAR(250) DEFAULT NULL,
PROFILE_PERCENTAGE INT DEFAULT 0,
SKILLS_NAME TEXT DEFAULT NULL,
EXPERIENCE_YEARS VARCHAR(2) DEFAULT NULL,
EXPERIENCE_MONTHS VARCHAR(2) DEFAULT NULL,
CURRENT_RATE VARCHAR(250) DEFAULT NULL,
CURRENT_RATE_TYPE VARCHAR(20) NULL,
CURRENT_RATE_CURRENCY VARCHAR(20) DEFAULT NULL,
EXPECTED_RATE VARCHAR(250) DEFAULT NULL,
EXPECTED_RATE_TYPE VARCHAR(20) NULL,
EXPECTED_RATE_CURRENCY VARCHAR(20) DEFAULT NULL,
NOTICE_PERIOD VARCHAR(100) DEFAULT NULL,
MARKET_PRICE VARCHAR(250) DEFAULT NULL,
MARKET_RATE_CURRENCY VARCHAR(20) DEFAULT NULL,
SUMMARY VARCHAR(5000) DEFAULT NULL,
CAN_MARKET_STATUS VARCHAR(20) DEFAULT NULL,
WITHDRAW_REASON VARCHAR(255) DEFAULT NULL,
IMAGE_URL VARCHAR(255) DEFAULT NULL,
NATIONALITY VARCHAR(100) NULL, 
MARITAL_STATUS VARCHAR(30) NULL,
STATUS INT(10) DEFAULT NULL, 
CREATED_DATE DATETIME, 
CREATED_BY BIGINT DEFAULT NULL, 
UPDATED_DATE DATETIME, 
UPDATED_BY BIGINT DEFAULT NULL, 
PRIMARY KEY (`ID`), 
FOREIGN KEY(CANDIDATE_ID) REFERENCES `CANDIDATE`(ID), 
FOREIGN KEY(MASTER_CANDIDATE_ID) REFERENCES `MASTER_CANDIDATE`(ID),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID), 
FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
);