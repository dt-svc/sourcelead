
DROP TABLE IF EXISTS `USER_SIGNATURE`;
CREATE TABLE `USER_SIGNATURE` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  USER_ID BIGINT DEFAULT NULL,
  ORG_LOCATION_ID BIGINT DEFAULT NULL,
  SIGNATURE_NAME VARCHAR(100),
  SIGNATURE TEXT DEFAULT NULL,
  STATUS INT DEFAULT NULL,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`), 
  FOREIGN KEY fk1_USER_SIGNATURE_USER (USER_ID)  REFERENCES `USER`(ID),
  FOREIGN KEY fk1_USER_SIGNATURE_ORG_LOCATIONS (ORG_LOCATION_ID)  REFERENCES `ORG_LOCATIONS`(ID)
); 


DROP TABLE IF EXISTS `USER_MAIL_BOX`;
CREATE TABLE `USER_MAIL_BOX` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  USER_ID BIGINT DEFAULT NULL,
  ORG_LOCATION_ID BIGINT DEFAULT NULL,
  TO_MAIL TEXT  DEFAULT NULL,
  FROM_MAIL TEXT  DEFAULT NULL,
  MAIL_STATUS VARCHAR(50),
  SUBJECT TEXT DEFAULT NULL,
  CAMPAIGN_TABLE_DATA TEXT DEFAULT NULL,
  BODY TEXT DEFAULT NULL,
  USER_SIGNATURE_ID BIGINT DEFAULT NULL,
  CANDIDATE_ID TEXT  DEFAULT NULL,
  UUID VARCHAR(50) DEFAULT NULL,
  IS_FAVOURITE INT DEFAULT NULL,
  NAME_FIELDS VARCHAR(50) DEFAULT NULL,
  STATUS INT DEFAULT NULL,
  CREATED_DATE DATETIME,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATETIME,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`), 
  FOREIGN KEY fk1_USER_MAIL_BOX_USER (USER_ID)  REFERENCES `USER`(ID),
  FOREIGN KEY fk1_USER_MAIL_BOX_ORG_LOCATIONS (ORG_LOCATION_ID)  REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY fk1_USER_MAIL_BOX_USER_SIGNATURE (USER_SIGNATURE_ID)  REFERENCES `USER_SIGNATURE`(ID)
); 


