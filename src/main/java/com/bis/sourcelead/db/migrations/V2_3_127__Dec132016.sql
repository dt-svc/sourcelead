
DROP TABLE IF EXISTS `sourcelead`.`CANDIDATE_HOT_LIST`;
CREATE TABLE `sourcelead`.`CANDIDATE_HOT_LIST` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  CANDIDATE_ID BIGINT DEFAULT NULL,
  TEAM_ID BIGINT DEFAULT NULL,
  ORG_LOCATION_ID BIGINT DEFAULT NULL,
  STATUS INT DEFAULT NULL,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`), 
  FOREIGN KEY(CANDIDATE_ID) REFERENCES `sourcelead`.`CANDIDATE`(ID),
  FOREIGN KEY(TEAM_ID) REFERENCES `sourcelead`.`TEAM`(ID),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `sourcelead`.`ORG_LOCATIONS`(ID)
); 
