DROP TABLE IF EXISTS `REQUIREMENT_WORKFLOW_TASKS`;
DROP TABLE IF EXISTS `REQUIREMENT_WORKFLOW_STAGES`;
DROP TABLE IF EXISTS `REQUIREMENT_QUESTIONNAIRE_TEMPLATE`;
DROP TABLE IF EXISTS `REQUIREMENT_WORKFLOW`;

DROP TABLE IF EXISTS `REQUIREMENT_QUESTIONNAIRE_TEMPLATE`;
CREATE TABLE `REQUIREMENT_QUESTIONNAIRE_TEMPLATE` (
ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
NAME VARCHAR(100) DEFAULT NULL,
DESCRIPTION LONGTEXT,
JSON_STRING LONGTEXT,
ORG_LOCATION_ID BIGINT,
UUID VARCHAR(50) DEFAULT NULL,
TIME_LIMIT_MINUTES INT,
TIME_LIMIT_SECONDS INT,
STATUS INT(10) NOT NULL,
CREATED_DATE DATE,
CREATED_BY BIGINT,
UPDATED_DATE DATE,
UPDATED_BY BIGINT,

PRIMARY KEY (`ID`),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
) ;

DROP TABLE IF EXISTS `REQUIREMENT_WORKFLOW`;
CREATE TABLE REQUIREMENT_WORKFLOW (
ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
WORKFLOW_NAME VARCHAR(100) DEFAULT NULL,
DESCRIPTION LONGTEXT,
ORG_LOCATION_ID BIGINT,
NO_OF_STAGES INT(10),

UUID VARCHAR(50) DEFAULT NULL,
STATUS INT(10) NOT NULL,
CONFIGURE_TYPE VARCHAR(50) DEFAULT NULL,
CREATED_DATE DATE,
CREATED_BY BIGINT,
UPDATED_DATE DATE,
UPDATED_BY BIGINT,
PRIMARY KEY (`ID`),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
);

DROP TABLE IF EXISTS `REQUIREMENT_WORKFLOW_STAGES`;
CREATE TABLE REQUIREMENT_WORKFLOW_STAGES (
ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
REQUIREMENT_WORKFLOW_ID BIGINT UNSIGNED NOT NULL,
ORG_LOCATION_ID BIGINT,
STAGE_NAME VARCHAR(100) DEFAULT NULL,
`STAGE_SHORT_CODE` VARCHAR(50) NOT NULL,
REQUIREMENT_QUESTIONNAIRE_TEMPLATE_ID BIGINT UNSIGNED NULL,
DESCRIPTION LONGTEXT,
SEQ_ORDER INT(10) NOT NULL,
UUID VARCHAR(50) DEFAULT NULL,
CONFIGURE_TYPE VARCHAR(50) DEFAULT NULL,
IS_EDITABLE VARCHAR(10) DEFAULT NULL,
STATUS INT(10) NOT NULL,
`COMMENT_REQUIRED` VARCHAR(10) NULL DEFAULT NULL,
`REQUIRED_STATS_LIST` VARCHAR(10) NULL DEFAULT NULL,
`CHOSEN_COLUMNS` LONGTEXT NULL DEFAULT NULL,
CREATED_DATE DATE,
CREATED_BY BIGINT,
UPDATED_DATE DATE,
UPDATED_BY BIGINT,

PRIMARY KEY (`ID`),
FOREIGN KEY(REQUIREMENT_WORKFLOW_ID) REFERENCES `REQUIREMENT_WORKFLOW`(ID),
FOREIGN KEY(REQUIREMENT_QUESTIONNAIRE_TEMPLATE_ID) REFERENCES `REQUIREMENT_QUESTIONNAIRE_TEMPLATE`(ID),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)

);

DROP TABLE IF EXISTS `REQUIREMENT_WORKFLOW_TASKS`;
CREATE TABLE `REQUIREMENT_WORKFLOW_TASKS` (
ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
REQUIREMENT_WORKFLOW_STAGES_ID BIGINT UNSIGNED NOT NULL,
ORG_LOCATION_ID BIGINT,
TASK_NAME VARCHAR(100) DEFAULT NULL,
ASSIGN_TO_USER_ID BIGINT ,
PRIORITY VARCHAR(20),
DESCRIPTION LONGTEXT,
UUID VARCHAR(50) DEFAULT NULL,
STATUS INT(10) NOT NULL,
CREATED_DATE DATE,
CREATED_BY BIGINT,
UPDATED_DATE DATE,
UPDATED_BY BIGINT,

PRIMARY KEY (`ID`),
FOREIGN KEY(REQUIREMENT_WORKFLOW_STAGES_ID) REFERENCES `REQUIREMENT_WORKFLOW_STAGES`(ID),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
FOREIGN KEY(ASSIGN_TO_USER_ID) REFERENCES `USER`(ID),
FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
) ;

