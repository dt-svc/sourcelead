CREATE OR REPLACE VIEW CANDIDATE_ONBAORDING_VIEW AS
    SELECT 
        CAN.ID AS CANDIDATE_ID,
        RF.ID AS OFFER_ID,
        CONCAT(CAN.FIRST_NAME,' ', IFNULL(CAN.LAST_NAME, '')) AS CANDIDATE_NAME,
        CAN.EMAIL AS CANDIDATE_EMAIL,
        CAN.CANDIDATE_UUID AS CANDIDATE_UUID,
        REQ.JOB_TITLE AS REQUIREMENT_NAME,
        REQ.REQUIREMENT_UUID AS REQUIREMENT_UUID,
        REQ.RELEASE_JOB_TO_ALL_USERS AS REQRELEASE_ALLJOB_USERSTATUS,
        U.ID AS REQ_MANAGERID,
        DATE_FORMAT(RF.DATE_OF_JOINING, '%d %m %Y') AS OFFER_JOIN_DATE,
        RF.POSITION_TYPE AS POSITION_TYPE,
        RF.AMOUNT AS RATE,
        RF.PAYMENT_MODE AS RATE_TYPE,
        RF.PAYMENT_TYPE AS PAYMENT_TYPE,
        RF.OFFER_UUID AS OFFER_UUID,
        RS.ORG_LOCATION_ID AS ORGLOCATION_ID
    FROM
        REQUIREMENT_SUBMISSION RS,
        CANDIDATE_GLOBAL CAN,
        REQUIREMENT REQ,
        REQUIREMENT_OFFERS RF,
        USER U
    WHERE
        RS.REQUIREMENT_ID = REQ.ID
            AND CAN.CONSULTANT_USER_ID IS NULL
            AND CAN.ID = RS.CANDIDATE_ID
            AND REQ.MANAGER_USER_ID = U.ID
            AND (RS.SUBMISSION_STATUS = 'OFFERACCEPTED' OR SUBMISSION_STATUS ='JOINED')
            AND RF.SUBMISSION_ID = RS.ID
            
            
            