DROP TABLE IF EXISTS `sourcelead`.`REQUIREMENT`;
CREATE TABLE `sourcelead`.`REQUIREMENT` (

  ID BIGINT NOT NULL AUTO_INCREMENT,
  PARENT_REQUIREMENT_ID BIGINT,
  ORG_LOCATION_ID BIGINT,
  JOB_TITLE VARCHAR(250)  DEFAULT NULL,
  JOB_TYPE VARCHAR(100)  DEFAULT NULL,
  JOB_ID VARCHAR(100) DEFAULT NULL,
  POSITIONS VARCHAR(10) DEFAULT NULL,
  EDUCATION VARCHAR(200) DEFAULT NULL,
  MIN_EXP VARCHAR(5) DEFAULT NULL,
  MAX_EXP VARCHAR(5) DEFAULT NULL,
  CURRENCY_CODE VARCHAR(10) DEFAULT NULL,
  RATE VARCHAR(8) DEFAULT NULL,
  RATE_TYPE VARCHAR(20) DEFAULT NULL,
  COUNTRY VARCHAR(50) DEFAULT NULL,
  STATE VARCHAR(50) DEFAULT NULL,
  CITY VARCHAR(50) DEFAULT NULL,
  SKILLS VARCHAR(150) DEFAULT NULL,
  DESCRIPTION VARCHAR(500) DEFAULT NULL,
  DOC_FILE MEDIUMBLOB,
  FILE_CONTENT_TYPE VARCHAR(50),
  FILE_NAME VARCHAR(50),
  IS_CLIENT_JOB VARCHAR(2) DEFAULT NULL,
  
  ORG_RELATION_ID BIGINT,
  SOPC_ID BIGINT,
  SUBMISSION_TEMPLATE_ID BIGINT,
  CLIENT_SUBMISSION_TEMPLATE_ID BIGINT,
  MANAGER_USER_ID BIGINT,
  
  CLIENT_CURRENCY_CODE VARCHAR(10) DEFAULT NULL,
  CLIENT_RATE VARCHAR(10) DEFAULT NULL,
  CLIENT_RATE_TYPE VARCHAR(10) DEFAULT NULL,
  IS_Template VARCHAR(2) DEFAULT NULL, 
  STATUS VARCHAR(20)DEFAULT NULL,
  PRIORITY VARCHAR(20) DEFAULT NULL,
  
  CREATED_DATE DATETIME,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATETIME,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `sourcelead`.`ORG_LOCATIONS`(ID),
  FOREIGN KEY(SUBMISSION_TEMPLATE_ID) REFERENCES `sourcelead`.`SUBMISSION_TEMPLATE`(ID),
  FOREIGN KEY(CLIENT_SUBMISSION_TEMPLATE_ID) REFERENCES `sourcelead`.`SUBMISSION_TEMPLATE`(ID),
  FOREIGN KEY(SOPC_ID) REFERENCES `sourcelead`.`USER`(ID),
  FOREIGN KEY(MANAGER_USER_ID) REFERENCES `sourcelead`.`USER`(ID),
  FOREIGN KEY(ORG_RELATION_ID) REFERENCES `sourcelead`.`ORG_RELATIONS`(ID),
  CONSTRAINT `SelfKey` FOREIGN KEY (`PARENT_REQUIREMENT_ID`) REFERENCES `REQUIREMENT` (`ID`) ON DELETE NO ACTION ON UPDATE NO ACTION
) ;






DROP TABLE IF EXISTS `sourcelead`.`TEAM`;
CREATE TABLE `sourcelead`.`TEAM` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  NAME VARCHAR(50),
  OWNER_USER_ID BIGINT,
  DESCRIPTION VARCHAR(5000) DEFAULT NULL,
  CATEGORY VARCHAR(20) DEFAULT NULL,
  STATUS VARCHAR(20) DEFAULT NULL,
  CREATED_DATE DATETIME,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATETIME,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(OWNER_USER_ID) REFERENCES `sourcelead`.`USER`(ID)
) ;


DROP TABLE IF EXISTS `sourcelead`.`TEAM_MEMBERS`;
CREATE TABLE `sourcelead`.`TEAM_MEMBERS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  TEAM_ID BIGINT,
  MEMBER_USER_ID BIGINT,
  STATUS VARCHAR(20) DEFAULT NULL,
  CREATED_DATE DATETIME,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATETIME,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(TEAM_ID) REFERENCES `sourcelead`.`TEAM`(ID),
  FOREIGN KEY(MEMBER_USER_ID) REFERENCES `sourcelead`.`USER`(ID)
) ;


