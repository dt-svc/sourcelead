DROP TABLE IF EXISTS `TIMESHEET_HISTORY`;
CREATE TABLE `TIMESHEET_HISTORY` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  TIMESHEET_SUBMISSION_ID BIGINT,  
  PROJECT_TASK bigint(20) DEFAULT NULL,
  START_DATE DATE DEFAULT NULL,
  END_DATE DATE DEFAULT NULL,
  TOTAL_HOURS INT DEFAULT NULL,
  SUBMITTED_HOURS INT DEFAULT NULL,
  ENTRY_STATUS VARCHAR(20),
  
  MON_HOURS varchar(100) DEFAULT NULL,
  MON_COMMENTS text,
  
  TUE_HOURS varchar(100) DEFAULT NULL,
  TUE_COMMENTS text,
  
  WED_HOURS varchar(100) DEFAULT NULL,
  WED_COMMENTS text,
  
  THU_HOURS varchar(100) DEFAULT NULL,
  THU_COMMENTS text,
  
  FRI_HOURS varchar(100) DEFAULT NULL,
  FRI_COMMENTS text,
  
  SAT_HOURS varchar(100) DEFAULT NULL,
  SAT_COMMENTS text,
  
  SUN_HOURS varchar(100) DEFAULT NULL,
  SUN_COMMENTS text,
		  
  ENTRY_TYPE VARCHAR(30) DEFAULT NULL,
  STATUS VARCHAR(20) DEFAULT NULL,
  
  DOC_FILE MEDIUMBLOB,
  FILE_CONTENT_TYPE varchar(50) DEFAULT NULL,
  FILE_NAME varchar(50) DEFAULT NULL,
  WEEK_COMMENTS text,
  
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),

  PRIMARY KEY (`ID`),
  FOREIGN KEY(TIMESHEET_SUBMISSION_ID) REFERENCES `TIMESHEET_SUBMISSIONS`(ID),
  FOREIGN KEY(PROJECT_TASK) REFERENCES `PROJECT_TASKS`(ID)
 
) ;