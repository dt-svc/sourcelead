
DROP TABLE IF EXISTS `PERFORMANCE_COMPETENCIES`;
CREATE TABLE `PERFORMANCE_COMPETENCIES`(
ID BIGINT NOT NULL AUTO_INCREMENT,
COMPETENCIES_NAME VARCHAR(500) DEFAULT NULL,
DESCRIPTION LONGTEXT DEFAULT NULL,
ORG_LOCATION_ID BIGINT DEFAULT NULL,
UUID VARCHAR(50) DEFAULT NULL,
STATUS INT,
CREATED_DATE DATE,
CREATED_BY BIGINT DEFAULT NULL,
UPDATED_DATE DATE,
UPDATED_BY BIGINT DEFAULT NULL,
PRIMARY KEY (`ID`),
FOREIGN KEY (CREATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY (UPDATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
);

DROP TABLE IF EXISTS `PERFORMANCE_TAG_COMPETENCIES`;
CREATE TABLE `PERFORMANCE_TAG_COMPETENCIES`(
ID BIGINT NOT NULL AUTO_INCREMENT,
ROLES TEXT DEFAULT NULL,
COMPETENCIES TEXT DEFAULT NULL,
COMPETENCIES_TAGGING_JSON_STRING LONGTEXT DEFAULT NULL,
ORG_LOCATION_ID BIGINT DEFAULT NULL,
UUID VARCHAR(50) DEFAULT NULL,
STATUS INT,
CREATED_DATE DATE,
CREATED_BY BIGINT DEFAULT NULL,
UPDATED_DATE DATE,
UPDATED_BY BIGINT DEFAULT NULL,
PRIMARY KEY (`ID`),
FOREIGN KEY (CREATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY (UPDATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
);
