#Leave Management
#Holiday & Restrict Days
DROP TABLE IF EXISTS `sourcelead`.`HOLIDAY_RESTRICT_DAYS`;
CREATE TABLE `sourcelead`.`HOLIDAY_RESTRICT_DAYS` (
  ID VARCHAR(100),
  ORGLOCATION_ID BIGINT,
  HOLIDAY_ID VARCHAR(100),
  RESTRICTDAY_ID VARCHAR(100),
  DAY DATE,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORGLOCATION_ID) REFERENCES `sourcelead`.`ORG_LOCATIONS`(ID),
  FOREIGN KEY(HOLIDAY_ID) REFERENCES `sourcelead`.`HOLIDAY`(ID),
  FOREIGN KEY(RESTRICTDAY_ID) REFERENCES `sourcelead`.`RESTRICT_DAY`(ID)
) ;

