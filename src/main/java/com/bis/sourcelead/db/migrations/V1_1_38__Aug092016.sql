DROP TABLE IF EXISTS `sourcelead`.`PROJECT_MEMBERS_HISTORY`;
CREATE TABLE `sourcelead`.`PROJECT_MEMBERS_HISTORY` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  PROJECT_MEMBERS_ID BIGINT,
  PROJECT_ASSIGNED_DATE DATE DEFAULT NULL,
  PROJECT_TERMINATION_DATE DATE DEFAULT NULL,
  STATUS VARCHAR(20),
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(PROJECT_MEMBERS_ID) REFERENCES `sourcelead`.`PROJECT_MEMBERS`(ID)
) ;
