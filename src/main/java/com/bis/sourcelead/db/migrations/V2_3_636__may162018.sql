DROP TABLE IF EXISTS `PAYROLL_PAYHEAD`;
CREATE TABLE `PAYROLL_PAYHEAD` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  PARENT_PAYHEAD_ID BIGINT,
  NAME VARCHAR(100),
  SHORT_CODE VARCHAR(10),
  EFFECTIVE_DATE DATE,
  PAY_TYPE BIGINT,
  AMOUNT DOUBLE,
  FORMULA VARCHAR(10),
  FORM_16 VARCHAR(100),
  TAX VARCHAR(50),
  APPLICABLE_FOR VARCHAR(50),
  COMPONENT VARCHAR(50),
  PAID_COMPONENT VARCHAR(10),
  PART_OF_A_CTC VARCHAR(10),
  FBP_COMPONENT VARCHAR(10),
  ORGLOCATION_ID BIGINT,
  STATUS INT,
  CREATED_DATE DATETIME,
  CREATED_BY BIGINT,
  UPDATED_DATE DATETIME,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORGLOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(PAY_TYPE) REFERENCES `PAYROLL_PAYTYPE`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID),
  CONSTRAINT `FK_PH_Parent` FOREIGN KEY (`PARENT_PAYHEAD_ID`) REFERENCES `PAYROLL_PAYHEAD` (`ID`) ON DELETE NO ACTION ON UPDATE NO ACTION
);


