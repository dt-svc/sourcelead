
DROP TABLE IF EXISTS `PERFORMANCE_GOALS`;
CREATE TABLE `PERFORMANCE_GOALS`(
ID BIGINT NOT NULL AUTO_INCREMENT,
GOAL_NAME VARCHAR(500) DEFAULT NULL,
START_DATE DATE,
END_DATE DATE,
NOTIFY_TO TEXT DEFAULT NULL,
DESCRIPTION LONGTEXT DEFAULT NULL,
ORG_LOCATION_ID BIGINT DEFAULT NULL,
GOAL_TYPE VARCHAR(50) DEFAULT NULL,
PERCENTAGE_DONE INT DEFAULT NULL,
UUID VARCHAR(50) DEFAULT NULL,
STATUS INT,
CREATED_DATE DATE,
CREATED_BY BIGINT DEFAULT NULL,
UPDATED_DATE DATE,
UPDATED_BY BIGINT DEFAULT NULL,
PRIMARY KEY (`ID`),
FOREIGN KEY (CREATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY (UPDATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
);

DROP TABLE IF EXISTS `PERFORMANCE_GOALS_ASSIGN_TO`;
CREATE TABLE `PERFORMANCE_GOALS_ASSIGN_TO`(
ID BIGINT NOT NULL AUTO_INCREMENT,
GOAL_ID BIGINT NOT NULL,
ASSIGNED_USER_ID BIGINT NOT NULL,
ORG_LOCATION_ID BIGINT DEFAULT NULL,
PERCENTAGE_DONE INT DEFAULT NULL,
UUID VARCHAR(50) DEFAULT NULL,
STATUS INT,
CREATED_DATE DATE,
CREATED_BY BIGINT DEFAULT NULL,
UPDATED_DATE DATE,
UPDATED_BY BIGINT DEFAULT NULL,
PRIMARY KEY (`ID`),
FOREIGN KEY (GOAL_ID) REFERENCES `PERFORMANCE_GOALS`(ID),
FOREIGN KEY (ASSIGNED_USER_ID) REFERENCES `USER`(ID),
FOREIGN KEY (CREATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY (UPDATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
);

DROP TABLE IF EXISTS `PERFORMANCE_GOALS_ATTACHMENTS`;
CREATE TABLE `PERFORMANCE_GOALS_ATTACHMENTS`(
ID BIGINT NOT NULL AUTO_INCREMENT,
GOAL_ID BIGINT NOT NULL,
FILE_NAME TEXT NOT NULL,
FILE_TYPE TEXT NOT NULL,
FILE_URL TEXT NOT NULL,
UUID VARCHAR(50) DEFAULT NULL,
STATUS INT,
PRIMARY KEY (`ID`),
FOREIGN KEY (GOAL_ID) REFERENCES `PERFORMANCE_GOALS`(ID)
);
