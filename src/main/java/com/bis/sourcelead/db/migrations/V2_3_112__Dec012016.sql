DROP TABLE IF EXISTS `sourcelead`.`ASSET_CATEGORY`;
CREATE TABLE `sourcelead`.`ASSET_CATEGORY` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  CATEGORY_NAME VARCHAR(100),
  DESCRIPTION TEXT,
  ORG_LOCATION_ID BIGINT,
  DEFAULT_CATEGORY INT,
  STATUS INT,
  CREATED_DATE DATETIME,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATETIME,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `sourcelead`.`ORG_LOCATIONS`(ID)
) ;


DROP TABLE IF EXISTS `sourcelead`.`ASSET`;
CREATE TABLE `sourcelead`.`ASSET` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  SL_NO INT(50),
  ASSET_CATEGORY_ID BIGINT,
  MAKE VARCHAR(100),
  MODEL VARCHAR(100),
  MEMRORY VARCHAR(50),
  WORKING_STATUS VARCHAR(50),
  CPU VARCHAR(100),
  HARD_DISK VARCHAR(100),
  MONITOR VARCHAR(100),
  ATTACHMENT MEDIUMBLOB,
  FILE_CONTENT_TYPE VARCHAR(50),
  FILE_NAME VARCHAR(500),
  SHIFT_A_EMPLOYEE BIGINT,
  SHIFT_A_ATTACHMENT MEDIUMBLOB,
  SHIFT_A_FILE_CONTENT_TYPE VARCHAR(50),
  SHIFT_A_FILE_NAME VARCHAR(500),
  SHIFT_B_EMPLOYEE BIGINT,
  SHIFT_B_ATTACHMENT MEDIUMBLOB,
  SHIFT_B_FILE_CONTENT_TYPE VARCHAR(50),
  SHIFT_B_FILE_NAME VARCHAR(500),
  ORG_LOCATION_ID BIGINT,
  DESCRIPTION TEXT,
  STATUS INT,
  CREATED_DATE DATETIME,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATETIME,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `sourcelead`.`ORG_LOCATIONS`(ID),
  FOREIGN KEY(ASSET_CATEGORY_ID) REFERENCES `sourcelead`.`ASSET_CATEGORY`(ID),
  FOREIGN KEY(SHIFT_A_EMPLOYEE) REFERENCES `sourcelead`.`EMPLOYEE`(ID),
  FOREIGN KEY(SHIFT_B_EMPLOYEE) REFERENCES `sourcelead`.`EMPLOYEE`(ID)
) ;


