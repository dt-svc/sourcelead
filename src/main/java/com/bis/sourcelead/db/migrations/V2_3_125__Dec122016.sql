ALTER TABLE `REQUIREMENT_INTERVIEW` 
DROP COLUMN `NOTIFICATION_TO_SPOC`,
DROP COLUMN `NOTIFICATION_TO_APPLICANT`;

DROP TABLE IF EXISTS `REQUIREMENT_INTERVIEW_HISTORY`;
CREATE TABLE `REQUIREMENT_INTERVIEW_HISTORY` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  INTERVIEW_ID BIGINT DEFAULT NULL,
  SUBMISSION_ID BIGINT DEFAULT NULL,
  ORG_LOCATION_ID BIGINT DEFAULT NULL,
  INTERVIEW_SOURCE_TYPE VARCHAR(250),
  NOTIFICATION_TO_APPLICANT VARCHAR(3),
  NOTIFICATION_TO_SPOC VARCHAR(2),
  STATUS INT(10) DEFAULT NULL,
  CREATED_DATE DATETIME,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATETIME,
  UPDATED_BY VARCHAR(10),
  
  PRIMARY KEY (`ID`), 
  FOREIGN KEY(INTERVIEW_ID) REFERENCES `REQUIREMENT_INTERVIEW`(ID),
  FOREIGN KEY(SUBMISSION_ID) REFERENCES `REQUIREMENT_SUBMISSION`(ID),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
); 
