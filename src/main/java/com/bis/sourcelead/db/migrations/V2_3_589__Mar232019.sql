
DROP TABLE IF EXISTS `USER_MANUAL_LEVEL_ONE`;
CREATE TABLE `USER_MANUAL_LEVEL_ONE` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  LEVEL_ONE_UUID VARCHAR(50) DEFAULT NULL,
  TITLE VARCHAR(500) DEFAULT NULL,
  DESCRIPTION LONGTEXT DEFAULT NULL,
  ORDER_ONE INT DEFAULT NULL,
  STATUS VARCHAR(250) DEFAULT NULL,
  CREATED_BY BIGINT DEFAULT NULL,
  UPDATED_BY BIGINT DEFAULT NULL,
  CREATED_DATE DATE,
  UPDATED_DATE DATE,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
) ;



DROP TABLE IF EXISTS `USER_MANUAL_LEVEL_TWO`;
CREATE TABLE `USER_MANUAL_LEVEL_TWO` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  LEVEL_TWO_UUID VARCHAR(50) DEFAULT NULL,
  TITLE VARCHAR(500) DEFAULT NULL,
  DESCRIPTION LONGTEXT DEFAULT NULL,
  USER_MANUAL_LEVEL_ONE_ID BIGINT DEFAULT NULL,
  ORDER_TWO INT DEFAULT NULL,
  STATUS VARCHAR(250) DEFAULT NULL,
  CREATED_BY BIGINT DEFAULT NULL,
  UPDATED_BY BIGINT DEFAULT NULL,
  CREATED_DATE DATE,
  UPDATED_DATE DATE,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(USER_MANUAL_LEVEL_ONE_ID) REFERENCES `USER_MANUAL_LEVEL_ONE`(ID)
) ;



DROP TABLE IF EXISTS `USER_MANUAL_LEVEL_THREE`;
CREATE TABLE `USER_MANUAL_LEVEL_THREE` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  LEVEL_THREE_UUID VARCHAR(50) DEFAULT NULL,
  TITLE VARCHAR(500) DEFAULT NULL,
  DESCRIPTION LONGTEXT DEFAULT NULL,
  FILE_NAME VARCHAR(500) DEFAULT NULL,
  FILE_URL TEXT DEFAULT NULL,
  FILE_TYPE VARCHAR(500) DEFAULT NULL,
  UPLOAD_URL LONGTEXT DEFAULT NULL,
  USER_MANUAL_LEVEL_TWO_ID BIGINT DEFAULT NULL,
  ORDER_THREE INT DEFAULT NULL,
  STATUS VARCHAR(250) DEFAULT NULL,
  CREATED_BY BIGINT DEFAULT NULL,
  UPDATED_BY BIGINT DEFAULT NULL,
  CREATED_DATE DATE,
  UPDATED_DATE DATE,
  PUBLISH_ON DATE,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(USER_MANUAL_LEVEL_TWO_ID) REFERENCES `USER_MANUAL_LEVEL_TWO`(ID)
) ;

DROP TABLE IF EXISTS `USER_MANUAL_ATTACHMENTS`;
CREATE TABLE `USER_MANUAL_ATTACHMENTS` (
ID BIGINT NOT NULL AUTO_INCREMENT,
USER_MANUAL_ID BIGINT,
ATTACHMENT_UUID VARCHAR(50) DEFAULT NULL,
FILE_URL TEXT DEFAULT NULL,
FILE_NAME VARCHAR(250) DEFAULT NULL,
FILE_TYPE VARCHAR(250) DEFAULT NULL,
STATUS VARCHAR(250) DEFAULT NULL,
CREATED_DATE DATE,
CREATED_BY BIGINT,
UPDATED_DATE DATE,
UPDATED_BY BIGINT,

PRIMARY KEY (`ID`),
FOREIGN KEY(USER_MANUAL_ID) REFERENCES `USER_MANUAL_LEVEL_THREE`(ID),
FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
) ;