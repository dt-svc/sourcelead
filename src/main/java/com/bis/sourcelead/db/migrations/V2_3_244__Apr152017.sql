DROP TABLE IF EXISTS `CONTRACTS`;
CREATE TABLE `CONTRACTS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  CONTRACT_TYPE varchar(100),
  CONTRACT_TITLE varchar(100),
  TYPE_OF_CONTRACT  varchar(100),
  TEMPLATE_ID BIGINT,
  OWNER_USER_ID BIGINT,
  START_DATE DATETIME,
  END_DATE DATETIME,
  INITIATOR_TYPE varchar(100),
  ORG_LOCATION_ID BIGINT,
  CONTRACT_ORG_LOCATION_ID BIGINT,
  CONTACT_USER_ID BIGINT,
  ORG_RELATION_ID BIGINT,
  STATE_OF_JURISDICTION  varchar(100),
  APPROVER_USER_ID BIGINT,
  DESCRIPTION TEXT DEFAULT NULL, 
  BILLING_AMOUNT  varchar(100),
  BILLING_PER  varchar(100),
  INVOICE_FREQUENCY varchar(100),
  PAYMENT_TERM varchar(100),
  TAX varchar(100),
  TAX_TYPE varchar(100),
  STATUS varchar(100),
  CREATED_DATE DATETIME,
  CREATED_BY VARCHAR(50),
  UPDATED_DATE DATETIME,
  UPDATED_BY VARCHAR(50),
  TEMPLATE_SUBMISSION_STATUS VARCHAR(50),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(TEMPLATE_ID) REFERENCES `CONTRACTS_TEMPLATE`(ID),
  FOREIGN KEY(OWNER_USER_ID) REFERENCES `USER`(ID),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(CONTRACT_ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID), 
  FOREIGN KEY(CONTACT_USER_ID) REFERENCES `USER`(ID),
  FOREIGN KEY(ORG_RELATION_ID) REFERENCES `ORG_RELATIONS`(ID),
  FOREIGN KEY(APPROVER_USER_ID) REFERENCES `USER`(ID)

) ;