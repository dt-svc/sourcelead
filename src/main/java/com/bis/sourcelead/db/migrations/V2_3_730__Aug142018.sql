DROP TABLE IF EXISTS `INVOICE_TIMELINE_HISTORY`;
CREATE TABLE `INVOICE_TIMELINE_HISTORY` (
	ID BIGINT NOT NULL AUTO_INCREMENT,
	INVOICE_ID BIGINT(20),
	ORG_LOCATION_ID BIGINT(20),
	ORG_RELATION_ID BIGINT(20),
	CONTACT_USER_ID BIGINT(20),
	OWNER_USER_ID BIGINT(20),
	CREATED_DATE DATETIME,
	CREATED_BY BIGINT(20),
	LINKED_CHILD_INVOICE_ID BIGINT(20),
	INVOICE_STATUS VARCHAR(20),
	INVOICE_PAYMENT_REMINDER_ID BIGINT(20),
	INVOICE_PAYMENT_REMINDER_STATUS VARCHAR(20),
	INVOICE_PAYMENT_REMINDER_EMAIL_BODY TEXT,
	INVOICE_PAYMENT_REMINDER_EMAIL_FROM VARCHAR(200),
	INVOICE_PAYMENT_REMINDER_EMAIL_TO VARCHAR(200),
	INVOICE_PAYMENT_REMINDER_EMAIL_SUBJECT VARCHAR(200),
    REASON TEXT,
	
	PRIMARY KEY (`ID`),
    FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID), 
	FOREIGN KEY(INVOICE_ID) REFERENCES `INVOICE`(ID), 
    FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID), 
    FOREIGN KEY(ORG_RELATION_ID) REFERENCES `ORG_RELATIONS`(ID),
    FOREIGN KEY(CONTACT_USER_ID) REFERENCES `USER`(ID),
    FOREIGN KEY(OWNER_USER_ID) REFERENCES `USER`(ID),
	FOREIGN KEY(LINKED_CHILD_INVOICE_ID) REFERENCES `INVOICE`(ID)
);