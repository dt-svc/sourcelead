#Users By DepartmentId View 

CREATE OR REPLACE VIEW ASSOCIATES_DEPARTMENT_VIEW AS
SELECT user.ID,
      user.FIRST_NAME,
      user.LAST_NAME,
      emp.DEPARTMENT_ID,
      emp.EMPLOYMENT_TYPE,
      emp.EMPLOYEE_ID,     
      emp.ORG_LOCATIONS_ID as EMP_ORGLOCATION_ID,
      uRole.ROLE_ID,
      uRole.ORG_LOCATIONS_ID,
      uRole.USER_STATE,
      role.DISPLAY_NAME
FROM USER user
INNER JOIN USER_ROLE uRole ON user.ID = uRole.USER_ID
INNER JOIN EMPLOYEE emp ON emp.USER_ID = uRole.USER_ID
INNER JOIN ROLES role ON uRole.ROLE_ID = role.ID;


