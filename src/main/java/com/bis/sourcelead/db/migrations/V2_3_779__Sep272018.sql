	ID BIGINT NOT NULL AUTO_INCREMENT,
	ASSOCIATE_BANK_ID BIGINT,
	PAYROLL_ID BIGINT,
	BANK_NAME VARCHAR(100),
	ACCOUNT_NUMBER VARCHAR(100),
	ROUTING_NUMBER VARCHAR(100),
	ACCOUNT_TYPE VARCHAR(50),
	BANK_DATA_HIS_UUID VARCHAR(20),
	STATUS INT,
	CREATED_DATE DATE,
	CREATED_BY BIGINT,
	UPDATED_DATE DATE,
	UPDATED_BY BIGINT,
	PRIMARY KEY (`ID`),
	FOREIGN KEY(PAYROLL_ID) REFERENCES `US_EMP_PAYROLL`(ID) 
	) ;


