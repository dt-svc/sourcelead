	#ASSOCIATE_TAX_DED_CONTRI_VIEW
	CREATE OR REPLACE VIEW ASSOCIATE_TAX_DED_CONTRI_VIEW AS 
      SELECT can.ID as CANDIDATE_ID,
      		 at.ID AS ASSOCIATE_TAX_ID,
      		 at.SUPPLEMENT_TYPE,
             at.FEDERAL_TAX_FILLIING_STATUS,
             at.FEDERAL_TAX_ALLOWANCES,
             at.FEDERAL_TAX_ADDITIONNAL_WITH_HOLDING,
             at.STATE_TAX_FILLIING_STATUS,
             at.STATE_TAX_ALLOWANCES,
             at.STATE_TAX_ADDITIONNAL_WITH_HOLDING,
             at.RESIDENCE_TAX_FILLIING_STATUS,
             at.RESIDENCE_TAX_ALLOWANCES,
             at.RESIDENCE_TAX_ADDITIONNAL_WITH_HOLDING,
             at.FEDERAL_EXEMPT,
             at.MEDIACARE_EXEMPT,
             at.SOCIAL_SECURITY_EXEMPT,
             at.FUTA_EXEMPT,
             at.SUTA_EXEMPT,
             at.LOCAL_TAX,
             at.LOCAL_TAX_STATE,
             at.ORG_LOCATION_ID AS TAX_LOCATION_ID,
             at.ASSOCIATE_TAX_UUID,
             ab.ID AS ASSOCIATE_BANK_ID,
             ab.ROUTING_NUMBER,
             ab.ACCOUNT_NUMBER,
             ab.ACCOUNT_TYPE,
             ab.BANK_NAME,
             ab.ORG_LOCATION_ID AS BANK_LOCATION_ID,
             ab.ASSOCIATE_BANK_UUID,
             assoS.ANNUAL_SALARY,
             assoS.HOURLY_RATE,
             assoS.PAY_TYPE,
             assoS.PAY_FREQUENCY
             
	FROM CANDIDATE can
	LEFT JOIN ASSOCIATE_TAX at ON can.ID = at.CANDIDATE_ID
	LEFT JOIN ASSOCIATE_BANK_DATA ab ON can.ID = ab.CANDIDATE_ID
	LEFT JOIN ASSOCIATE_SALARY assoS ON can.ID = assoS.CANDIDATE_ID;