#credit_debit_note entity
DROP TABLE IF EXISTS `CREDIT_DEBIT_NOTE`;
CREATE TABLE `CREDIT_DEBIT_NOTE`(
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_LOCATIONS_ID BIGINT DEFAULT NULL,
  ORG_RELATION_ID BIGINT DEFAULT NULL,
  RESPONDER_LOCATION_ID BIGINT DEFAULT NULL,
  INVOICE_BILL_ID BIGINT DEFAULT NULL,
  CONTACT_USER_ID BIGINT DEFAULT NULL,
  OWNER_USER_ID BIGINT DEFAULT NULL,
  ORG_SPOC_ID BIGINT DEFAULT NULL,
  PARENT_NOTE_ID BIGINT DEFAULT NULL,
  SUB_TOTAL DECIMAL(20,2),
  TOTAL DECIMAL(20,2),
  REASON TEXT,
  STATUS VARCHAR(50),
  BILLING_ADDRESS VARCHAR(250),
  NOTE_TYPE VARCHAR(50),
  NOTE_STATUS VARCHAR(100),
  SHIPPING_ADDRESS VARCHAR(250),
  REFERENCE_NUMBER VARCHAR(250),
  APPROVER_CHECK_BOX VARCHAR(10),
  APPROVERS VARCHAR(250),
  CREDIT_DEBIT_UUID VARCHAR(100),
  CREDIT_NOTE_DATE DATETIME,
  CREATED_DATE DATETIME,
  CREATED_BY BIGINT DEFAULT NULL,
  UPDATED_DATE DATETIME,
  UPDATED_BY BIGINT DEFAULT NULL,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_RELATION_ID) REFERENCES `ORG_RELATIONS`(ID),
  FOREIGN KEY(ORG_LOCATIONS_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(RESPONDER_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(ORG_SPOC_ID) REFERENCES `ORG_SPOC`(ID),
  FOREIGN KEY(INVOICE_BILL_ID) REFERENCES `INVOICE`(ID),
  FOREIGN KEY(OWNER_USER_ID) REFERENCES `USER`(ID),
  FOREIGN KEY(PARENT_NOTE_ID) REFERENCES `CREDIT_DEBIT_NOTE`(ID),
  FOREIGN KEY(CONTACT_USER_ID) REFERENCES `USER`(ID)
);

DROP TABLE IF EXISTS `CREDIT_DEBIT_LINE_ITEMS`;
CREATE TABLE `CREDIT_DEBIT_LINE_ITEMS`(
ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_LOCATIONS_ID BIGINT DEFAULT NULL,
  USER_ID BIGINT DEFAULT NULL,
  CREDIT_DEBIT_NOTE_ID BIGINT DEFAULT NULL,
  INLINE_DESCRIPTION TEXT,
  LINE_ITEM_DATE DATETIME,
  PRICE DECIMAL(20,2),
  TAX_TYPE VARCHAR(50),
  TAX_AMOUNT DECIMAL(20,2),
  QUANTITY VARCHAR(100),
  AMOUNT DECIMAL(20,2),
  TOTAL_AMOUNT DECIMAL(20,2),
  STATUS VARCHAR(50),
  CREATED_DATE DATETIME,
  CREATED_BY BIGINT DEFAULT NULL,
  UPDATED_DATE DATETIME,
  UPDATED_BY BIGINT DEFAULT NULL,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_LOCATIONS_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(CREDIT_DEBIT_NOTE_ID) REFERENCES `CREDIT_DEBIT_NOTE`(ID),
  FOREIGN KEY(USER_ID) REFERENCES `USER`(ID)
);

