
DROP TABLE IF EXISTS `sourcelead`.`PROJECT_PLANNING_REQUREST`;
CREATE TABLE `sourcelead`.`PROJECT_PLANNING_REQUREST` (
ID BIGINT NOT NULL AUTO_INCREMENT,      
REQUEST_ID VARCHAR(250),
PROJECT_ID BIGINT DEFAULT NULL,
DESCRIPTION LONGTEXT DEFAULT NULL,
APPROVER_USER_ID BIGINT DEFAULT NULL,
APPROVER_NAME VARCHAR(500) DEFAULT NULL,
REQUESTED_RESOURCES INT DEFAULT NULL,
ALLOCATED_RESOURCES INT DEFAULT NULL,
ESTIMATED_HOURS DOUBLE DEFAULT NULL,
ESTIMATED_BUDGET DOUBLE DEFAULT NULL,
ESTIMATED_BUDGET_CURRENCY VARCHAR(50) DEFAULT NULL,
REQUEST_STATUS VARCHAR(50) DEFAULT NULL,
REQUESTED_USER VARCHAR(500) DEFAULT NULL,
ORG_LOCATION_ID BIGINT DEFAULT NULL,
STATUS INT,
CREATED_DATE DATE,
CREATED_BY VARCHAR(10),
UPDATED_DATE DATE,
UPDATED_BY VARCHAR(10),
PRIMARY KEY (`ID`),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `sourcelead`.`ORG_LOCATIONS`(ID),
FOREIGN KEY(PROJECT_ID) REFERENCES `sourcelead`.`PROJECTS`(ID),
FOREIGN KEY(APPROVER_USER_ID) REFERENCES `sourcelead`.`USER`(ID)
);

DROP TABLE IF EXISTS `sourcelead`.`PROJECT_PLANNING_NEW_RESOURCE_REQUEST`;
CREATE TABLE `sourcelead`.`PROJECT_PLANNING_NEW_RESOURCE_REQUEST` (
ID BIGINT NOT NULL AUTO_INCREMENT,      
PROJECT_PLANNING_REQUREST_ID BIGINT DEFAULT NULL,
ROLE VARCHAR(250),
OTHER_ROLE VARCHAR(100),
NO_OF_RESOURCES INT DEFAULT NULL,
MIN_EXP INT DEFAULT NULL,
MAX_EXP INT DEFAULT NULL,
SKILLS TEXT DEFAULT NULL,
BILL_RATE VARCHAR(100) DEFAULT NULL,
PAY_RATE VARCHAR(100) DEFAULT NULL,
START_DATE DATE,
END_DATE DATETIME,
ESTIMATED_HOURS DOUBLE DEFAULT NULL,
ESTIMATED_BUDGET DOUBLE DEFAULT NULL,
ESTIMATED_BUDGET_CURRENCY VARCHAR(50) DEFAULT NULL,
CONSULTING_TYPE VARCHAR(50) DEFAULT NULL,
STATUS INT,
CREATED_DATE DATETIME,
CREATED_BY VARCHAR(10),
UPDATED_DATE DATETIME,
UPDATED_BY VARCHAR(10),
PRIMARY KEY (`ID`),
FOREIGN KEY(PROJECT_PLANNING_REQUREST_ID) REFERENCES `sourcelead`.`PROJECT_PLANNING_REQUREST`(ID)
);
