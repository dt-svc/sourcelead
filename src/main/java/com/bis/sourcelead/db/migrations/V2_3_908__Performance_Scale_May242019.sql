DROP TABLE IF EXISTS `PERFORMANCE_RATING_LEVEL`;
CREATE TABLE `PERFORMANCE_RATING_LEVEL`(
ID BIGINT NOT NULL AUTO_INCREMENT,
LEVEL_NAME VARCHAR(250) DEFAULT NULL,
DESCRIPTION LONGTEXT DEFAULT NULL,
ORG_LOCATION_ID BIGINT DEFAULT NULL,
UUID VARCHAR(50) DEFAULT NULL,
STATUS INT,
CREATED_DATE DATETIME,
CREATED_BY BIGINT DEFAULT NULL,
UPDATED_DATE DATETIME,
UPDATED_BY BIGINT DEFAULT NULL,
PRIMARY KEY (`ID`),
FOREIGN KEY (CREATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY (UPDATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
);



DROP TABLE IF EXISTS `PERFORMANCE_RATING_SCALE`;
CREATE TABLE `PERFORMANCE_RATING_SCALE`(
ID BIGINT NOT NULL AUTO_INCREMENT,
RATING_NAME VARCHAR(500) DEFAULT NULL,
SHORT_CODE VARCHAR(10) DEFAULT NULL,
RATING_LEVEL_ID BIGINT DEFAULT NULL,
RATING_SCALE_VALUE INT DEFAULT NULL,
DESCRIPTION LONGTEXT DEFAULT NULL,
ORG_LOCATION_ID BIGINT DEFAULT NULL,
UUID VARCHAR(50) DEFAULT NULL,
STATUS INT,
CREATED_DATE DATETIME,
CREATED_BY BIGINT DEFAULT NULL,
UPDATED_DATE DATETIME,
UPDATED_BY BIGINT DEFAULT NULL,
PRIMARY KEY (`ID`),
FOREIGN KEY (CREATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY (UPDATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY (RATING_LEVEL_ID) REFERENCES `PERFORMANCE_RATING_LEVEL`(ID),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
);