
DROP TABLE IF EXISTS `sourcelead`.`MASTER_CANDIDATE`;
CREATE TABLE `sourcelead`.`MASTER_CANDIDATE` (
ID BIGINT NOT NULL AUTO_INCREMENT,
FIRST_NAME VARCHAR(250),
LAST_NAME VARCHAR(250) DEFAULT NULL,
EMAIL VARCHAR(250),
ALTERNATE_EMAIL VARCHAR(250) DEFAULT NULL,
PHNO VARCHAR(50) DEFAULT NULL,
ALTERNATE_PHNO VARCHAR(50) DEFAULT NULL,
STATUS INT,
CREATED_DATE DATETIME,
CREATED_BY VARCHAR(10),
UPDATED_DATE DATETIME,
UPDATED_BY VARCHAR(10),
PRIMARY KEY (`ID`)
);

CALL sourcelead.AlterTableAddColumn ('sourcelead','CANDIDATE','MASTER_CANDIDATE_ID','BIGINT NULL AFTER `ID`');
ALTER TABLE sourcelead.`CANDIDATE` ADD CONSTRAINT `MASTER_CANDIDATE_ID_FK` FOREIGN KEY (`MASTER_CANDIDATE_ID`) REFERENCES `sourcelead`.`MASTER_CANDIDATE` (`ID`);



