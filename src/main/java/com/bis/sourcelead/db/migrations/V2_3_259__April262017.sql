
DROP TABLE IF EXISTS `OFF_BOARDING_TEMPLATE`;
CREATE TABLE `OFF_BOARDING_TEMPLATE` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  TEMPLATE_NAME VARCHAR(100) DEFAULT NULL,
  DESCRIPTION TEXT,
  TEMPLATE_UUID VARCHAR(20) DEFAULT NULL,
  CREATED_USER VARCHAR(200) DEFAULT NULL,
  TEMPLATE_STATUS VARCHAR(20) DEFAULT NULL,
  STATUS INT,
  ORG_LOCATION_ID BIGINT,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
  
) ;


DROP TABLE IF EXISTS `CANDIDATE_OFF_BOARDING`;
CREATE TABLE `CANDIDATE_OFF_BOARDING` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  USER_ID BIGINT,  
  FIRST_NAME VARCHAR(100) DEFAULT NULL,
  LAST_NAME VARCHAR(100) DEFAULT NULL,
  ADDRESS_1 TEXT,
  ADDRESS_2 TEXT,
  COUNTRY VARCHAR(200) DEFAULT NULL,
  STATE VARCHAR(200) DEFAULT NULL,
  CITY VARCHAR(200) DEFAULT NULL,
  ZIPCODE VARCHAR(20) DEFAULT NULL,
  MOBILE_NUMBER VARCHAR(20) DEFAULT NULL,
  EMAIL VARCHAR(100) DEFAULT NULL,
  ROLE VARCHAR(100) DEFAULT NULL,
  DATE_OF_JOIN DATE,
  END_DATE DATE,
  REASON VARCHAR(50) DEFAULT NULL,
  EXPLANATION TEXT,
  NOTICE_PERIOD VARCHAR(50) DEFAULT NULL,
  EFFECTIVE_DATE DATE,
  HAVE_TO_WORK_IN_NOTICE_PERIOD VARCHAR(10) NULL,
  OFFBOARD_TEMPLATE_ID TEXT,
  ORG_LOCATION_ID BIGINT,
  CANDIDATE_OFFBOARD_UUID VARCHAR(20) DEFAULT NULL,
  CANDIDATE_OFFBOARD_STATUS VARCHAR(20) DEFAULT NULL,
  OFFBOARD_SUBMITTED VARCHAR(10) DEFAULT NULL,
  SURVEY_EXPLANATION TEXT,
  SURVEY_REASON TEXT,
  RATING INT,
  WANTED_TO_SELL_PROPERTY VARCHAR(10) DEFAULT NULL,
  WANTED_TO_SUB_LEASE VARCHAR(10) DEFAULT NULL,
  LOOKING_FOR_PUBLIC_STORAGE VARCHAR(10) DEFAULT NULL,
  LOOKING_FOR_ACCOMMODATION VARCHAR(10) DEFAULT NULL,
  STATUS INT,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(USER_ID) REFERENCES `USER`(ID),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
) ;


DROP TABLE IF EXISTS `OFF_BOARDING_DOCUMENTS`;
CREATE TABLE `OFF_BOARDING_DOCUMENTS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  OFF_BOARDING_TEMPLATE_ID BIGINT,
  CANDIDATE_OFF_BOARDING_ID BIGINT,
  DOCUMENT_TYPE VARCHAR(50) DEFAULT NULL,
  DOC_FILE MEDIUMBLOB,
  FILE_CONTENT_TYPE VARCHAR(500),
  FILE_NAME TEXT,
  DOCUMENT_STATUS VARCHAR(50) DEFAULT NULL,
  DOCUMENT_UUID VARCHAR(20) DEFAULT NULL,
  STATUS INT,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(OFF_BOARDING_TEMPLATE_ID) REFERENCES `OFF_BOARDING_TEMPLATE`(ID),
  FOREIGN KEY(CANDIDATE_OFF_BOARDING_ID) REFERENCES `CANDIDATE_OFF_BOARDING`(ID)
 
) ;


DROP TABLE IF EXISTS `OFFBOARD_TASKS`;
CREATE TABLE `OFFBOARD_TASKS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  TASK_NAME VARCHAR(100) DEFAULT NULL,
  OFF_BOARDING_TEMPLATE_ID BIGINT,
  CANDIDATE_OFF_BOARDING_ID BIGINT,
  ASSIGN_TO_USERS VARCHAR(500) DEFAULT NULL,
  ASSIGN_TO_CANDIDATE VARCHAR(10) DEFAULT NULL,
  PRIORITY VARCHAR(20) DEFAULT NULL,
  DUE_AFTER_MONTHS INT,
  DUE_AFTER_DAYS INT,
  DUE_AFTER_HOURS INT,
  DUE_AFTER_MINUTES INT,
  TASK_REPEAT VARCHAR(20) DEFAULT NULL,
  TASK_EMAIL VARCHAR(10) DEFAULT NULL,
  TASK_NOTIFICATION VARCHAR(10) DEFAULT NULL,
  DESCRIPTION TEXT DEFAULT NULL,
  STATUS INT,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(OFF_BOARDING_TEMPLATE_ID) REFERENCES `OFF_BOARDING_TEMPLATE`(ID),
  FOREIGN KEY(CANDIDATE_OFF_BOARDING_ID) REFERENCES `CANDIDATE_OFF_BOARDING`(ID)
); 


