CREATE OR REPLACE VIEW EXPENSE_APPOVER_VIEW AS
SELECT
    E.ID AS EXPENSE_ID,
    
    (SELECT GROUP_CONCAT(EMP.EMPLOYEE_ID SEPARATOR '') FROM EMPLOYEE EMP
		WHERE EMP.USER_ID =(
			SELECT C.CONSULTANT_USER_ID FROM CANDIDATE C WHERE C.ID =(
				SELECT PM.CANDIDATE_ID FROM PROJECT_MEMBERS PM WHERE PM.ID=E.PROJECT_MEMBERS_ID
			)
		)
	) AS EMP_ID,
    

    (SELECT C.DESIGNATION_TYPE FROM CANDIDATE C WHERE C.ID =(
		SELECT PM.CANDIDATE_ID FROM PROJECT_MEMBERS PM WHERE PM.ID=E.PROJECT_MEMBERS_ID
		)
	) AS EMPLOYMENT_TYPE,
    
    (SELECT CONCAT(C.FIRST_NAME, ' ', C.LAST_NAME) FROM CANDIDATE C WHERE C.ID=(SELECT PM.CANDIDATE_ID FROM PROJECT_MEMBERS PM WHERE PM.ID=E.PROJECT_MEMBERS_ID)) AS EMP_NAME,
    (SELECT P.PROJECT_NAME FROM PROJECTS P WHERE P.ID=E.PROJECT_ID) AS PROJECT_NAME,
	(SELECT P.ID FROM PROJECTS P WHERE P.ID=E.PROJECT_ID) AS PROJECT_ID,
    (SELECT CONCAT(P.START_DATE, ' -- ', P.END_DATE) FROM PROJECTS P WHERE P.ID=E.PROJECT_ID) AS DURATION,
    (SELECT P.EXPENSE_APPROVAL_TYPE FROM PROJECTS P WHERE P.ID=E.PROJECT_ID) AS APPROVAL_MECHANISM,
    (SELECT GROUP_CONCAT(EPAH.APPROVER_USER_ID SEPARATOR ', ') FROM EXPENSE_PROJECT_APPROVER_HIERARCHY EPAH WHERE EPAH.PROJECT_ID=E.PROJECT_ID AND EPAH.LEVEL=1) AS LEVEL_1,
    (SELECT GROUP_CONCAT(EPAH.APPROVER_USER_ID SEPARATOR ', ') FROM EXPENSE_PROJECT_APPROVER_HIERARCHY EPAH WHERE EPAH.PROJECT_ID=E.PROJECT_ID AND EPAH.LEVEL=2) AS LEVEL_2,
    (SELECT GROUP_CONCAT(CONCAT(U.FIRST_NAME,' ', U.LAST_NAME) SEPARATOR ', ') FROM USER U WHERE U.ID IN (SELECT EPAH.APPROVER_USER_ID FROM EXPENSE_PROJECT_APPROVER_HIERARCHY EPAH WHERE EPAH.PROJECT_ID=E.PROJECT_ID AND EPAH.LEVEL=1)) AS LEVEL_1_NAME,
    (SELECT GROUP_CONCAT(CONCAT(U.FIRST_NAME,' ', U.LAST_NAME) SEPARATOR ', ') FROM USER U WHERE U.ID IN (SELECT EPAH.APPROVER_USER_ID FROM EXPENSE_PROJECT_APPROVER_HIERARCHY EPAH WHERE EPAH.PROJECT_ID=E.PROJECT_ID AND EPAH.LEVEL=2)) AS LEVEL_2_NAME,
    (SELECT GROUP_CONCAT(EAH.ACTIONPERFORMEDBY SEPARATOR ', ') FROM EXPENSES_APPROVER_HIERARCHY EAH WHERE EAH.EXPENSESID=E.ID) AS ACTION_PERFORMED_BY,
    E.SUBMITTED_DATE AS SUBMITTED_DATE,
	E.Total_Submitted_Amount AS SUBMITTED_AMOUNT
FROM EXPENSES E
WHERE E.EXPENSE_STATUS='SUBMITTED';