DROP TABLE IF EXISTS `EMAIL_REMINDER`;
CREATE TABLE `EMAIL_REMINDER`(
ID BIGINT NOT NULL AUTO_INCREMENT,
SCENARIO_NAME VARCHAR(20),
SCENARIO_ID BIGINT,
NOTIFY_TO TEXT,
ORG_LOCATIONS_ID BIGINT DEFAULT NULL,
TABS_ID BIGINT DEFAULT NULL,
STATUS INT,
CREATED_DATE DATE,
CREATED_BY BIGINT DEFAULT NULL,
UPDATED_DATE DATETIME,
UPDATED_BY BIGINT DEFAULT NULL,
PRIMARY KEY (`ID`),
FOREIGN KEY (CREATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY (UPDATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY(ORG_LOCATIONS_ID) REFERENCES `ORG_LOCATIONS`(ID),
FOREIGN KEY(TABS_ID) REFERENCES `TABS`(ID)
);

DROP TABLE IF EXISTS `EMAIL_REMINDER_HIERARCHY`;
CREATE TABLE `EMAIL_REMINDER_HIERARCHY`(
ID BIGINT NOT NULL AUTO_INCREMENT,
EMAIL_REMINDER_ID BIGINT,
REMINDER_DAYS BIGINT,
REMINDER_TIME VARCHAR(20),
REMINDER_HIERARCHY VARCHAR(150),
STATUS INT,
CREATED_DATE DATE,
CREATED_BY BIGINT DEFAULT NULL,
UPDATED_DATE DATETIME,
UPDATED_BY BIGINT DEFAULT NULL,
PRIMARY KEY (ID),
FOREIGN KEY (CREATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY (UPDATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY (EMAIL_REMINDER_ID) REFERENCES `EMAIL_REMINDER`(ID)
);