#PAY_ADJUSTMENT_HISTORY
DROP TABLE IF EXISTS `PAY_ADJUSTMENT_HISTORY`;
CREATE TABLE `PAY_ADJUSTMENT_HISTORY` (
ID BIGINT NOT NULL AUTO_INCREMENT,
PAYROLL_ID BIGINT,
PRE_REGULAR_HOURS VARCHAR(20),
PRE_REGULAR_HOURS_AMOUNT DECIMAL(20,2),
PRE_OVERTIME_HOURS VARCHAR(20),
PRE_OVERTIME_HOURS_AMOUNT DECIMAL(20,2),
REGULAR_HOURS VARCHAR(20),
REGULAR_HOURS_AMOUNT DECIMAL(20,2),
OVERTIME_HOURS VARCHAR(20),
OVERTIME_HOURS_AMOUNT DECIMAL(20,2),
STATUS int,
CREATED_DATE DATE,
CREATED_BY BIGINT,
UPDATED_DATE DATE,
UPDATED_BY BIGINT,
PRIMARY KEY (`ID`),
FOREIGN KEY(PAYROLL_ID) REFERENCES `US_EMP_PAYROLL`(ID)
) ;

#PAY_ADJUSTMENT_DED_HISTORY
DROP TABLE IF EXISTS `PAY_ADJUSTMENT_DED_HISTORY`;
CREATE TABLE `PAY_ADJUSTMENT_DED_HISTORY` (
ID BIGINT NOT NULL AUTO_INCREMENT,
PAY_ADJUSTMENT_HISTORY_ID BIGINT,
DEDUCTION_ID BIGINT,
CONTRIBUTION_ID BIGINT,
PRE_DEDUCTION_TYPE VARCHAR(20),
PRE_DEDUCTION_AMOUNT DECIMAL(20,2),
DEDUCTION_TYPE VARCHAR(20),
DEDUCTION_AMOUNT DECIMAL(20,2),
PRE_CONTRIBUTION_TYPE VARCHAR(20),
PRE_CONTRIBUTION_AMOUNT DECIMAL(20,2),
CONTRIBUTION_TYPE VARCHAR(20),
CONTRIBUTION_AMOUNT DECIMAL(20,2),
PRIMARY KEY (`ID`),
FOREIGN KEY(PAY_ADJUSTMENT_HISTORY_ID) REFERENCES `PAY_ADJUSTMENT_HISTORY`(ID)
) ;


