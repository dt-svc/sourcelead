DROP TABLE IF EXISTS `CANDIDATE_SOURCE`;
CREATE TABLE `CANDIDATE_SOURCE` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_LOCATION_ID BIGINT,
  NAME VARCHAR(100)  DEFAULT NULL,
  DESCRIPTION VARCHAR(5000) DEFAULT NULL,
  STATUS INTEGER(11),
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
) ;

ALTER TABLE `CANDIDATE` 
ADD COLUMN `CANDIDATE_SOURCE` VARCHAR(100) NULL AFTER `IS_SHARED_IN_MARKETPLACE`;
