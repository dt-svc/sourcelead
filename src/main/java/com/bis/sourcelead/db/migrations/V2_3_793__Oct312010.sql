#US_PAYROLL_SCHEDULE

DROP TABLE IF EXISTS `US_PAYROLL_SCHEDULE`;
CREATE TABLE `US_PAYROLL_SCHEDULE` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_LOCATION_ID BIGINT,
  PAY_FREQUENCY  VARCHAR(20),
  PAY_PERIOD_START_DATE DATE,
  PAY_CHECK_DATE DATE,
  RUN_PAYROLL_DATE DATE,
  NEXT_PAY_MONTH varchar(45),
  STATUS int,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
) ;


#USPAY_SCHEDULE_NOTIFY_MEMBERS

DROP TABLE IF EXISTS `USPAY_SCHEDULE_NOTIFY_MEMBER`;
CREATE TABLE `USPAY_SCHEDULE_NOTIFY_MEMBER` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  US_PAYROLL_SCHEDULE_ID BIGINT,
  USER_ID  BIGINT,
  STATUS int,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(US_PAYROLL_SCHEDULE_ID) REFERENCES `US_PAYROLL_SCHEDULE`(ID)
) ;