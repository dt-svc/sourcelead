CREATE OR REPLACE VIEW LCA_LIST_VIEW AS
SELECT 
        TEMP.ID,
        TEMP.ORG_LOCATION_ID,
        TEMP.LCAT_NO,
        TEMP.LCA_TITLE,
        TEMP.PREVAILING_WAGE,
        TEMP.LCA_STATUS,
        TEMP.START_DATE,
        TEMP.END_DATE,
        TEMP.JOB_TITLE,
        TEMP.WAGES_LEVEL,
        TEMP.CREATED_DATE,
        TEMP.STATUS,
		TEMP.LCA_UUID,
        GROUP_CONCAT(LCAEMPT.LOCATION) AS LOCATION
        
    FROM
         `LCA` TEMP,
         `LCA_PLACE_OF_EMPLOYMENT` LCAEMPT
         WHERE  LCAEMPT.LCA_ID = TEMP.ID
         
         GROUP BY TEMP.ID
         
         ORDER BY TEMP.UPDATED_DATE DESC;
