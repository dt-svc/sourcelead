DROP TABLE IF EXISTS `USER_DROPPED_HOLIDAYS`;
CREATE TABLE `USER_DROPPED_HOLIDAYS` (
  ID BIGINT NOT NULL AUTO_INCREMENT, 
  USER_ID BIGINT DEFAULT NULL,
  LOCATION_ID BIGINT DEFAULT NULL,
  HOLIDAY_ID BIGINT DEFAULT NULL,
  STATUS int,
  CREATED_DATE DATETIME,
  CREATED_BY BIGINT,
  UPDATED_DATE DATETIME,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(HOLIDAY_ID) REFERENCES `HOLIDAY`(ID),
  FOREIGN KEY(LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(USER_ID) REFERENCES `USER`(ID)
);