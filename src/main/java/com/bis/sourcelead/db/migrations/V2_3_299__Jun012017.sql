DROP TABLE IF EXISTS `sourcelead`.`CONTRACT_REQUEST_DOCUMENTS`;
CREATE TABLE `sourcelead`.`CONTRACT_REQUEST_DOCUMENTS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  CONTRACT_ID BIGINT,
  DESCRIPTION TEXT DEFAULT NULL,
  DOC_FILE MEDIUMBLOB NULL,
  FILE_NAME TEXT NULL,
  FILE_TYPE VARCHAR(250) NULL,
  STATUS VARCHAR(20) NULL,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(100),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(100),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(CONTRACT_ID) REFERENCES `sourcelead`.`CONTRACTS`(ID)
);
