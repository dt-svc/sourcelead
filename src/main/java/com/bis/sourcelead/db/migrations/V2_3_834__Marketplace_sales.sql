# Candidate_Marketplace_sales_order_Table

DROP TABLE IF EXISTS `CANDIDATE_MARKET_PLACE_SALES_ORDER`;
CREATE TABLE `CANDIDATE_MARKET_PLACE_SALES_ORDER`(
ID BIGINT NOT NULL AUTO_INCREMENT,
ORDER_NO TEXT DEFAULT NULL,
COMPANY_NAME VARCHAR(45) DEFAULT NULL,
PAYMENT_STATUS VARCHAR(10) DEFAULT NULL,
PAYMENT_ID TEXT DEFAULT NULL,
ORG_LOCATION_ID BIGINT DEFAULT NULL,
TOTAL_RESUME_PRICE DOUBLE DEFAULT NULL,
NO_OF_RESUMES VARCHAR(45) DEFAULT NULL,
MARKET_PLACE_ID BIGINT NOT NULL,
SALES_UUID VARCHAR(50),
DESCRIPTION VARCHAR(255),
ORDER_DATE DATE,

PRIMARY KEY (`ID`), 

FOREIGN KEY(MARKET_PLACE_ID) REFERENCES `CANDIDATE_MARKET_PLACE`(ID)
);
