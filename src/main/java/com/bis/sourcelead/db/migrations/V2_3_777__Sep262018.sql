DROP TABLE IF EXISTS `ASSOCIATE_PAYROLL_PAYHEAD_HISTORY`;
DROP TABLE IF EXISTS `IND_EMPLOYEE_PAYROLL`;
DROP TABLE IF EXISTS `IND_PAY_SHEET_FREQUENCY`;

#IND_PAY_SHEET_FREQUENCY
CREATE TABLE `IND_PAY_SHEET_FREQUENCY` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_LOCATION_ID BIGINT,
  GROUP_ID BIGINT,
  FREQUENCY_START_DATE DATE,
  FREQUENCY_END_DATE  DATE,
  PAY_CHECK_DATE  DATE,
  PAY_SHEET_FREQUENCY_UUID  VARCHAR(10),
  ACTIONPERFORMEDBY TEXT,
  APPROVER_STATUS varchar(45),
  STATUS int,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(GROUP_ID) REFERENCES `USER_GROUP`(ID)
) ;

#IND_EMPLOYEE_PAYROLL
CREATE TABLE `IND_EMPLOYEE_PAYROLL` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  EMPLOYEE_ID BIGINT,
  CANDIDATE_ID BIGINT,
  IND_PAY_SHEET_FREQUENCY_ID BIGINT,
  EMP_PAY_RATE DECIMAL(20,2),
  REGULAR_HOURS VARCHAR(20),
  OVER_TIME_AMOUNT DECIMAL(20,2),
  OVER_TIME_HOURS VARCHAR(20),
  NO_OF_DAYS DECIMAL(20,2),
  NO_OF_LEAVES DECIMAL(20,2),
  GROSS_PAY DECIMAL(20,2),
  NET_PAY DECIMAL(20,2),
  PROFESSIONAL_TAX DECIMAL(20,2),
  TDS DECIMAL(20,2),
  SUBMIT_FOR_APROVER_STATUS VARCHAR(20),
  
  STATUS INT,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(IND_PAY_SHEET_FREQUENCY_ID) REFERENCES `IND_PAY_SHEET_FREQUENCY`(ID),
  FOREIGN KEY(EMPLOYEE_ID) REFERENCES `EMPLOYEE`(ID),
  FOREIGN KEY(CANDIDATE_ID) REFERENCES `CANDIDATE`(ID)
);

CREATE TABLE `ASSOCIATE_PAYROLL_PAYHEAD_HISTORY` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  IND_EMPLOYEE_PAYROLL_ID BIGINT,
  PAYROLL_PAYHEAD BIGINT,
  MONTHLY DECIMAL(20,2),
  ANNUALY DECIMAL(20,2),
  STATUS int,
  UUID VARCHAR(20) DEFAULT NULL,
  CREATED_DATE DATETIME,
  CREATED_BY BIGINT,
  UPDATED_DATE DATETIME,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(IND_EMPLOYEE_PAYROLL_ID) REFERENCES `IND_EMPLOYEE_PAYROLL`(ID),
  FOREIGN KEY(PAYROLL_PAYHEAD) REFERENCES `PAYROLL_PAYHEAD`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
);

