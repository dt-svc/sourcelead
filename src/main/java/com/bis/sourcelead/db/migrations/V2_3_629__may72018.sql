
DROP TABLE IF EXISTS `ORGLOCATION_INFORMATION_DETAILS`;
CREATE TABLE `ORGLOCATION_INFORMATION_DETAILS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORGLOCATION_ID BIGINT,
  CIN VARCHAR(100),
  GSTIN  VARCHAR(100),
  INCORPORATION_DATE DATE,
  PAN VARCHAR(100),
  TAN VARCHAR(100),
  TDS VARCHAR(100),
  PF_NUMBER VARCHAR(100), 
  PF_REGISTRATION_DATE DATE,
  ESI_NUMBER VARCHAR(100), 
  ESI_REGISTRATION_DATE DATE,
  PT_NUMBER VARCHAR(100), 
  PT_REGISTRATION_DATE DATE,
  UUID VARCHAR(20),
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORGLOCATION_ID) REFERENCES `USER`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
);