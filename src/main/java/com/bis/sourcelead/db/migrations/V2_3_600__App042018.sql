
#TimesheetSummary

DROP TABLE IF EXISTS `TIMESHEET_SUMMARY`;
CREATE TABLE `TIMESHEET_SUMMARY` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  PROJECT_MEMBER_ID BIGINT DEFAULT NULL,
  MONTH_YEAR_FREQUENCY VARCHAR(50) DEFAULT NULL,
  START_DATE DATE,
  END_DATE DATE,
  PAY_RATE FLOAT,
  NO_OF_WEEKS BIGINT(20),
  WEEK_1_FREQUENCY VARCHAR(50) DEFAULT NULL,
  WEEK_2_FREQUENCY VARCHAR(50) DEFAULT NULL,
  WEEK_3_FREQUENCY VARCHAR(50) DEFAULT NULL,
  WEEK_4_FREQUENCY VARCHAR(50) DEFAULT NULL,
  WEEK_5_FREQUENCY VARCHAR(50) DEFAULT NULL,
  WEEK_6_FREQUENCY VARCHAR(50) DEFAULT NULL,
  
  WEEK_1_TOTAL_HOURS FLOAT DEFAULT NULL,
  WEEK_2_TOTAL_HOURS FLOAT DEFAULT NULL,
  WEEK_3_TOTAL_HOURS FLOAT DEFAULT NULL,
  WEEK_4_TOTAL_HOURS FLOAT DEFAULT NULL,
  WEEK_5_TOTAL_HOURS FLOAT DEFAULT NULL,
  WEEK_6_TOTAL_HOURS FLOAT DEFAULT NULL,
  
  WEEK_1_BILLABLE_HOURS FLOAT DEFAULT NULL,
  WEEK_2_BILLABLE_HOURS FLOAT DEFAULT NULL,
  WEEK_3_BILLABLE_HOURS FLOAT DEFAULT NULL,
  WEEK_4_BILLABLE_HOURS FLOAT DEFAULT NULL,
  WEEK_5_BILLABLE_HOURS FLOAT DEFAULT NULL,
  WEEK_6_BILLABLE_HOURS FLOAT DEFAULT NULL,
  
  WEEK_1_NON_BILLABLE_HOURS FLOAT DEFAULT NULL,
  WEEK_2_NON_BILLABLE_HOURS FLOAT DEFAULT NULL,
  WEEK_3_NON_BILLABLE_HOURS FLOAT DEFAULT NULL,
  WEEK_4_NON_BILLABLE_HOURS FLOAT DEFAULT NULL,
  WEEK_5_NON_BILLABLE_HOURS FLOAT DEFAULT NULL,
  WEEK_6_NON_BILLABLE_HOURS FLOAT DEFAULT NULL,
    
  WEEK_1_APPROVAL_STATUS VARCHAR(50) DEFAULT NULL,
  WEEK_2_APPROVAL_STATUS VARCHAR(50) DEFAULT NULL,
  WEEK_3_APPROVAL_STATUS VARCHAR(50) DEFAULT NULL,
  WEEK_4_APPROVAL_STATUS VARCHAR(50) DEFAULT NULL,
  WEEK_5_APPROVAL_STATUS VARCHAR(50) DEFAULT NULL,
  WEEK_6_APPROVAL_STATUS VARCHAR(50) DEFAULT NULL,
  
  STATUS BIGINT(20) DEFAULT NULL,
  CREATED_BY BIGINT DEFAULT NULL,
  CREATED_DATE DATE,
  UPDATED_BY BIGINT DEFAULT NULL,
  UPDATED_DATE DATE,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(PROJECT_MEMBER_ID) REFERENCES `PROJECT_MEMBERS`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID)
) ;