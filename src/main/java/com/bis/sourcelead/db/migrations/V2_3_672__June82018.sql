CREATE TABLE `JOB_BOARD` (
  `ID` INT NOT NULL AUTO_INCREMENT,
  `NAME` VARCHAR(50) NOT NULL,
  `LOGO_URL` VARCHAR(500) NULL,
  `CREATED_DATE` date DEFAULT NULL,
  `CREATED_BY` varchar(20) DEFAULT NULL,
  `UPDATED_DATE` date DEFAULT NULL,
  `UPDATED_BY` varchar(20) DEFAULT NULL,
  PRIMARY KEY (`ID`));


CREATE TABLE `ORG_JOB_BOARD` (
  `ID` BIGINT(20) NOT NULL AUTO_INCREMENT,
  `JOB_BOARD_ID` INT NOT NULL,
  `ORG_ID` BIGINT(20) NOT NULL,
  `ACTIVE` BIT(1) NOT NULL,
  `CREATED_DATE` date DEFAULT NULL,
  `CREATED_BY` varchar(20) DEFAULT NULL,
  `UPDATED_DATE` date DEFAULT NULL,
  `UPDATED_BY` varchar(20) DEFAULT NULL,
  PRIMARY KEY (`ID`),
  INDEX `ORG_JOB_BOARD_ORG_ID_FK1_idx` (`ORG_ID` ASC),
  CONSTRAINT `ORG_JOB_BOARD_ORG_ID_FK1`
    FOREIGN KEY (`ORG_ID`)
    REFERENCES `ORG` (`ID`)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION);


CREATE TABLE `ORG_JOB_BOARD_ACCOUNT` (
  `ID` BIGINT(20) NOT NULL AUTO_INCREMENT,
  `ORG_JOB_BOARD_ID` BIGINT(20) NOT NULL,
  `ORG_ID` BIGINT(20) NOT NULL,
  `NAME` VARCHAR(50) NOT NULL,
  `USERNAME` VARCHAR(100) NULL,
  `PASSWORD` VARCHAR(100) NULL,
  `API_KEY` VARCHAR(500) NULL,
  `ACCESS_TOKEN` VARCHAR(500) NULL,
  `ACCOUNT_ID` VARCHAR(100) NULL,
  `ACTIVE` BIT(1) NOT NULL DEFAULT 1,
  `ACCESS_TO_ALL` BIT(1) NOT NULL DEFAULT 1,
  `CREATED_DATE` date DEFAULT NULL,
  `CREATED_BY` varchar(20) DEFAULT NULL,
  `UPDATED_DATE` date DEFAULT NULL,
  `UPDATED_BY` varchar(20) DEFAULT NULL,
  PRIMARY KEY (`ID`),
  INDEX `ORG_JOB_BOARD_ACCOUNT_ORG_JOB_BOARD_ID_FK1_idx` (`ORG_ID` ASC),
  CONSTRAINT `ORG_JOB_BOARD_ACCOUNT_ORG_JOB_BOARD_ID_FK1`
    FOREIGN KEY (`ORG_JOB_BOARD_ID`)
    REFERENCES `ORG_JOB_BOARD` (`ID`)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION,
  INDEX `ORG_JOB_BOARD_ACCOUNT_ORG_FK1_idx` (`ORG_JOB_BOARD_ID` ASC),
  CONSTRAINT `ORG_JOB_BOARD_ACCOUNT_ORG_FK1`
    FOREIGN KEY (`ORG_ID`)
    REFERENCES `ORG` (`ID`)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION);

CREATE TABLE `ORG_JOB_BOARD_ACCOUNT_USER` (
  `ID` BIGINT(20) NOT NULL AUTO_INCREMENT,
  `ORG_JOB_BOARD_ACCOUNT_ID` BIGINT(20) NOT NULL,
  `USER_ID` BIGINT(20),
  `TEAM_ID` BIGINT(20),
  `CREATED_DATE` date DEFAULT NULL,
  `CREATED_BY` varchar(20) DEFAULT NULL,
  `UPDATED_DATE` date DEFAULT NULL,
  `UPDATED_BY` varchar(20) DEFAULT NULL,
  PRIMARY KEY (`ID`),
  INDEX `ORG_JOB_BOARD_ACCOUNT_USER_ACCOUNT_ID_FK1_idx` (`ORG_JOB_BOARD_ACCOUNT_ID` ASC),
  CONSTRAINT `ORG_JOB_BOARD_ACCOUNT_USER_ACCOUNT_ID_FK1_idx`
    FOREIGN KEY (`ORG_JOB_BOARD_ACCOUNT_ID`)
    REFERENCES `ORG_JOB_BOARD_ACCOUNT` (`ID`)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION,
  INDEX `ORG_JOB_BOARD_ACCOUNT_USER_USER_ID_FK1_idx` (`USER_ID` ASC),
  CONSTRAINT `ORG_JOB_BOARD_ACCOUNT_USER_USER_ID_FK1_idx`
    FOREIGN KEY (`USER_ID`)
    REFERENCES `USER` (`ID`)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION,
  INDEX `ORG_JOB_BOARD_ACCOUNT_USERS_TEAM_ID_FK1_idx` (`TEAM_ID` ASC),
  CONSTRAINT `ORG_JOB_BOARD_ACCOUNT_USER_TEAM_ID_FK1_idx`
    FOREIGN KEY (`TEAM_ID`)
    REFERENCES `TEAM` (`ID`)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION);


