DROP TABLE IF EXISTS `REQUIREMENT_SUBMISSION_HISTORY`;
CREATE TABLE `REQUIREMENT_SUBMISSION_HISTORY` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  REQUIREMENT_SUBMISSION_ID BIGINT,
  FROM_STAGE VARCHAR(50) DEFAULT NULL,
  TO_STAGE VARCHAR(50) DEFAULT NULL,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(REQUIREMENT_SUBMISSION_ID) REFERENCES `REQUIREMENT_SUBMISSION`(ID)
) ;