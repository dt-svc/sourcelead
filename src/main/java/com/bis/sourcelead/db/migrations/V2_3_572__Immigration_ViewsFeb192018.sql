CREATE OR REPLACE VIEW IMMIGRATON_TEMPLATE_VIEW AS 
SELECT 
     TEMP.ID,
     TEMP.ORG_LOCATION_ID,
     TEMP.NAME,
     TEMP.DESCRIPTION,
     TEMP.STATUS,
     (select COUNT(DOCS.ID) from `SOURCELEAD`.`IMMIGRATION_TEMPLATE_DOCUMENTS` DOCS where TEMP.ID = DOCS.IMMIGRATION_TEMPLATE_ID) as DOCS_COUNT,
     (select COUNT(FORM.ID) from `SOURCELEAD`.`IMMIGRATION_TEMPLATE_FORMS` FORM where TEMP.ID = FORM.IMMIGRATION_TEMPLATE_ID) as FORMS_COUNT,
    (select count(TASK.ID) from `SOURCELEAD`.`IMMIGRATION_TEMPLATE_TASKS` TASK where TEMP.ID = TASK.IMMIGRATION_TEMPLATE_ID) as TASKS_COUNT
    FROM `SOURCELEAD`.`IMMIGRATION_TEMPLATE` TEMP