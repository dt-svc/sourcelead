
DROP TABLE IF EXISTS `PERFORMANCE_BADGES`;
CREATE TABLE `PERFORMANCE_BADGES` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  NAME VARCHAR(500),
  FILE_URL TEXT DEFAULT NULL,
  FILE_NAME TEXT DEFAULT NULL,
  FILE_CONTENT_TYPE TEXT DEFAULT NULL,
  DESCRIPTION LONGTEXT DEFAULT NULL,
  ORG_LOCATION_ID BIGINT,
  UUID VARCHAR(50) DEFAULT NULL,
  STATUS INT,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
) ;


DROP TABLE IF EXISTS `PERFORMANCE_FEEDBACK_TEMPLATE`;
CREATE TABLE `PERFORMANCE_FEEDBACK_TEMPLATE` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  NAME VARCHAR(500),
  DESCRIPTION LONGTEXT DEFAULT NULL,
  JSON_STRING LONGTEXT DEFAULT NULL,
  ORG_LOCATION_ID BIGINT,
  UUID VARCHAR(50) DEFAULT NULL,
  STATUS INT,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
) ;
