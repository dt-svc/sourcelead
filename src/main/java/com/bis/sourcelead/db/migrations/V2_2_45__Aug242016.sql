DROP TABLE IF EXISTS `ORG_SPOC`;
CREATE TABLE `ORG_SPOC` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_RELATION_ID BIGINT DEFAULT NULL,
  SPOC_USER_ID BIGINT DEFAULT NULL,
  OWNER_USER_ID BIGINT DEFAULT NULL,
  INVITATION_STATUS VARCHAR(20) DEFAULT NULL,
  SPOC_STATUS VARCHAR(20) DEFAULT NULL,
  STATUS VARCHAR(20) DEFAULT NULL,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`), 
  FOREIGN KEY(ORG_RELATION_ID) REFERENCES `ORG_RELATIONS`(ID),
  FOREIGN KEY(SPOC_USER_ID) REFERENCES `USER`(ID),
  FOREIGN KEY(OWNER_USER_ID) REFERENCES `USER`(ID)
); 

ALTER TABLE `ORG_RELATIONS`
	CHANGE COLUMN `RELATION_TYPE` `INITIATOR_TYPE` VARCHAR(150) NULL DEFAULT NULL AFTER `LOCATION_ID`;
	
