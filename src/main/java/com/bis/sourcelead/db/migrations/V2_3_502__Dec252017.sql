DROP TABLE IF EXISTS `TIMESHEET_DAY_ENTRIES`;
CREATE TABLE `TIMESHEET_DAY_ENTRIES` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  SUBMISSION_ID BIGINT NOT NULL,
  PROJECT_TASK_ID BIGINT,
  TASK_TYPE VARCHAR(45),
  TIMESHEET_DATE  DATE DEFAULT NULL,
  BILLABLE_HOURS VARCHAR(100),
  NONBILLABLE_HOURS VARCHAR(100),
  TOTALHOURS VARCHAR(100),
  COMMENTS TEXT,
  CREATED_DATE DATETIME,
  CREATED_BY VARCHAR(100),
  UPDATED_DATE DATETIME,
  UPDATED_BY VARCHAR(100),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(SUBMISSION_ID) REFERENCES `TIMESHEET_SUBMISSIONS`(ID),
  FOREIGN KEY(PROJECT_TASK_ID) REFERENCES `PROJECT_TASKS`(ID)
) ;
  
  
  DROP TABLE IF EXISTS `TIMESHEET_DAY_ENTRIES_HISTORY`;
  CREATE TABLE `TIMESHEET_DAY_ENTRIES_HISTORY` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ENTRY_ID BIGINT NOT NULL,
  SUBMISSION_ID BIGINT,
  PROJECT_TASK_ID BIGINT,
  TASK_TYPE VARCHAR(45),
  TIMESHEET_DATE  DATE DEFAULT NULL,
  BILLABLE_HOURS VARCHAR(100),
  NONBILLABLE_HOURS VARCHAR(100),
  TOTALHOURS VARCHAR(100),
  COMMENTS TEXT,
  CREATED_DATE DATETIME,
  CREATED_BY VARCHAR(100),
  UPDATED_DATE DATETIME,
  UPDATED_BY VARCHAR(100),
   PRIMARY KEY (`ID`),
  FOREIGN KEY(ENTRY_ID) REFERENCES `TIMESHEET_DAY_ENTRIES`(ID),
  FOREIGN KEY(SUBMISSION_ID) REFERENCES `TIMESHEET_SUBMISSIONS`(ID),
  FOREIGN KEY(PROJECT_TASK_ID) REFERENCES `PROJECT_TASKS`(ID)
) ;