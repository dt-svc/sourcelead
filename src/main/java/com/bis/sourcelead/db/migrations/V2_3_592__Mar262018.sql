DROP TABLE IF EXISTS `SUBMISSION_APPROVER_HIERARCHY_HISTORY`;
CREATE TABLE `SUBMISSION_APPROVER_HIERARCHY_HISTORY` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  HIERARCHY_ID BIGINT,
  SUBMISSION_ID BIGINT,
  SUBMISSION_APPROVER_HIERARCHY_ID BIGINT,
  SUBMISSION_STATUS varchar(20),
  SUBMISSION_APPROVALSTATUS varchar(50),
  INVOICE_STATUS varchar(20),
  BILLING_STATUS varchar(20),
  INVOICE_DATE DATE,
  BILL_DATE DATE,
  INVOICE_ID BIGINT,
  BILL_ID BIGINT,
  FREQUENCY_START_DATE DATE,
  FREQUENCY_END_DATE DATE,
  REJECTED_REASON TEXT,
  ACTIONPERFORMEDBY TEXT,
  ACTION_BY_ORGLOC_ID BIGINT(20),
  MECHANISM_TYPE varchar(20),
  STATUS varchar(20),
  REOPENED_USER_ID BIGINT,
  REOPEN_REASON TEXT,
  REOPEN_REJECTED_REASON TEXT,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(HIERARCHY_ID) REFERENCES `PROJECT_APPROVER_HIERARCHY`(ID),
  FOREIGN KEY(SUBMISSION_ID) REFERENCES `TIMESHEET_SUBMISSIONS`(ID),
  FOREIGN KEY(REOPENED_USER_ID) REFERENCES `USER`(ID),
  FOREIGN KEY(INVOICE_ID) REFERENCES `INVOICE`(ID),
  FOREIGN KEY(SUBMISSION_APPROVER_HIERARCHY_ID) REFERENCES `SUBMISSION_APPROVER_HIERARCHY`(ID),
  FOREIGN KEY(INVOICE_ID) REFERENCES `INVOICE`(ID)
) ;
