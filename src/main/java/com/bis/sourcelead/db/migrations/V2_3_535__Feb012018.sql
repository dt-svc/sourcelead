
DROP TABLE IF EXISTS `sourcelead`.`REQUIREMENT_LOCATIONS`;
CREATE TABLE `sourcelead`.`REQUIREMENT_LOCATIONS` (
   ID BIGINT NOT NULL AUTO_INCREMENT,
   REQUIREMENT_ID BIGINT DEFAULT NULL,
   LOCATION TEXT DEFAULT NULL,
   COUNTRY VARCHAR(100) DEFAULT NULL,
   STATE VARCHAR(100) DEFAULT NULL,
   CITY VARCHAR(100) DEFAULT NULL,
   ZIPCODE VARCHAR(20) DEFAULT NULL,
   LONGITUDE VARCHAR(100) DEFAULT NULL,
   LATITUDE VARCHAR(100) DEFAULT NULL,
   LOCATION_UID VARCHAR(50) DEFAULT NULL,
   STATUS INT DEFAULT NULL,
   PRIMARY KEY (`ID`),
   FOREIGN KEY(REQUIREMENT_ID) REFERENCES `sourcelead`.`REQUIREMENT`(ID)
) ;
