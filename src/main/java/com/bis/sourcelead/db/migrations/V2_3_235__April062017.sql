DROP TABLE IF EXISTS `CANDIDATE_DOCUMENTS`;
CREATE TABLE `CANDIDATE_DOCUMENTS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_LOCATION_ID BIGINT,
  CANDIDATE_ID BIGINT,
  DOCUMENT_TYPE VARCHAR(100)  DEFAULT NULL,
  DOCUMENT_OTHER_TYPE VARCHAR(150)  DEFAULT NULL,
  DOC_FILE MEDIUMBLOB,
  FILE_CONTENT_TYPE VARCHAR(50),
  FILE_NAME TEXT DEFAULT NULL,
  DESCRIPTION VARCHAR(500) DEFAULT NULL,
  DOCUMENT_UUID VARCHAR(50),
  STATUS INT(10) DEFAULT NULL,
  CREATED_DATE DATETIME,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATETIME,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(CANDIDATE_ID) REFERENCES `CANDIDATE`(ID)
) ;

