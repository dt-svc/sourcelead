#LEAVE_OPTION
DROP TABLE IF EXISTS `LEAVE_OPTION`;
CREATE TABLE `LEAVE_OPTION` (
  ID VARCHAR(100),
  ORGLOCATION_ID BIGINT,
  DEPARTMENT_ID BIGINT,
  CALENDAR_MONTH VARCHAR(150) DEFAULT NULL,
  WEEKENDS VARCHAR(150) DEFAULT NULL,
  HALFDAY_REQUEST VARCHAR(250) DEFAULT NULL,
  LEAVE_TRANSFER VARCHAR(250) DEFAULT NULL,
  WORKING_HOURS VARCHAR(250) DEFAULT NULL,
  DELETE_REASON TEXT DEFAULT NULL,
  STATUS VARCHAR(50) DEFAULT NULL,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORGLOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(DEPARTMENT_ID) REFERENCES `DEPARTMENT`(ID)
) ;

