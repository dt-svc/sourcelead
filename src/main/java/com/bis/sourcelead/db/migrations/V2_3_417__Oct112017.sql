#LEAVE

DROP TABLE IF EXISTS `LEAVE`;
CREATE TABLE `LEAVE` (
  ID VARCHAR(100),
  ORGLOCATION_ID BIGINT,
  USER_ID BIGINT,
  FROM_DATE DATE,
  TO_DATE DATE,
  FROM_HALF_DAY VARCHAR(50),
  TO_HALF_DAY VARCHAR(10),
  LEAVE_TYPE_ID VARCHAR(100) DEFAULT NULL,
  FILE_NAME VARCHAR(100), 
  FILE_CONTENT_TYPE VARCHAR(100), 
  FILE_URL VARCHAR(250), 
  REASON TEXT DEFAULT NULL,
  NUMBER_OF_DAYS VARCHAR(20),
  REJECTED_REASON TEXT DEFAULT NULL,
  APPROVED_BY BIGINT,
  REJECTED_BY BIGINT,
  CANCELLED_BY BIGINT,
  STATUS VARCHAR(50) DEFAULT NULL,
  DELETE_REASON TEXT DEFAULT NULL,
  WITHDRAW_REASON TEXT DEFAULT NULL,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORGLOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(USER_ID) REFERENCES `USER`(ID),
  FOREIGN KEY(LEAVE_TYPE_ID) REFERENCES `LEAVE_TYPE`(ID),
  FOREIGN KEY(APPROVED_BY) REFERENCES `USER`(ID) ,
  FOREIGN KEY(REJECTED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(CANCELLED_BY) REFERENCES `USER`(ID)
) ;

