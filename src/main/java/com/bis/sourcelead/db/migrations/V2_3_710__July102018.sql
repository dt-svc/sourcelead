DROP TABLE IF EXISTS `JOB_FAIR_REQUIREMENTS`;
DROP TABLE IF EXISTS `JOB_FAIR`;

CREATE TABLE `JOB_FAIR` (
	ID BIGINT NOT NULL AUTO_INCREMENT,
    UUID VARCHAR(10),
    NAME VARCHAR(100),
    BUDGET DOUBLE DEFAULT 0,
    DESCRIPTION VARCHAR(500),
    USER_ID BIGINT DEFAULT NULL,
    ORG_LOCATION_ID BIGINT DEFAULT NULL,
    START_DATE DATE,
    END_DATE DATE,
    POSTED_FROM VARCHAR(25),
	VENUE VARCHAR(200),
    NOTIFY_TO VARCHAR(500),
    STATUS INT,
    DATE_FORMAT VARCHAR(20),
    PRIMARY KEY (`ID`),
    FOREIGN KEY (USER_ID) REFERENCES `USER`(ID),
    FOREIGN KEY (ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
);

CREATE TABLE `JOB_FAIR_REQUIREMENTS` (
	ID BIGINT NOT NULL AUTO_INCREMENT,
    JOB_FAIR_ID BIGINT DEFAULT NULL,
    REQUIREMENT_ID BIGINT DEFAULT NULL,
    FAIR_DATES VARCHAR(200),
    PRIMARY KEY (`ID`),
    FOREIGN KEY (JOB_FAIR_ID) REFERENCES `JOB_FAIR`(ID),
    FOREIGN KEY (REQUIREMENT_ID) REFERENCES `REQUIREMENT`(ID)
);
