DROP TABLE IF EXISTS `EXPENSES_HISTORY`;
CREATE TABLE `EXPENSES_HISTORY` (

ID BIGINT NOT NULL AUTO_INCREMENT,
EXPENSE_ID BIGINT DEFAULT NULL,
LOCATION_ID BIGINT DEFAULT NULL,
PROJECT_MEMBERS_ID BIGINT DEFAULT NULL,
EXPENSE_ENTRY_ID BIGINT DEFAULT NULL,
EXPENSE_CATEGORY_ID BIGINT DEFAULT NULL,
EXPENSE_APPROVER_HIERARCHY_ID BIGINT DEFAULT NULL,
UPDATED_BY_USER BIGINT DEFAULT NULL,
EXPENSE_ENTRIES_DOCUMENTS_ID BIGINT DEFAULT NULL,
CLIENT_NAME VARCHAR(250) DEFAULT NULL,
START_DATE DATETIME,
END_DATE DATETIME,

EXPENSE_STATUS_OLD VARCHAR(50),
EXPENSE_STATUS_NEW VARCHAR(50),
ENTRY_DATE DATETIME,

ENTRY_PAYMENT_MODE VARCHAR(250),
ENTRY_RECEIPT_ISSUED_BY VARCHAR(250),
ENTRY_CURRENCY_TYPE VARCHAR(250),

ENTRY_AMOUNT FLOAT DEFAULT NULL,
ENTRY_DESCRIPTION TEXT DEFAULT NULL,
ENTRY_STATUS VARCHAR(20),

EXPENSE_APPROVAL_STATUS_OLD VARCHAR(50),
EXPENSE_APPROVAL_STATUS_NEW VARCHAR(50),
EXPENSE_APPROVAL_STATUS_REASON TEXT DEFAULT NULL,
PURPOSE TEXT DEFAULT NULL,
UPDATED_DATE  DATETIME,

PRIMARY KEY (`ID`),
FOREIGN KEY(EXPENSE_ID) REFERENCES `EXPENSES`(ID),
FOREIGN KEY(LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
FOREIGN KEY(PROJECT_MEMBERS_ID) REFERENCES `PROJECT_MEMBERS`(ID),
FOREIGN KEY(EXPENSE_ENTRY_ID) REFERENCES `EXPENSES_ENTRIES`(ID),
FOREIGN KEY(EXPENSE_CATEGORY_ID) REFERENCES `EXPENSE_CATEGORY`(ID),
FOREIGN KEY(EXPENSE_APPROVER_HIERARCHY_ID) REFERENCES `EXPENSES_APPROVER_HIERARCHY`(ID),
FOREIGN KEY(UPDATED_BY_USER) REFERENCES `USER`(ID),
FOREIGN KEY(EXPENSE_ENTRIES_DOCUMENTS_ID) REFERENCES `EXPENSES_ENTRIES_DOCUMENTS`(ID)
);