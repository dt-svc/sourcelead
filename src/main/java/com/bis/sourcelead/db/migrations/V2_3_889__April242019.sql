DROP TABLE IF EXISTS `PERFORMANCE_GOALS_COMMENTS`;
CREATE TABLE `PERFORMANCE_GOALS_COMMENTS` (
   ID BIGINT NOT NULL AUTO_INCREMENT,
   GOAL_ID BIGINT(20) NOT NULL,
   CREATED_USER_ID BIGINT(20) NOT NULL,
   CREATE_USER_NAME varchar(250) DEFAULT NULL,
   COMMENT TEXT DEFAULT NULL,
   CREATED_DATE DATETIME,
   PRIMARY KEY (`ID`),
   FOREIGN KEY (GOAL_ID) REFERENCES `PERFORMANCE_GOALS`(ID),
   FOREIGN KEY(CREATED_USER_ID) REFERENCES `USER`(ID)
); 


