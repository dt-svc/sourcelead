
CALL AlterTableAddColumn ('ASSOCIATE_SALARY_IND','STOP_SALARY','VARCHAR(10) NULL AFTER `SALARY_TYPE`');

DROP TABLE IF EXISTS `ASSOCIATE_SALARY_HISTORY_IND`;
CREATE TABLE `ASSOCIATE_SALARY_HISTORY_IND` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ASSOCIATE_SALARY_IND BIGINT,
  GROUP_ID BIGINT,
  PAY_TYPE varchar(150),
  PAY_FREQUENCY varchar(150),
  STANDARD_HOURS varchar(150),
  ANNUAL_SALARY DECIMAL(20,2),
  GROSS_SALARY DECIMAL(20,2),
  HOURLY_RATE DECIMAL(20,2),
  INCREMENT_PERCENTAGE VARCHAR(100),
  EFFECTIVE_DATE DATE,
  CHANGE_REASON TEXT,
  SALARY_TYPE VARCHAR(45),
  STOP_SALARY VARCHAR(10),
  PREVIOUS_GROUP_ID BIGINT,
  PREVIOUS_PAY_TYPE varchar(150),
  PREVIOUS_PAY_FREQUENCY varchar(150),
  PREVIOUS_STANDARD_HOURS varchar(150),
  PREVIOUS_ANNUAL_SALARY DECIMAL(20,2),
  PREVIOUS_GROSS_SALARY DECIMAL(20,2),
  PREVIOUS_HOURLY_RATE DECIMAL(20,2),
  PREVIOUS_INCREMENT_PERCENTAGE VARCHAR(100),
  PREVIOUS_EFFECTIVE_DATE DATE,
  PREVIOUS_CHANGE_REASON TEXT,
  PREVIOUS_SALARY_TYPE VARCHAR(45),
  PREVIOUS_STOP_SALARY VARCHAR(10),
  PREVIOUS_CREATED_DATE DATETIME,
  PREVIOUS_CREATED_BY BIGINT,
  PREVIOUS_UPDATED_DATE DATETIME,
  PREVIOUS_UPDATED_BY BIGINT,
  STATUS int,
  UUID VARCHAR(20) DEFAULT NULL,
  CREATED_DATE DATETIME,
  CREATED_BY BIGINT,
  UPDATED_DATE DATETIME,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(PREVIOUS_CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(PREVIOUS_UPDATED_BY) REFERENCES `USER`(ID)
);


DROP TABLE IF EXISTS `ASSOCIATE_SALARY_PAYHEAD_HISTORY_IND`;
CREATE TABLE `ASSOCIATE_SALARY_PAYHEAD_HISTORY_IND` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ASSOCIATE_SALARY_IND BIGINT,
  ASSOCIATE_SALARY_HISTORY_IND BIGINT,
  PAYROLL_PAYHEAD BIGINT,
  MONTHLY DECIMAL(20,2),
  ANNUALY DECIMAL(20,2),
  PREVIOUS_PAYROLL_PAYHEAD BIGINT,
  PREVIOUS_MONTHLY DECIMAL(20,2),
  PREVIOUS_ANNUALY DECIMAL(20,2),
  PREVIOUS_CREATED_DATE DATETIME,
  PREVIOUS_CREATED_BY BIGINT,
  PREVIOUS_UPDATED_DATE DATETIME,
  PREVIOUS_UPDATED_BY BIGINT,
  STATUS int,
  UUID VARCHAR(20) DEFAULT NULL,
  CREATED_DATE DATETIME,
  CREATED_BY BIGINT,
  UPDATED_DATE DATETIME,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ASSOCIATE_SALARY_IND) REFERENCES `ASSOCIATE_SALARY_IND`(ID),
  FOREIGN KEY(ASSOCIATE_SALARY_HISTORY_IND) REFERENCES `ASSOCIATE_SALARY_HISTORY_IND`(ID),
  FOREIGN KEY(PAYROLL_PAYHEAD) REFERENCES `PAYROLL_PAYHEAD`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(PREVIOUS_PAYROLL_PAYHEAD) REFERENCES `PAYROLL_PAYHEAD`(ID),
  FOREIGN KEY(PREVIOUS_CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(PREVIOUS_UPDATED_BY) REFERENCES `USER`(ID)
);
