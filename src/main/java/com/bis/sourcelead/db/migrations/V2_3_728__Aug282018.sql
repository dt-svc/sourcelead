#LEAVE_REPORT_VIEW
CREATE OR REPLACE VIEW LEAVE_REPORT_VIEW AS
SELECT
    uLeave.ID,
    emp.EMPLOYMENT_TYPE AS EMP_TYPE,
    (SELECT DEPARTMENT_NAME FROM DEPARTMENT dept WHERE dept.ID = emp.DEPARTMENT_ID) AS USER_DEPT_NAME,    
    (SELECT DISPLAY_NAME FROM ROLES role WHERE role.ID = uRole.ROLE_ID) AS USER_ROLE_NAME,
    (SELECT ORG_ID FROM `ORG_LOCATIONS` WHERE ID = uLeave.ORGLOCATION_ID) AS ORG_ID,
    (SELECT  CONCAT(FIRST_NAME,LAST_NAME) AS EMPLOYEE_NAME FROM `USER` WHERE ID = uLeave.USER_ID) AS EMPLOYEE_NAME,
    (SELECT group_concat(CONCAT(U.FIRST_NAME, ' ', U.LAST_NAME)  SEPARATOR ' , ') AS APPROVER_NAME
    FROM LEAVE_APPROVER_HIERARCHY LAH,USER U
    WHERE LAH.LEAVE_ID = uLeave.ID AND (U.ID = LAH.APPROVER_USER_ID or U.ID = uRole.REPORTING_MANAGER_ID)
    group by uLeave.ID) AS APPROVER_NAME,
    uLeave.FROM_DATE,
    uLeave.TO_DATE,
    uLeave.REASON AS REASON,
    uLeave.USER_ID,
    uRole.ROLE_ID AS ROLE_ID,
    uLeave.ORGLOCATION_ID,
    uRole.REPORTING_MANAGER_ID,
    (SELECT  CONCAT(FIRST_NAME,LAST_NAME) FROM `USER` WHERE ID = uRole.REPORTING_MANAGER_ID) AS REPORTING_MANAGER,
    emp.DEPARTMENT_ID,
    emp.ID AS Employee_ID,
    uLeave.CREATED_DATE,
    uLeave.UPDATED_DATE,
    uLeave.LEAVE_TYPE_ID,
    uLeave.STATUS AS LEAVE_STATUS,
    leaveType.NAME AS LEAVE_TYPE_NAME,
    leaveType.LEAVE_TYPE AS LEAVE_TYPE_BILLABLE,
    leaveType.DURATION AS DURATION
FROM USER_LEAVE uLeave,LEAVE_TYPE leaveType, EMPLOYEE emp, USER_ROLE uRole
where leaveType.ID = uLeave.LEAVE_TYPE_ID and (uLeave.USER_ID = emp.USER_ID and uLeave.ORGLOCATION_ID = emp.ORG_LOCATIONS_ID) and (uLeave.USER_ID = uRole.USER_ID and uLeave.ORGLOCATION_ID = uRole.ORG_LOCATIONS_ID);