DROP TABLE IF EXISTS `TIMESHEET_SUBMISSIONS_DOCUMENTS_HISTORY`;
CREATE TABLE `TIMESHEET_SUBMISSIONS_DOCUMENTS_HISTORY` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  TIMESHEET_SUBMISSION_ID BIGINT DEFAULT NULL,
  DOC_FILE MEDIUMBLOB,
  FILE_CONTENT_TYPE VARCHAR(500),
  FILE_NAME TEXT DEFAULT NULL,
  STATUS INT,
  FILE_URL VARCHAR(500) NULL,
  TIMESHEET_ACTIVITY_ID BIGINT(20),
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(TIMESHEET_SUBMISSION_ID) REFERENCES `TIMESHEET_SUBMISSIONS`(ID)
);	

