DROP TABLE IF EXISTS `BIS_USER_MAPPING`;
CREATE TABLE `BIS_USER_MAPPING` (
ID BIGINT NOT NULL AUTO_INCREMENT,
COMPANY VARCHAR(250),
BRANCH VARCHAR(250),      
EMP_ID VARCHAR(250),
ORG_LOCATION_ID BIGINT DEFAULT NULL,
USER_ID BIGINT DEFAULT NULL,
CANDIDATE_NAME VARCHAR(250),
RATE DOUBLE DEFAULT NULL,           
FIXEDRATE DOUBLE DEFAULT NULL,       
PAYRATE DOUBLE DEFAULT NULL,         
FIXEDPAY DOUBLE DEFAULT NULL,         
INSURANCE DOUBLE DEFAULT NULL,        
DED DOUBLE DEFAULT NULL,              
EFFECTIVE_RATE DOUBLE DEFAULT NULL,    
PAYROLL_DIFFERENCE DOUBLE DEFAULT NULL,
IMMIGRATION VARCHAR(250),      
COMMENTS TEXT DEFAULT NULL,        
ADVANCE_HCP DOUBLE DEFAULT NULL, 
BALANCE DOUBLE DEFAULT NULL,  
STATUS VARCHAR(50),
CREATED_DATE DATETIME,
CREATED_BY VARCHAR(10),
UPDATED_DATE DATETIME,
UPDATED_BY VARCHAR(10),
PRIMARY KEY (`ID`),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
FOREIGN KEY(USER_ID) REFERENCES `USER`(ID)
);
