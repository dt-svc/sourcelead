
DROP TABLE IF EXISTS `sourcelead`.`TIMESHEET_DAY_ENTRIES`;
CREATE TABLE `sourcelead`.`TIMESHEET_DAY_ENTRIES` (
  ID BIGINT NOT NULL AUTO_INCREMENT primary key NOT NULL,
  TIMESHEET_ID BIGINT NOT NULL,
  PROJECT_TASK BIGINT NOT NULL,
  DATE_TIMESHEET DATE,
  BILLABLE_HOURS VARCHAR(100),
  NONBILLABLE_HOURS VARCHAR(100),
  TOTALHOURS VARCHAR(100),
  COMMENTS VARCHAR(200),
  CREATED_DATE DATETIME,
  CREATED_BY VARCHAR(100),
  UPDATED_DATE DATETIME,
  UPDATED_BY VARCHAR(100),
  FOREIGN KEY(TIMESHEET_ID) REFERENCES `sourcelead`.`TIMESHEET_SUBMISSIONS`(ID),
  FOREIGN KEY(PROJECT_TASK) REFERENCES `sourcelead`.`PROJECT_TASKS`(ID)
) ;



