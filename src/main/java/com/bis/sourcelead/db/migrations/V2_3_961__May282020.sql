
DROP TABLE IF EXISTS `LINE_OF_BUSINESS`;
CREATE TABLE `LINE_OF_BUSINESS` (
  ID BIGINT NOT NULL AUTO_INCREMENT, 
  ORG_LOCATION_ID BIGINT DEFAULT NULL,
  DEPARTMENT_ID BIGINT DEFAULT NULL,
  LOB_NAME VARCHAR(100) DEFAULT NULL,
  DESCRIPTION TEXT DEFAULT NULL,
  STATUS INT,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(DEPARTMENT_ID) REFERENCES `DEPARTMENT`(ID)
  );
  
CALL AlterTableAddColumn ('EMPLOYEE','LOB_ID','BIGINT  DEFAULT NULL');
ALTER TABLE `EMPLOYEE` ADD CONSTRAINT FK_LOB_ID FOREIGN KEY (LOB_ID) REFERENCES LINE_OF_BUSINESS(ID);
