DROP TABLE IF EXISTS `sourcelead`.`SOURCELEAD_NOTES`;
CREATE TABLE `sourcelead`.`SOURCELEAD_NOTES` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_RELATION_ID BIGINT DEFAULT NULL,
  USER_ID BIGINT DEFAULT NULL,
  REQUIREMENT_ID BIGINT DEFAULT NULL,
  CONTRACT_ID BIGINT DEFAULT NULL,
  INVOICE_ID BIGINT DEFAULT NULL,
  COMMENT TEXT,
  NOTE_TYPE VARCHAR(20),
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_RELATION_ID) REFERENCES `sourcelead`.`ORG_RELATIONS`(ID),
  FOREIGN KEY(REQUIREMENT_ID) REFERENCES `sourcelead`.`REQUIREMENT`(ID),
  FOREIGN KEY(CONTRACT_ID) REFERENCES `sourcelead`.`CONTRACTS`(ID),
  FOREIGN KEY(INVOICE_ID) REFERENCES `sourcelead`.`INVOICE`(ID),
  FOREIGN KEY(USER_ID) REFERENCES `sourcelead`.`USER`(ID)
) ;