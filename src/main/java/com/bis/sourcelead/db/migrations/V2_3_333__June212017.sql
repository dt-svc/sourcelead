
DROP TABLE IF EXISTS `HR_DEDUCTIONS`;
CREATE TABLE `HR_DEDUCTIONS` (
ID BIGINT NOT NULL AUTO_INCREMENT,
ORG_LOCATION_ID BIGINT DEFAULT NULL,
EMPLOYEE_ID VARCHAR(100) DEFAULT NULL,
EMPLOYEE_NAME VARCHAR(250) DEFAULT NULL,
DED_AMOUNT FLOAT DEFAULT NULL,	
FROM_DATE DATETIME,
TO_DATE DATETIME,
BATCH_NUMBER VARCHAR(100),
REQUEST_SUB_DATE DATETIME,
REQUEST_APPROVED_DATE DATETIME,
REPAID_STATUS VARCHAR(200),
STATUS VARCHAR(20),
DESCRIPTION TEXT DEFAULT NULL,
CREATED_DATE DATETIME,
CREATED_BY VARCHAR(10),
UPDATED_DATE DATETIME,
UPDATED_BY VARCHAR(10),
PRIMARY KEY (`ID`),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
);


DROP TABLE IF EXISTS `HR_DEDUCTIONS_DETAILS`;
CREATE TABLE `HR_DEDUCTIONS_DETAILS` (
ID BIGINT NOT NULL AUTO_INCREMENT,
ORG_LOCATION_ID BIGINT DEFAULT NULL,
HR_DEDUCTIONS_ID BIGINT DEFAULT NULL,
PAY_CYCLE_NAME VARCHAR(250) DEFAULT NULL,
DED_AMOUNT_PER_CYCLE FLOAT DEFAULT NULL,	
PAID_STATUS VARCHAR(250) DEFAULT NULL,
STATUS VARCHAR(20),
DESCRIPTION TEXT DEFAULT NULL,
CREATED_DATE DATETIME,
CREATED_BY VARCHAR(10),
UPDATED_DATE DATETIME,
UPDATED_BY VARCHAR(10),
PRIMARY KEY (`ID`),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
FOREIGN KEY(HR_DEDUCTIONS_ID) REFERENCES `HR_DEDUCTIONS`(ID)
);

