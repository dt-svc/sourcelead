CREATE OR REPLACE VIEW IMMIGRATON_DASHBOARD_VIEW AS
SELECT 
    SUM(CASE
        WHEN UPPER(CURRENT_USCIS_STATUS) = 'DRAFT' THEN 1
        ELSE 0
    END) AS DRAFT_COUNT,
    SUM(CASE
        WHEN UPPER(CURRENT_USCIS_STATUS) = 'REQUEST TO FILL' THEN 1
        ELSE 0
    END) AS REQUEST_SENT_COUNT,
    SUM(CASE
        WHEN UPPER(CURRENT_USCIS_STATUS) = 'APPROVED' THEN 1
        ELSE 0
    END) AS APPROVED_COUNT,
    SUM(CASE
        WHEN UPPER(CURRENT_USCIS_STATUS) = 'REJECTED' THEN 1
        ELSE 0
    END) AS REJECTED_COUNT,
    SUM(CASE
        WHEN UPPER(CURRENT_USCIS_STATUS) = 'Filled' THEN 1
        WHEN UPPER(CURRENT_USCIS_STATUS) = 'REVIEWED & SEND TO ATTORNEY' THEN 1
        WHEN UPPER(CURRENT_USCIS_STATUS) = 'REQUEST FOR MODIFICATIONS' THEN 1
        WHEN UPPER(CURRENT_USCIS_STATUS) = 'REVIEWED & FILED' THEN 1
        WHEN UPPER(CURRENT_USCIS_STATUS) = 'RFE' THEN 1
        WHEN UPPER(CURRENT_USCIS_STATUS) = 'RFE RECEIVED' THEN 1
        WHEN UPPER(CURRENT_USCIS_STATUS) = 'MOTION TO RE-OPEN' THEN 1
        WHEN UPPER(CURRENT_USCIS_STATUS) = 'RFE APPROVED' THEN 1
        WHEN UPPER(CURRENT_USCIS_STATUS) = 'RFE DENIED' THEN 1
        WHEN UPPER(CURRENT_USCIS_STATUS) = 'RFE RESPONDED' THEN 1
        ELSE 0
    END) AS INPROGRESS_COUNT,
    SUM(CASE
        WHEN UPPER(CURRENT_USCIS_STATUS) = 'DENIED' THEN 1
        WHEN UPPER(CURRENT_USCIS_STATUS) = 'REVOKED' THEN 1
        WHEN UPPER(CURRENT_USCIS_STATUS) = 'CANCELLED' THEN 1
        WHEN UPPER(CURRENT_USCIS_STATUS) = 'WITHDRAWN' THEN 1
        ELSE 0
    END) AS OTHERS_COUNT
FROM
    IMMIGRATON_LIST_VIEW