# CREATED BY SRINIVAS SABBU ON OCT 30 2018 FOR MARKET PLACE HISTORY.

DROP TABLE IF EXISTS `CANDIDATE_MARKET_PLACE_PAYMENT_TRANSACTION_HISTORY`; 
CREATE TABLE `CANDIDATE_MARKET_PLACE_PAYMENT_TRANSACTION_HISTORY` ( 
ID BIGINT NOT NULL AUTO_INCREMENT,
MARKETPLACE_CART_IDS TEXT DEFAULT NULL,
ORG_LOCATION_ID BIGINT DEFAULT NULL,
CURRENCY VARCHAR(10) DEFAULT NULL,
INVOICE_AMOUNT DOUBLE DEFAULT NULL,
PAYMENT_ID TEXT DEFAULT NULL,
ORDER_ID TEXT DEFAULT NULL,
RECEPIT_ID TEXT DEFAULT NULL,
INVOICE_NUMBER TEXT DEFAULT NULL,
TRANSACTION_ID TEXT DEFAULT NULL,
TRANSACTION_PAYER_ID TEXT DEFAULT NULL,
TRANSACTION_USER TEXT DEFAULT NULL,
TRANSACTION_USER_EMAIL TEXT DEFAULT NULL,
TRANSACTION_DATE DATE,
PRIMARY KEY (`ID`), 
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
);