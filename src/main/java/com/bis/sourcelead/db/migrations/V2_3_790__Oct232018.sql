DROP TABLE IF EXISTS `RELEASE_NOTE`;
CREATE TABLE `RELEASE_NOTE` (
  ID BIGINT NOT NULL AUTO_INCREMENT, 
  RELEASE_NAME VARCHAR(500) NULL,
  RELEASE_DATE DATE NULL,
  RELEASE_UUID VARCHAR(50) NULL,
  RELEASE_PUBLISH_DATE DATE NULL,
  RELEASE_NOTES VARCHAR(500) NULL,
  RELEASE_SHORT_DESCRPTION LONGTEXT NULL,
  RELEASE_DELETE_REASON TEXT NULL,
  RELEASE_DESCRPTION LONGTEXT NULL,
  STATUS INT,
  CREATED_DATE DATETIME,
  CREATED_BY BIGINT,
  UPDATED_DATE DATETIME,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`)
  );