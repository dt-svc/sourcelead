DROP TABLE IF EXISTS `TICKET_STATUS_HISTORY`;
DROP TABLE IF EXISTS `TICKET_COMMENT`;
DROP TABLE IF EXISTS `TICKET_ATTACHMENT`;
DROP TABLE IF EXISTS `TICKET_ASSIGN_TO`;
DROP TABLE IF EXISTS `TICKET`;

DROP TABLE IF EXISTS `TICKET_TYPE`; 
DROP TABLE IF EXISTS `TICKET_CATEGORY_ASSIGN_TO`;
DROP TABLE IF EXISTS `TICKET_CATEGORY`; 
DROP TABLE IF EXISTS `TICKET_PRIORITY`; 
DROP TABLE IF EXISTS `TICKET_STATUS`;

CREATE TABLE `TICKET_TYPE` ( 
	ID BIGINT NOT NULL AUTO_INCREMENT, 
	UUID  VARCHAR(100) DEFAULT NULL,
	NAME  VARCHAR(100) DEFAULT NULL,
	DESCRIPTION  VARCHAR(1000) DEFAULT NULL,
	STATUS INT(10) DEFAULT 1,
	ORG_LOCATION_ID BIGINT DEFAULT NULL,
	CREATED_BY BIGINT DEFAULT NULL, 
	CREATED_DATE DATETIME, 
	UPDATED_BY BIGINT DEFAULT NULL, 
	UPDATED_DATE DATETIME, 
	PRIMARY KEY (`ID`), 
	FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
);

CREATE TABLE `TICKET_CATEGORY` (
	ID BIGINT NOT NULL AUTO_INCREMENT, 
	UUID  VARCHAR(100) DEFAULT NULL,
	NAME  VARCHAR(100) DEFAULT NULL,
	DESCRIPTION  VARCHAR(1000) DEFAULT NULL,
	NOTIFY_TO LONGTEXT DEFAULT NULL,
	STATUS INT(10) DEFAULT 1,
	ORG_LOCATION_ID BIGINT DEFAULT NULL,
	CREATED_BY BIGINT DEFAULT NULL, 
	CREATED_DATE DATETIME, 
	UPDATED_BY BIGINT DEFAULT NULL, 
	UPDATED_DATE DATETIME, 
	PRIMARY KEY (`ID`), 
	FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
);

CREATE TABLE `TICKET_CATEGORY_ASSIGN_TO` (
	ID BIGINT NOT NULL AUTO_INCREMENT,
	USER_ID BIGINT DEFAULT NULL,
	TICKET_CATEGORY_ID BIGINT DEFAULT NULL,
	CREATED_BY BIGINT DEFAULT NULL, 
	CREATED_DATE DATETIME, 
	UPDATED_BY BIGINT DEFAULT NULL, 
	UPDATED_DATE DATETIME, 
	PRIMARY KEY (`ID`),
	FOREIGN KEY(USER_ID) REFERENCES `USER`(ID),
	FOREIGN KEY(TICKET_CATEGORY_ID) REFERENCES `TICKET_CATEGORY`(ID)
);

CREATE TABLE `TICKET_PRIORITY` (
	ID BIGINT NOT NULL AUTO_INCREMENT, 
	UUID VARCHAR(100) DEFAULT NULL,
	NAME VARCHAR(100) DEFAULT NULL,
	DESCRIPTION VARCHAR(1000) DEFAULT NULL,
	COLOR_CODE VARCHAR(10) DEFAULT NULL,
	FILE_NAME VARCHAR(100) DEFAULT NULL,
	FILE_URL VARCHAR(100) DEFAULT NULL,
	FILE_CONTENT_TYPE VARCHAR(100) DEFAULT NULL,
	STATUS INT(10) DEFAULT 1,
	ORG_LOCATION_ID BIGINT DEFAULT NULL,
	CREATED_BY BIGINT DEFAULT NULL, 
	CREATED_DATE DATETIME, 
	UPDATED_BY BIGINT DEFAULT NULL, 
	UPDATED_DATE DATETIME, 
	PRIMARY KEY (`ID`),
	FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
);
 
CREATE TABLE `TICKET_STATUS` (
	ID BIGINT NOT NULL AUTO_INCREMENT, 
	UUID  VARCHAR(100) DEFAULT NULL,
	NAME  VARCHAR(100) DEFAULT NULL,
	DESCRIPTION  VARCHAR(1000) DEFAULT NULL,
	IS_COMMENT_REQUIRED BOOLEAN,
	STATUS INT(10) DEFAULT 1,
	ORG_LOCATION_ID BIGINT DEFAULT NULL,
	CREATED_BY BIGINT DEFAULT NULL, 
	CREATED_DATE DATETIME, 
	UPDATED_BY BIGINT DEFAULT NULL, 
	UPDATED_DATE DATETIME, 
	PRIMARY KEY (`ID`), 
	FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
);

CREATE TABLE `TICKET` ( 
	ID BIGINT NOT NULL AUTO_INCREMENT, 
	UUID  VARCHAR(100) DEFAULT NULL,
	GENERATED_ID  VARCHAR(100) DEFAULT NULL,
	TICKET_TITLE  VARCHAR(100) DEFAULT NULL,
	TICKET_TYPE_ID BIGINT DEFAULT NULL,
	TICKET_CATEGORY_ID BIGINT DEFAULT NULL,
	TICKET_PRIORITY_ID BIGINT DEFAULT NULL,
	TICKET_STATUS_ID BIGINT DEFAULT NULL,
	ORG_LOCATION_ID BIGINT DEFAULT NULL,
	DESCRIPTION LONGTEXT DEFAULT NULL,
	NOTIFY_TO LONGTEXT DEFAULT NULL,
	STATUS INT(10) DEFAULT 1,
	CREATED_BY BIGINT DEFAULT NULL, 
	CREATED_DATE DATETIME, 
	UPDATED_BY BIGINT DEFAULT NULL, 
	UPDATED_DATE DATETIME, 
	PRIMARY KEY (`ID`), 
	FOREIGN KEY(TICKET_TYPE_ID) REFERENCES `TICKET_TYPE`(ID),
	FOREIGN KEY(TICKET_CATEGORY_ID) REFERENCES `TICKET_CATEGORY`(ID),
	FOREIGN KEY(TICKET_PRIORITY_ID) REFERENCES `TICKET_PRIORITY`(ID),
	FOREIGN KEY(TICKET_STATUS_ID) REFERENCES `TICKET_STATUS`(ID),
	FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
	FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
	FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
);

CREATE TABLE `TICKET_ASSIGN_TO` (
	ID BIGINT NOT NULL AUTO_INCREMENT,
	USER_ID BIGINT DEFAULT NULL,
	TICKET_ID BIGINT DEFAULT NULL,
	CREATED_BY BIGINT DEFAULT NULL, 
	CREATED_DATE DATETIME, 
	UPDATED_BY BIGINT DEFAULT NULL, 
	UPDATED_DATE DATETIME, 
	PRIMARY KEY (`ID`),
	FOREIGN KEY(USER_ID) REFERENCES `USER`(ID),
	FOREIGN KEY(TICKET_ID) REFERENCES `TICKET`(ID)
);

CREATE TABLE `TICKET_ATTACHMENT` (
	ID BIGINT NOT NULL AUTO_INCREMENT, 
	UUID  VARCHAR(100) DEFAULT NULL,
	TICKET_ID BIGINT DEFAULT NULL,
	FILE_TYPE  VARCHAR(100) DEFAULT NULL,
	FILE_NAME  VARCHAR(100) DEFAULT NULL,
	FILE_URL  VARCHAR(100) DEFAULT NULL,
	STATUS INT(10) DEFAULT 1, 
	CREATED_BY BIGINT DEFAULT NULL, 
	CREATED_DATE DATETIME, 
	UPDATED_BY BIGINT DEFAULT NULL, 
	UPDATED_DATE DATETIME, 
	PRIMARY KEY (`ID`), 
	FOREIGN KEY(TICKET_ID) REFERENCES `TICKET`(ID)
);	

CREATE TABLE `TICKET_COMMENT` (
	ID BIGINT NOT NULL AUTO_INCREMENT, 
	TICKET_ID BIGINT DEFAULT NULL,
	COMMENT  VARCHAR(100) DEFAULT NULL,
	STATUS INT(10) DEFAULT 1, 
	CREATED_BY BIGINT DEFAULT NULL, 
	CREATED_DATE DATETIME, 
	UPDATED_BY BIGINT DEFAULT NULL, 
	UPDATED_DATE DATETIME, 
	PRIMARY KEY (`ID`), 
	FOREIGN KEY(TICKET_ID) REFERENCES `TICKET`(ID)
);

CREATE TABLE `TICKET_STATUS_HISTORY` (
	ID BIGINT NOT NULL AUTO_INCREMENT, 
	TICKET_ID BIGINT DEFAULT NULL,
	PREVIOUS_STATUS VARCHAR(50) DEFAULT NULL,
	NEW_STATUS VARCHAR(50) DEFAULT NULL,
	COMMENT  VARCHAR(100) DEFAULT NULL,
	CREATED_BY BIGINT DEFAULT NULL, 
	CREATED_DATE DATETIME, 
	PRIMARY KEY (`ID`), 
	FOREIGN KEY(TICKET_ID) REFERENCES `TICKET`(ID)
);