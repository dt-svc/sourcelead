DROP TABLE IF EXISTS `sourcelead`.`SUBMISSION_TEMPLATE`;
CREATE TABLE `sourcelead`.`SUBMISSION_TEMPLATE` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  TEMPLATE_NAME VARCHAR(500) DEFAULT NULL,
  CLIENT_LOCATION_ID BIGINT DEFAULT NULL,
  ORG_LOCATION_ID BIGINT DEFAULT NULL,
  JSON_STRING TEXT DEFAULT NULL,
  DESCRIPTION TEXT DEFAULT NULL,
  STATUS VARCHAR(20) DEFAULT NULL,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`), 
  FOREIGN KEY(CLIENT_LOCATION_ID) REFERENCES `sourcelead`.`ORG_LOCATIONS`(ID),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `sourcelead`.`ORG_LOCATIONS`(ID)
); 