#This table is for pre defined sourcelead form sections 

DROP TABLE IF EXISTS `sourcelead`.`SOURCELEAD_FORM_SECTIONS`; 
CREATE TABLE `sourcelead`.`SOURCELEAD_FORM_SECTIONS` ( 
ID BIGINT NOT NULL AUTO_INCREMENT, 
TAB_ID BIGINT DEFAULT NULL, 
SOURCELEAD_ACTION_ID BIGINT DEFAULT NULL, 
SECTION_NAME VARCHAR(500) DEFAULT NULL, 
SECTION_DESC TEXT DEFAULT NULL, 
STATUS INT(10) DEFAULT NULL, 
CREATED_DATE DATETIME, 
CREATED_BY BIGINT DEFAULT NULL, 
UPDATED_DATE DATETIME, 
UPDATED_BY BIGINT DEFAULT NULL, 
PRIMARY KEY (`ID`), 
FOREIGN KEY(TAB_ID) REFERENCES `sourcelead`.`TABS`(ID), 
FOREIGN KEY(SOURCELEAD_ACTION_ID) REFERENCES `sourcelead`.`SOURCELEAD_ACTIONS`(ID), 
FOREIGN KEY(CREATED_BY) REFERENCES `sourcelead`.`USER`(ID), 
FOREIGN KEY(UPDATED_BY) REFERENCES `sourcelead`.`USER`(ID) 
); 

#This table is for pre defined sourcelead form fields 
DROP TABLE IF EXISTS `sourcelead`.`SOURCELEAD_FORM_FIELDS`; 
CREATE TABLE `sourcelead`.`SOURCELEAD_FORM_FIELDS` ( 
ID BIGINT NOT NULL AUTO_INCREMENT, 
SECTION_ID BIGINT DEFAULT NULL, 
LABEL_NAME VARCHAR(500) DEFAULT NULL, 
FIELD_NAME VARCHAR(500) DEFAULT NULL, 
LABEL_INFO TEXT DEFAULT NULL, 
FIELD_TYPE VARCHAR(100) DEFAULT NULL, 
FIELD_DESC TEXT DEFAULT NULL, 
IS_FIELD_REQUIRED INT(10) DEFAULT NULL, 
STATUS INT(10) DEFAULT NULL, 
CREATED_DATE DATETIME, 
CREATED_BY BIGINT DEFAULT NULL, 
UPDATED_DATE DATETIME, 
UPDATED_BY BIGINT DEFAULT NULL, 
PRIMARY KEY (`ID`), 
FOREIGN KEY(SECTION_ID) REFERENCES `sourcelead`.`SOURCELEAD_FORM_SECTIONS`(ID), 
FOREIGN KEY(CREATED_BY) REFERENCES `sourcelead`.`USER`(ID), 
FOREIGN KEY(UPDATED_BY) REFERENCES `sourcelead`.`USER`(ID) 
); 


#This table is for org locations specific custom form fields 
DROP TABLE IF EXISTS `sourcelead`.`ORGLOCATION_FORM_FIELDS`; 
CREATE TABLE `sourcelead`.`ORGLOCATION_FORM_FIELDS` ( 
ID BIGINT NOT NULL AUTO_INCREMENT, 
SECTION_ID BIGINT DEFAULT NULL, 
ORGLOCATION_ID BIGINT DEFAULT NULL, 
ORG_ID BIGINT DEFAULT NULL, 
LABEL_NAME VARCHAR(500) DEFAULT NULL, 
FIELD_NAME VARCHAR(500) DEFAULT NULL, 
LABEL_INFO TEXT DEFAULT NULL, 
FIELD_TYPE VARCHAR(100) DEFAULT NULL, 
FIELD_DESC TEXT DEFAULT NULL, 
IS_FIELD_REQUIRED INT(10) DEFAULT NULL, 

SL_DEPENDANT_FIELD BIGINT DEFAULT NULL, 
CUSTOM_DEPENDANT_FIELD BIGINT DEFAULT NULL, 
MIN_LENGTH INT DEFAULT NULL, 
MAX_LENGTH INT DEFAULT NULL, 
MIN_DATE VARCHAR(100) DEFAULT NULL, 
MAX_DATE VARCHAR(100) DEFAULT NULL, 
MIN_NUMBER INT DEFAULT NULL, 
MAX_NUMBER INT DEFAULT NULL, 

STATUS INT(10) DEFAULT NULL, 
CREATED_DATE DATETIME, 
CREATED_BY BIGINT DEFAULT NULL, 
UPDATED_DATE DATETIME, 
UPDATED_BY BIGINT DEFAULT NULL, 
PRIMARY KEY (`ID`), 
FOREIGN KEY(SL_DEPENDANT_FIELD) REFERENCES `sourcelead`.`SOURCELEAD_FORM_FIELDS`(ID), 
FOREIGN KEY(CUSTOM_DEPENDANT_FIELD) REFERENCES `sourcelead`.`ORGLOCATION_FORM_FIELDS`(ID), 
FOREIGN KEY(SECTION_ID) REFERENCES `sourcelead`.`SOURCELEAD_FORM_SECTIONS`(ID), 
FOREIGN KEY(ORGLOCATION_ID) REFERENCES `sourcelead`.`ORG_LOCATIONS`(ID), 
FOREIGN KEY(ORG_ID) REFERENCES `sourcelead`.`ORG`(ID), 
FOREIGN KEY(CREATED_BY) REFERENCES `sourcelead`.`USER`(ID), 
FOREIGN KEY(UPDATED_BY) REFERENCES `sourcelead`.`USER`(ID) 
); 

#This table is for org locations specific custom form sub fields. ie.,(For selectbox, choices and radio buttons) 
DROP TABLE IF EXISTS `sourcelead`.`ORGLOCATION_FORM_SUB_FIELDS`; 
CREATE TABLE `sourcelead`.`ORGLOCATION_FORM_SUB_FIELDS` ( 
ID BIGINT NOT NULL AUTO_INCREMENT, 
FORM_FIELD_ID BIGINT DEFAULT NULL, 
LABEL_NAME VARCHAR(500) DEFAULT NULL, 
FIELD_NAME VARCHAR(500) DEFAULT NULL, 
FIELD_DESC TEXT DEFAULT NULL, 
STATUS INT(10) DEFAULT NULL, 
PRIMARY KEY (`ID`), 
FOREIGN KEY(FORM_FIELD_ID) REFERENCES `sourcelead`.`ORGLOCATION_FORM_FIELDS`(ID) 
); 

#Job sepecific custom fields data 
