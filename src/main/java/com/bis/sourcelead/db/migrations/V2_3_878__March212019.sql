
DROP TABLE IF EXISTS `PERFORMANCE_COMPETENCIES`;
CREATE TABLE `PERFORMANCE_COMPETENCIES`(
ID BIGINT NOT NULL AUTO_INCREMENT,
COMPETENCIES_NAME VARCHAR(500) DEFAULT NULL,
DESCRIPTION LONGTEXT DEFAULT NULL,
ORG_LOCATION_ID BIGINT DEFAULT NULL,
UUID VARCHAR(50) DEFAULT NULL,
STATUS INT,
CREATED_DATE DATE,
CREATED_BY BIGINT DEFAULT NULL,
UPDATED_DATE DATE,
UPDATED_BY BIGINT DEFAULT NULL,
PRIMARY KEY (`ID`),
FOREIGN KEY (CREATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY (UPDATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
);

DROP TABLE IF EXISTS `PERFORMANCE_TAG_COMPETENCIES`;
CREATE TABLE `PERFORMANCE_TAG_COMPETENCIES`(
ID BIGINT NOT NULL AUTO_INCREMENT,
ROLES TEXT DEFAULT NULL,
COMPETENCIES TEXT DEFAULT NULL,
COMPETENCIES_TAGGING_JSON_STRING LONGTEXT DEFAULT NULL,
ORG_LOCATION_ID BIGINT DEFAULT NULL,
UUID VARCHAR(50) DEFAULT NULL,
STATUS INT,
CREATED_DATE DATE,
CREATED_BY BIGINT DEFAULT NULL,
UPDATED_DATE DATE,
UPDATED_BY BIGINT DEFAULT NULL,
PRIMARY KEY (`ID`),
FOREIGN KEY (CREATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY (UPDATED_BY) REFERENCES `USER`(ID),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
);


DROP TABLE IF EXISTS `PERFORMANCE_APPRAISAL_TEMPLATE`;
CREATE TABLE `PERFORMANCE_APPRAISAL_TEMPLATE` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  NAME VARCHAR(500),
  APPRAISAL_START_DATE DATE,
  APPRAISAL_END_DATE DATE,
  DEPARTMENT TEXT DEFAULT NULL,
  ROLES TEXT DEFAULT NULL,
  EMPLOYEE_TYPE TEXT DEFAULT NULL,
  SELF_APPRAISAL_START_DATE DATE,
  SELF_APPRAISAL_END_DATE DATE,
  APPROVING_FROM_START_DATE DATE,
  APPROVING_FROM_END_DATE DATE,
  PROCESS_PERIOD_START_DATE DATE,
  PROCESS_PERIOD_END_DATE DATE,
  DESCRIPTION LONGTEXT DEFAULT NULL,
  DESCRIPTION_DISPLAY VARCHAR(10) DEFAULT NULL,
  CATEGORIES TEXT DEFAULT NULL,
  COMPETENCIES TEXT DEFAULT NULL,
  CATEGORIES_JSON_STRING LONGTEXT DEFAULT NULL,
  ORG_LOCATION_ID BIGINT,
  UUID VARCHAR(50) DEFAULT NULL,
  STATUS INT,
  CREATED_DATE DATETIME,
  CREATED_BY BIGINT,
  UPDATED_DATE DATETIME,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
) ;

