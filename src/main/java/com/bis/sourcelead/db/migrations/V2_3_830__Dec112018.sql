DROP TABLE IF EXISTS `IND_PAYSLIP`;
CREATE TABLE `IND_PAYSLIP` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  PAYSLIP_NAME VARCHAR(500) DEFAULT NULL,
  PAYSLIP_DESCRIPTION VARCHAR(500) DEFAULT NULL,
  
  COMPANY_NAME VARCHAR(10) DEFAULT 'N',
  COMPANY_ADDRESS VARCHAR(10) DEFAULT 'N',
  COMPANY_CONTACT_DETAILS VARCHAR(10) DEFAULT 'N',
  COMPANY_LOGO VARCHAR(10) DEFAULT 'N',
  
  EMPLOYEE_ID VARCHAR(10) DEFAULT 'N',
  EMPLOYEE_NAME VARCHAR(10) DEFAULT 'N',
  EMPLOYEE_TYPE VARCHAR(10) DEFAULT 'N',
  EMPLOYEE_CONTACT_DETAILS VARCHAR(10) DEFAULT 'N',
  EMPLOYEE_PROJECT VARCHAR(10) DEFAULT 'N',
  EMPLOYEE_JOIN_DATE VARCHAR(10) DEFAULT 'N',
  EMPLOYEE_PF_NUMBER VARCHAR(10) DEFAULT 'N',
  EMPLOYEE_ESI_NUMBER VARCHAR(10) DEFAULT 'N',
  EMPLOYEE_BANK_DETAILS VARCHAR(10) DEFAULT 'N',
  EMPLOYEE_LOCATION VARCHAR(10) DEFAULT 'N',
  EMPLOYEE_DESIGNATION VARCHAR(10) DEFAULT 'N',
  
  LEAVE_ATTENDED VARCHAR(10) DEFAULT 'N',
  LEAVE_LEAVES VARCHAR(10) DEFAULT 'N',
  LEAVE_LOP VARCHAR(10) DEFAULT 'N',
  
  PREVIOUS_MONTH_PAID VARCHAR(10) DEFAULT 'N',
  REGULAR_HOURS VARCHAR(10) DEFAULT 'N',
  OVERTIME_HOURS VARCHAR(10) DEFAULT 'N',
  
  ORGLOCATION_ID BIGINT,
  STATUS int,
  UUID VARCHAR(20) DEFAULT NULL,
  CREATED_DATE DATETIME,
  CREATED_BY BIGINT,
  UPDATED_DATE DATETIME,
  UPDATED_BY BIGINT,
  
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORGLOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID) 
);