
DROP TABLE IF EXISTS `SAVED_JOBS`;
CREATE TABLE `SAVED_JOBS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  USER_ID BIGINT DEFAULT NULL,
  REQUIREMENT_ID BIGINT DEFAULT NULL,
  REFER_ID BIGINT DEFAULT NULL,
  ORGLOCATION_ID BIGINT DEFAULT NULL,
  SAVED_JOB_UUID VARCHAR(20) DEFAULT NULL,
  STATUS INT(10),
  CREATED_DATE DATETIME,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATETIME,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`), 
  FOREIGN KEY(USER_ID) REFERENCES `USER`(ID),
  FOREIGN KEY(REQUIREMENT_ID) REFERENCES `REQUIREMENT`(ID),
  FOREIGN KEY(REFER_ID) REFERENCES `REQUIREMENT_REFER`(ID),
  FOREIGN KEY(ORGLOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
); 



DROP TABLE IF EXISTS `JOB_ALERTS_HISTORY`;
CREATE TABLE `JOB_ALERTS_HISTORY` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  USER_ID BIGINT DEFAULT NULL,
  ALERT_TITLE VARCHAR(100),
  SKILLS_NAME TEXT DEFAULT NULL,
  COUNTRY VARCHAR(50) DEFAULT NULL,
  STATE VARCHAR(50) DEFAULT NULL,
  CITY VARCHAR(50) DEFAULT NULL,
  EXPERIENCE VARCHAR(20),
  RATE VARCHAR(20),
  RATE_TYPE VARCHAR(20),
  RATE_CURRENCY VARCHAR(50),
  INDUSTRY_NAME VARCHAR(50),
  DURATION VARCHAR(50),
  EMAIL VARCHAR(100),
  JOB_ALERT_UUID VARCHAR(20),
  STATUS INT(10),
  CREATED_DATE DATETIME,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATETIME,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`), 
  FOREIGN KEY(USER_ID) REFERENCES `USER`(ID)
); 
