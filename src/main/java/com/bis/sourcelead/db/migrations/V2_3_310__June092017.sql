
DROP TABLE IF EXISTS `sourcelead`.`SAVED_JOBS`;
CREATE TABLE `sourcelead`.`SAVED_JOBS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  USER_ID BIGINT DEFAULT NULL,
  REQUIREMENT_ID BIGINT DEFAULT NULL,
  REFER_ID BIGINT DEFAULT NULL,
  ORGLOCATION_ID BIGINT DEFAULT NULL,
  SAVED_JOB_UUID VARCHAR(20) DEFAULT NULL,
  STATUS INT(10),
  CREATED_DATE DATETIME,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATETIME,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`), 
  FOREIGN KEY(USER_ID) REFERENCES `sourcelead`.`USER`(ID),
  FOREIGN KEY(REQUIREMENT_ID) REFERENCES `sourcelead`.`REQUIREMENT`(ID),
  FOREIGN KEY(REFER_ID) REFERENCES `sourcelead`.`REQUIREMENT_REFER`(ID),
  FOREIGN KEY(ORGLOCATION_ID) REFERENCES `sourcelead`.`ORG_LOCATIONS`(ID)
); 
