#APPLIED_LEAVE_DATE_VIEW
DROP VIEW APPLIED_LEAVE_DATE_VIEW;
CREATE  VIEW APPLIED_LEAVE_DATE_VIEW AS
SELECT 
	aLeaveDate.ID,
	aLeaveDate.APPLY_LEAVE_DATE,
	aLeaveDate.APPLY_MONTH_NAME,
	aLeaveDate.IS_PAYROLL_INCLUDE,
	aLeaveDate.STATUS,
	uLeave.USER_ID,
	uLeave.ORGLOCATION_ID,
    (SELECT ORG_ID FROM `ORG_LOCATIONS` WHERE ID = uLeave.ORGLOCATION_ID) AS ORG_ID,
	uLeave.LEAVE_TYPE_ID,
	uLeave.FROM_HALF_DAY,
	uLeave.TO_HALF_DAY,
	uLeave.FROM_DATE_FROM_TIME,
	uLeave.FROM_DATE_TO_TIME,
	uLeave.TO_DATE_FROM_TIME,
	uLeave.TO_DATE_TO_TIME,
	uLeave.FROM_DATE,
	uLeave.TO_DATE,
	uLeave.STATUS as LEAVE_STATUS,
	uLeave.REASON AS REASON
FROM USER_LEAVE uLeave,APPLIED_LEAVE_DATE aLeaveDate
where uLeave.ID = aLeaveDate.LEAVE_ID;