
DROP TABLE IF EXISTS `TIMESHEET_SUBMISSIONS_DOCUMENTS`;
CREATE TABLE `TIMESHEET_SUBMISSIONS_DOCUMENTS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  TIMESHEET_SUBMISSION_ID BIGINT DEFAULT NULL,
  DOC_FILE MEDIUMBLOB,
  FILE_CONTENT_TYPE VARCHAR(50),
  FILE_NAME TEXT DEFAULT NULL,
  STATUS INT,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(TIMESHEET_SUBMISSION_ID) REFERENCES `TIMESHEET_SUBMISSIONS`(ID)
);	

