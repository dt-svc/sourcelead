DROP TABLE IF EXISTS `sourcelead`.`REQUESTED_DOCUMENTS`;
CREATE TABLE `sourcelead`.`REQUESTED_DOCUMENTS` (
ID BIGINT NOT NULL AUTO_INCREMENT,
USER_ID BIGINT,
