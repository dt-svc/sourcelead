
DROP TABLE IF EXISTS `MASTER_CANDIDATE`;
CREATE TABLE `MASTER_CANDIDATE` (
ID BIGINT NOT NULL AUTO_INCREMENT,
FIRST_NAME VARCHAR(250),
LAST_NAME VARCHAR(250) DEFAULT NULL,
EMAIL VARCHAR(250),
ALTERNATE_EMAIL VARCHAR(250) DEFAULT NULL,
PHNO VARCHAR(50) DEFAULT NULL,
ALTERNATE_PHNO VARCHAR(50) DEFAULT NULL,
STATUS INT,
CREATED_DATE DATETIME,
CREATED_BY VARCHAR(10),
UPDATED_DATE DATETIME,
UPDATED_BY VARCHAR(10),
PRIMARY KEY (`ID`)
);

CALL AlterTableAddColumn ('CANDIDATE','MASTER_CANDIDATE_ID','BIGINT NULL AFTER `ID`');
ALTER TABLE `CANDIDATE` ADD CONSTRAINT `MASTER_CANDIDATE_ID_FK` FOREIGN KEY (`MASTER_CANDIDATE_ID`) REFERENCES `MASTER_CANDIDATE` (`ID`);



DROP TABLE IF EXISTS `REQUESTED_DOCUMENTS`;
CREATE TABLE `REQUESTED_DOCUMENTS` (
ID BIGINT NOT NULL AUTO_INCREMENT,
USER_ID BIGINT,
CANDIDATE_ID BIGINT,
ORG_LOCATION_ID BIGINT,
REQUEST_DOC_UUID VARCHAR(20) DEFAULT NULL,
IS_DOCS_UPLOADED VARCHAR(10) DEFAULT NULL,
STATUS INT,
CREATED_DATE DATETIME,
CREATED_BY VARCHAR(10),
UPDATED_DATE DATETIME,
UPDATED_BY VARCHAR(10),
PRIMARY KEY (`ID`),
FOREIGN KEY(USER_ID) REFERENCES `USER`(ID),
FOREIGN KEY(CANDIDATE_ID) REFERENCES `CANDIDATE`(ID),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
);


DROP TABLE IF EXISTS `REQUESTED_DOCUMENTS_HISTORY`;
CREATE TABLE `REQUESTED_DOCUMENTS_HISTORY` (
ID BIGINT NOT NULL AUTO_INCREMENT,
REQUESTED_DOCUMENTS_ID BIGINT,
DOCUMENT_TYPE VARCHAR(250) DEFAULT NULL,
DESCRIPTION TEXT DEFAULT NULL,
IS_REQUESTED_DOC_REQUIRED  VARCHAR(10) DEFAULT NULL,
STATUS INT,
CREATED_DATE DATETIME,
CREATED_BY VARCHAR(10),
UPDATED_DATE DATETIME,
UPDATED_BY VARCHAR(10),
PRIMARY KEY (`ID`),
FOREIGN KEY(REQUESTED_DOCUMENTS_ID) REFERENCES `REQUESTED_DOCUMENTS`(ID)
);

CALL AlterTableAddColumn ('CANDIDATE_DOCUMENTS','REQUESTED_DOC_ID','BIGINT NULL AFTER `ID`');
ALTER TABLE `CANDIDATE_DOCUMENTS` ADD CONSTRAINT `REQUESTED_DOC_ID_FK` FOREIGN KEY (`REQUESTED_DOC_ID`) REFERENCES `REQUESTED_DOCUMENTS` (`ID`);

CALL AlterTableAddColumn ('CANDIDATE_DOCUMENTS','IS_REQUESTED_DOC_REQUIRED','VARCHAR(10) NULL AFTER `REQUESTED_DOC_ID`');

CALL AlterTableAddColumn ('CANDIDATE_DOCUMENTS','DOC_UPLOAD_STATUS','VARCHAR(20) NULL AFTER `IS_REQUESTED_DOC_REQUIRED`');

CALL AlterTableAddColumn ('CANDIDATE_DOCUMENTS','REQUESTED_DOC_STATUS','VARCHAR(20) NULL AFTER `DOC_UPLOAD_STATUS`');

