#LEAVE_AND_LEAVE_TYPE_VIEW
CREATE OR REPLACE VIEW LEAVE_AND_LEAVE_TYPE_VIEW AS
SELECT
LT.*,
UL.ID AS LEAVE_ID,
UL.FROM_DATE,
UL.TO_DATE,
UL.USER_ID 
FROM
LEAVE_TYPE LT,
USER_LEAVE UL
WHERE UL.LEAVE_TYPE_ID = LT.ID;


#APPLIED_LEAVE_DATE_VIEW
CREATE OR REPLACE VIEW APPLIED_LEAVE_DATE_VIEW AS
SELECT uLeave.USER_ID,
uLeave.ORGLOCATION_ID,
uLeave.LEAVE_TYPE_ID,
uLeave.STATUS as LEAVE_STATUS,
uLeave.REASON AS REASON,
aLeaveDate.APPLY_LEAVE_DATE,
aLeaveDate.APPLY_MONTH_NAME,
aLeaveDate.IS_PAYROLL_INCLUDE,
aLeaveDate.STATUS
FROM sourcelead.USER_LEAVE uLeave,APPLIED_LEAVE_DATE aLeaveDate
where uLeave.ID = aLeaveDate.LEAVE_ID;

DROP PROCEDURE IF EXISTS updateAssociateBalLeave;
DELIMITER //
CREATE PROCEDURE updateAssociateBalLeave(
totalLeaves varchar(20),
locationID BIGINT,
userID BIGINT,
leaveTypeID BIGINT
)
BEGIN
UPDATE ASSOCIATE_BALANCE_LEAVES
SET TOTAL_LEAVES = totalLeaves
WHERE ORG_LOCATION_ID = locationID and USER_ID = userID and LEAVE_TYPE_ID = leaveTypeID;
END//
DELIMITER ;



