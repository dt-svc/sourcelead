
DROP TABLE IF EXISTS `ORG_LICENSE_PAYMENT_TRANSACTION_HISTORY`;
CREATE TABLE `ORG_LICENSE_PAYMENT_TRANSACTION_HISTORY` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_LICENSE_SUBSCRIPTION_ID BIGINT DEFAULT NULL,
  LICENSE_TYPE VARCHAR(100) DEFAULT NULL,
  CURRENCY VARCHAR(10) DEFAULT NULL,
  INVOICE_AMOUNT DOUBLE DEFAULT NULL,
  PAYMENT_ID TEXT DEFAULT NULL,
  ORDER_ID TEXT DEFAULT NULL,
  RECEPIT_ID TEXT DEFAULT NULL,
  INVOICE_NUMBER TEXT DEFAULT NULL,
  TRANSACTION_ID TEXT DEFAULT NULL,
  TRANSACTION_PAYER_ID TEXT DEFAULT NULL,
  TRANSACTION_USER TEXT DEFAULT NULL,
  TRANSACTION_USER_EMAIL TEXT DEFAULT NULL,
  TRANSACTION_DATE DATE,
  PRIMARY KEY (`ID`), 
  FOREIGN KEY(ORG_LICENSE_SUBSCRIPTION_ID) REFERENCES `ORG_LICENSE_SUBSCRIPTION`(ID)
); 
