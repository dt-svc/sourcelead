DROP TABLE IF EXISTS `SOURCELEAD_TAX_CHALLAN`;


CREATE TABLE `SOURCELEAD_TAX_CHALLAN` (
	ID BIGINT NOT NULL AUTO_INCREMENT,
	LABEL_NAME VARCHAR(100),
    DESCRIPTION VARCHAR(100),
	SOURCELEAD_TAX_FORM_ID BIGINT DEFAULT NULL,
	UUID VARCHAR(20),
	ACTIVE BOOLEAN DEFAULT TRUE,
	PRIMARY KEY (`ID`),
	FOREIGN KEY(SOURCELEAD_TAX_FORM_ID) REFERENCES `SOURCELEAD_TAX_FORM`(ID)
);


CREATE TABLE `SOURCELEAD_TAX_CHALLAN_ITEM` (
	ID BIGINT NOT NULL AUTO_INCREMENT,
	FIELD_TYPE VARCHAR(200),
	LABEL_NAME VARCHAR(250),
	IS_FIELD_REQUIRED BOOLEAN DEFAULT FALSE,
	PLACEHOLDER VARCHAR(200),
	MIN_LENGTH int  DEFAULT 0,
	MAX_LENGTH int DEFAULT 0,
	MIN_DATE date,
	MAX_DATE date,
	MIN_NUMBER int DEFAULT 0,
	MAX_NUMBER int DEFAULT 0,
	HELPTEXT VARCHAR(200),
	DATAVALIDATION_TYPE VARCHAR(200),
	DATAVALIDATION_RANGE VARCHAR(200),
	CREATED_DATE DATE,
	UPDATED_DATE DATE,
    MAX_LIMIT DOUBLE DEFAULT 0,
    DISCRIPTION VARCHAR(500),
	SOURCELEAD_TAX_CHALLAN_ID BIGINT DEFAULT NULL,
	ACTIVE BOOLEAN DEFAULT TRUE,
	PRIMARY KEY (`ID`),
	FOREIGN KEY(SOURCELEAD_TAX_CHALLAN_ID) REFERENCES `SOURCELEAD_TAX_CHALLAN`(ID)
);





CREATE TABLE `SOURCELEAD_TAX_CHALLAN_ITEM_SUB_FORMFIELD` (
	ID BIGINT NOT NULL AUTO_INCREMENT,
	SOURCELEAD_TAX_CHALLAN_ITEM_ID  BIGINT NOT NULL ,
	LABEL_NAME VARCHAR(100),
	PRIMARY KEY (`ID`),
	FOREIGN KEY(SOURCELEAD_TAX_CHALLAN_ITEM_ID) REFERENCES `SOURCELEAD_TAX_CHALLAN_ITEM`(ID)
);



