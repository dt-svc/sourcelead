#Client sepecific custom fields data 
DROP TABLE IF EXISTS `CLIENT_CUSTOM_FIELD_DATA`; 
CREATE TABLE `CLIENT_CUSTOM_FIELD_DATA` ( 
ID BIGINT NOT NULL AUTO_INCREMENT, 
CLIENT_ID BIGINT DEFAULT NULL, 
CUSTOM_FORM_FIELD_ID BIGINT DEFAULT NULL, 
CUSTOM_FORM_FIELD_DATA TEXT DEFAULT NULL, 
FORM_FIELD_ADDITIONAL_DATA_1 TEXT DEFAULT NULL, 
FORM_FIELD_ADDITIONAL_DATA_2 TEXT DEFAULT NULL,
PRIMARY KEY (`ID`), 
FOREIGN KEY(CLIENT_ID) REFERENCES `ORG`(ID), 
FOREIGN KEY(CUSTOM_FORM_FIELD_ID) REFERENCES `ORGLOCATION_FORM_FIELDS`(ID) 
); 