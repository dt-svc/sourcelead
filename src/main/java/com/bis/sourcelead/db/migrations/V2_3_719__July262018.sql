DROP TABLE IF EXISTS `EXPENSE_PROJECT_APPROVER_HIERARCHY`;
CREATE TABLE `EXPENSE_PROJECT_APPROVER_HIERARCHY` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  PROJECT_ID BIGINT DEFAULT NULL,
  PROJECT_CLIENTS_ID BIGINT DEFAULT NULL,
  APPROVER_USER_ID BIGINT DEFAULT NULL,
  LEVEL INT(10) NOT NULL,
  STATUS VARCHAR(20),
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(PROJECT_ID) REFERENCES PROJECTS(ID),
  FOREIGN KEY(PROJECT_CLIENTS_ID) REFERENCES PROJECT_CLIENTS(ID),
  FOREIGN KEY(APPROVER_USER_ID) REFERENCES USER(ID)
);