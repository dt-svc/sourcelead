CREATE OR REPLACE VIEW RECRUITER_REPORT_ASSOCIATE_COUNT_VIEW AS
SELECT
MAX(REQ.ID) AS REQ_ID,
DATE_FORMAT(REQ.CREATED_DATE ,"%Y-%m-%d") AS CREATED_DATE,
REQ.CREATED_BY AS USER_ID,
REQ.ORG_LOCATION_ID AS ORG_LOCATION_ID,
COUNT(REQ.ID) AS REQ_COUNT,

    
	(SELECT OL.ORG_ID 
         FROM 
         ORG_LOCATIONS OL 
         WHERE OL.ID = REQ.ORG_LOCATION_ID) AS ORG_ID    
         
    
FROM
    REQUIREMENT REQ

GROUP BY REQ.CREATED_BY,  
DATE_FORMAT(REQ.CREATED_DATE ,"%Y-%m-%d");




CREATE OR REPLACE VIEW RECRUITER_REPORT_CANDIDATE_COUNT_VIEW AS
SELECT
MAX(CAND.ID) AS CAND_ID,
DATE_FORMAT(CAND.CREATED_DATE ,"%Y-%m-%d") AS CREATED_DATE,
CAND.CREATED_BY AS USER_CODE,
CAND.ORG_LOCATION_ID AS ORG_LOCATION_ID,
COUNT(CAND.ID) AS CAND_COUNT,

    
	(SELECT OL.ORG_ID 
         FROM 
         ORG_LOCATIONS OL 
         WHERE OL.ID = CAND.ORG_LOCATION_ID) AS ORG_ID    
         
    
FROM
    CANDIDATE CAND

GROUP BY CAND.CREATED_BY,  
DATE_FORMAT(CAND.CREATED_DATE ,"%Y-%m-%d");




