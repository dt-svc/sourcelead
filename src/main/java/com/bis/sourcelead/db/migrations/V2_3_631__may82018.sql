
DROP TABLE IF EXISTS `ORGLOCATION_INDIA_BANKING_DETAILS`;
CREATE TABLE `ORGLOCATION_INDIA_BANKING_DETAILS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORGLOCATION_ID BIGINT,
  ACCOUNT_NAME VARCHAR(500) DEFAULT NULL,
  BANK_NAME VARCHAR(500) DEFAULT NULL,
  BANK_ADDRESS TEXT DEFAULT NULL,
  ACCOUNT_NUMBER  VARCHAR(100) DEFAULT NULL,
  IFSC_CODE  VARCHAR(50) DEFAULT NULL,
  BSR_NUMBER  VARCHAR(50) DEFAULT NULL,
  MICR_CODE  VARCHAR(50) DEFAULT NULL,
  UUID VARCHAR(50) DEFAULT NULL,
  STATUS INT DEFAULT NULL,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORGLOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
) ;