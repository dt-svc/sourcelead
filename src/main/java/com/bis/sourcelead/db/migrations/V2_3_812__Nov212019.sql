#ORGLOCATION_DEPOSIT_TAXES  
DROP TABLE IF EXISTS `ORGLOCATION_DEPOSIT_TAXES`;
CREATE TABLE `ORGLOCATION_DEPOSIT_TAXES` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_LOCATION_ID BIGINT,
  FILLER_TYPE varchar(45),
  FEDERAL_DEPOSIT varchar(45),
  TAX_DEPOSIT_SCHEDULE varchar(45),
  STATUS int,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
) ;
