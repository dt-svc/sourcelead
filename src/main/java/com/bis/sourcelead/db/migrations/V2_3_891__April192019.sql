CREATE OR REPLACE VIEW OFFER_ACCEPTANCE_RATE_VIEW_FOR_VENDOR AS
    SELECT 
        MAX(RSH.ID) AS RSH_ID,
        RSH.REQUIREMENT_SUBMISSION_ID AS REQUIREMENT_SUBMISSION_ID,
        (SELECT RS.REQUIREMENT_ID
            FROM REQUIREMENT_SUBMISSION RS
            WHERE RS.ID = RSH.REQUIREMENT_SUBMISSION_ID) AS REQUIREMENT_ID, 
		(SELECT R.PARENT_REQUIREMENT_ID
			FROM REQUIREMENT R
            WHERE R.ID = REQUIREMENT_ID) AS PARENT_REQUIREMENT_ID,
        (SELECT R.ORG_RELATION_ID	
            FROM REQUIREMENT R
            WHERE R.ID=(SELECT RS.REQUIREMENT_ID FROM REQUIREMENT_SUBMISSION RS WHERE  RS.ID = RSH.REQUIREMENT_SUBMISSION_ID))
            AS ORG_RELATION_ID,
		(SELECT R.SPOC_ID 
			FROM REQUIREMENT R 
            WHERE R.ID=(SELECT RS.REQUIREMENT_ID FROM REQUIREMENT_SUBMISSION RS WHERE RS.ID=RSH.REQUIREMENT_SUBMISSION_ID))
            AS ORG_SPOC_ID,
        DATE_FORMAT(RSH.CREATED_DATE ,"%Y") AS CREATED_YEAR,
        DATE_FORMAT(RSH.CREATED_DATE ,"%Y-%m") AS CREATED_YEAR_MONTH,
        DATE_FORMAT(RSH.CREATED_DATE ,"%Y-%m-%d") AS CREATED_YEAR_MONTH_DATE,
        RSH.MASTER_USER_CODE AS USER_CODE,
        SUM(CASE
			WHEN UPPER(RSH.TO_STAGE) = 'OFFERMADE' THEN 1
			ELSE 0
			END) AS OFFERMADE_COUNT,
		SUM(CASE
			WHEN UPPER(RSH.TO_STAGE) = 'OFFERACCEPTED' THEN 1
			ELSE 0
			END) AS OFFERACCEPTED_COUNT,
		SUM(CASE
			WHEN UPPER(RSH.TO_STAGE) = 'OFFERREJECTED' THEN 1
			ELSE 0
			END) AS OFFERREJECTED_COUNT,
        (SELECT RS.ORG_LOCATION_ID
			FROM
			REQUIREMENT_SUBMISSION RS
			WHERE RS.ID =RSH.REQUIREMENT_SUBMISSION_ID) AS ORG_LOCATION_ID,
		(SELECT OL.ORG_ID
			FROM
			ORG_LOCATIONS OL
			WHERE OL.ID =ORG_LOCATION_ID) AS ORG_ID
	FROM
		REQUIREMENT_SUBMISSION_HISTORY RSH
	GROUP BY RSH.ID,
	DATE_FORMAT(RSH.CREATED_DATE ,"%Y-%m-%d")