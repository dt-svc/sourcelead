DROP TABLE IF EXISTS `WHITELIST_IP_ADDRESS`;
CREATE TABLE `WhiteList_IP_ADDRESS` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_LOCATION_ID BIGINT,
  FROM_IP_ADDRESS VARCHAR(100) DEFAULT NULL,
  TO_IP_ADDRESS VARCHAR(100) DEFAULT NULL,
  STATUS VARCHAR(50) DEFAULT NULL,
  CREATED_DATE DATE,
  CREATED_BY BIGINT,
  UPDATED_DATE DATE,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
) ;

