DROP TABLE IF EXISTS `BGC_CANDIDATE_DETAILS`;
CREATE TABLE `BGC_CANDIDATE_DETAILS` (
	`ID` BIGINT NOT NULL AUTO_INCREMENT,
	`ORG_LOCATION_ID` BIGINT DEFAULT NULL,
	`BGC_UUID` VARCHAR(20) DEFAULT NULL,
	`CANDIDATE_ID` BIGINT DEFAULT NULL,
	`CURRENT_BGC_STATUS` VARCHAR(100) DEFAULT NULL,
	`PERSONAL_INFO_STATUS` VARCHAR(50) DEFAULT NULL,
	`EDUCATION_CHECK_STATUS` VARCHAR(50) DEFAULT NULL,
	`PRIOR_EMPLOYERS_CHECK_STATUS` VARCHAR(50) DEFAULT NULL,
	`HEALTH_CHECK_STATUS` VARCHAR(50) DEFAULT NULL,
	`CRIME_RECORD_STATUS` VARCHAR(50) DEFAULT NULL,
	`OTHERS_INFO_STATUS` VARCHAR(50) DEFAULT NULL,
	`UPDATED_PERCENTAGE` VARCHAR(10) DEFAULT NULL,
	`COMMENTS` TEXT DEFAULT NULL,
	`STATUS` int,
	`CREATED_DATE` DATE,
	`CREATED_BY` BIGINT,
	`UPDATED_DATE` DATE,
	`UPDATED_BY` BIGINT,
	 PRIMARY KEY (`ID`),
	 FOREIGN KEY(CANDIDATE_ID) REFERENCES `CANDIDATE`(ID),
	 FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID),
	 FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
	 FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
);
DROP TABLE IF EXISTS `BGC_CANDIDATE_DOCS`;
CREATE TABLE `BGC_CANDIDATE_DOCS`(
	`ID` BIGINT NOT NULL AUTO_INCREMENT,
	`BGC_CANDIDATES_DETAILS_ID` BIGINT DEFAULT NULL,
	`DOCUMENT_UUID` VARCHAR(20) DEFAULT NULL,
	`DOCUMENT_TYPE` VARCHAR(20) DEFAULT NULL,
	`DOCUMENT_CATEGORY` VARCHAR(20) DEFAULT NULL,
	`STATUS` int,
	`CREATED_DATE` DATE,
	`CREATED_BY` BIGINT,
	`UPDATED_DATE` DATE,
	`UPDATED_BY` BIGINT,
	 PRIMARY KEY (`ID`),
	 FOREIGN KEY(BGC_CANDIDATES_DETAILS_ID) REFERENCES `BGC_CANDIDATE_DETAILS`(ID),
	 FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
	 FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
);

DROP TABLE IF EXISTS `BGC_CANDIDATE_DOCS_HISTORY`;
