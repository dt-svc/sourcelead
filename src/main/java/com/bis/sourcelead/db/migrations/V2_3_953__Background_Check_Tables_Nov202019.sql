	`FILE_NAME` VARCHAR(200) DEFAULT NULL,
	`FILE_URL` VARCHAR(250) DEFAULT NULL,
	`FILE_CONTENT_TYPE` VARCHAR(50) DEFAULT NULL,
	`DESCRIPTION` TEXT DEFAULT NULL,
	`STATUS` int,
	`CREATED_DATE` DATE,
	`CREATED_BY` BIGINT,
	`UPDATED_DATE` DATE,
	`UPDATED_BY` BIGINT,
	 PRIMARY KEY (`ID`),
	 FOREIGN KEY(BGC_CANDIDATE_DOCS_ID) REFERENCES `BGC_CANDIDATE_DOCS`(ID),
	 FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
	 FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
 );
 
