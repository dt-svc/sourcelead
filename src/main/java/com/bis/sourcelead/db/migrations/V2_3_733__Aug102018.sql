SET FOREIGN_KEY_CHECKS=0;

DROP TABLE IF EXISTS `PAYROLL_PAYHEAD_SALARY_SETUP`;
DROP TABLE IF EXISTS `PAYROLL_PAYHEAD_SALARY_SETUP_HISTORY`;
CREATE TABLE `PAYROLL_PAYHEAD_SALARY_SETUP_HISTORY` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  PAYHEAD BIGINT,
  PAYHEAD_NAME VARCHAR(100),
  METHOD VARCHAR(100),
  FORMULA TEXT,
  CREATED_DATE DATETIME,
  CREATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(PAYHEAD) REFERENCES `PAYROLL_PAYHEAD`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID)
);


DROP TABLE IF EXISTS `ASSOCIATE_SALARY_IND`;
CREATE TABLE `ASSOCIATE_SALARY_IND` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  CANDIDATE BIGINT,
  CTC DECIMAL(20,2),
  FBP DECIMAL(20,2),
  VARIABLE_PAY DECIMAL(20,2),
  STATUS int,
  UUID VARCHAR(20) DEFAULT NULL,
  CREATED_DATE DATETIME,
  CREATED_BY BIGINT,
  UPDATED_DATE DATETIME,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(CANDIDATE) REFERENCES `CANDIDATE`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
);


DROP TABLE IF EXISTS `ASSOCIATE_SALARY_PAYHEAD_IND`;
CREATE TABLE `ASSOCIATE_SALARY_PAYHEAD_IND` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ASSOCIATE_SALARY_IND BIGINT,
  PAYROLL_PAYHEAD BIGINT,
  MONTHLY DECIMAL(20,2),
  ANNUALY DECIMAL(20,2),
  STATUS int,
  UUID VARCHAR(20) DEFAULT NULL,
  CREATED_DATE DATETIME,
  CREATED_BY BIGINT,
  UPDATED_DATE DATETIME,
  UPDATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ASSOCIATE_SALARY_IND) REFERENCES `ASSOCIATE_SALARY_IND`(ID),
  FOREIGN KEY(PAYROLL_PAYHEAD) REFERENCES `PAYROLL_PAYHEAD`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID),
  FOREIGN KEY(UPDATED_BY) REFERENCES `USER`(ID)
);

SET FOREIGN_KEY_CHECKS=1;