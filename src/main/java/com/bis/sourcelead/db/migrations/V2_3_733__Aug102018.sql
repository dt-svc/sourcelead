CREATE TABLE `PAYROLL_PAYHEAD_SALARY_SETUP_HISTORY` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  PAYHEAD BIGINT,
  PAYHEAD_NAME VARCHAR(100),
  METHOD VARCHAR(100),
  FORMULA TEXT,
  CREATED_DATE DATETIME,
  CREATED_BY BIGINT,
  PRIMARY KEY (`ID`),
  FOREIGN KEY(PAYHEAD) REFERENCES `PAYROLL_PAYHEAD`(ID),
  FOREIGN KEY(CREATED_BY) REFERENCES `USER`(ID)
);


