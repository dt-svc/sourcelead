  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_lOCATION_ID BIGINT,
  EMAIL_ID varchar(500),
  EMAIL_PASSWORD varchar(50),
  EMAIL_UUID varchar(10),
  SERVER_NAME varchar(500),
  VERIFIED_STATUS varchar(2),
  ENCRYPTION_TYPE varchar(10),
  PORT_NUMBER BIGINT,
