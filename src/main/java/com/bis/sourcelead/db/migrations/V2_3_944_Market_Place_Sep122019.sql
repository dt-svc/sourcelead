#BELOW TABLES ARE CREATED FOR MARKETPLACE FUNCTIONALITY TO SHARE PRODUCTS IN SOURCELEAD APPLICATION. CREATED ON 13-SEP-2019.

DROP TABLE IF EXISTS `MARKETPLACE_PRODUCT_FILES_HISTORY`;
DROP TABLE IF EXISTS `MARKETPLACE_PRODUCT_NEGOTIATION_HISTORY`;
DROP TABLE IF EXISTS `MARKETPLACE_PRODUCTS`;
CREATE TABLE `MARKETPLACE_PRODUCTS`(
   `ID` BIGINT NOT NULL AUTO_INCREMENT,
	`ASSOCIATE_ID` BIGINT DEFAULT NULL,
	`UUID` VARCHAR(50) DEFAULT NULL,
	`ORG_ID` BIGINT DEFAULT NULL,
	`ORG_LOCATION_ID` BIGINT DEFAULT NULL,
	`PRODUCT_CODE` VARCHAR(10) DEFAULT NULL,
	`PRODUCT_NAME` VARCHAR(10) DEFAULT NULL,
	`PRODUCT_SHARE_TYPE` VARCHAR(10) DEFAULT NULL,
	`SHARE_CONTACT_DETAILS` VARCHAR(10) DEFAULT NULL,
	`PRODUCT_DESCRIPTION` VARCHAR(50) DEFAULT NULL,
	`IS_NEGOTIABLE` VARCHAR(10) DEFAULT NULL,
	`FINAL_PRICE` VARCHAR(50) DEFAULT NULL,
	`MANUFACTURER_NAME` VARCHAR(10) DEFAULT NULL,
	`MANUFACTURER_DATE` DATE DEFAULT NULL,
	`IS_IN_WARRANTY` VARCHAR(10) DEFAULT NULL,
	`WARRANTY_END_DATE` DATE DEFAULT NULL,
	`PRODUCT_CURRENT_STATUS`  VARCHAR(50) DEFAULT NULL,
	`AVLBL_QUANTITY` INT DEFAULT NULL,
	`PRODUCT_AVLBL_END_DATE` DATE DEFAULT NULL,
	`CATEGORY` VARCHAR(50) DEFAULT NULL,
	`PRICE` VARCHAR(50) DEFAULT NULL,
	`CURRENT_RATE_CURRENCY` VARCHAR(10) DEFAULT NULL,
	`STATUS` VARCHAR(10) DEFAULT NULL,
	`CREATED_DATE` DATE DEFAULT NULL,
	`CREATED_BY` BIGINT DEFAULT NULL,
	`UPDATED_DATE` DATE DEFAULT NULL,
	`UPDATED_BY` BIGINT DEFAULT NULL, 
	
	PRIMARY KEY (`ID`),
	FOREIGN KEY (`ASSOCIATE_ID`) REFERENCES `USER` (`ID`),
	FOREIGN KEY(`CREATED_BY`) REFERENCES `USER`(ID),
	FOREIGN KEY(`UPDATED_BY`) REFERENCES `USER`(ID),
	FOREIGN KEY(`ORG_LOCATION_ID`) REFERENCES `ORG_LOCATIONS`(ID),
	FOREIGN KEY(`ORG_ID`) REFERENCES `ORG`(ID)
);

DROP TABLE IF EXISTS `MARKETPLACE_PRODUCT_FILES_HISTORY`;
CREATE TABLE `MARKETPLACE_PRODUCT_FILES_HISTORY` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  `MARKETPLACE_PRODUCT_ID` BIGINT DEFAULT NULL,
  `UPLOADED_FILE_NAME` VARCHAR(250) DEFAULT NULL,
  `UPLOADED_FILE_CONTENT_TYPE` VARCHAR(250) DEFAULT NULL,
  `UPLOADED_FILE_URL` VARCHAR(250) DEFAULT NULL,
  `STATUS` INT(10) DEFAULT NULL,
  `CREATED_DATE` DATE DEFAULT NULL,
  `CREATED_BY` BIGINT DEFAULT NULL, 
  `UPDATED_DATE` DATE DEFAULT NULL,
  `UPDATED_BY` BIGINT DEFAULT NULL, 
 
  PRIMARY KEY (`ID`),
  FOREIGN KEY(`MARKETPLACE_PRODUCT_ID`) REFERENCES `MARKETPLACE_PRODUCTS`(ID),
  FOREIGN KEY(`CREATED_BY`) REFERENCES `USER`(ID), 
  FOREIGN KEY(`UPDATED_BY`) REFERENCES `USER`(ID)
 
);
DROP TABLE IF EXISTS `MARKETPLACE_PRODUCT_NEGOTIATION_HISTORY`;
CREATE TABLE `MARKETPLACE_PRODUCT_NEGOTIATION_HISTORY` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  `MARKETPLACE_PRODUCT_ID` BIGINT NOT NULL,
  `NEGOTIATED_PRICE` VARCHAR(50) DEFAULT NULL,
  `NEGOTIATED_QUANTITY` INT DEFAULT NULL,
  `APPROVED_USER_ID` BIGINT  NOT NULL,
  `APPROVED_PRICE` VARCHAR(50) DEFAULT NULL,
  `APPROVED_DATE` DATE DEFAULT NULL,
  `UUID` VARCHAR(50) NULL DEFAULT NULL,
  `REQUESTED_USER_ID` BIGINT UNSIGNED NOT NULL,
  `REQUESTED_DATE` DATE DEFAULT NULL ,
 
  PRIMARY KEY (`ID`),
  FOREIGN KEY(`MARKETPLACE_PRODUCT_ID`) REFERENCES `MARKETPLACE_PRODUCTS`(ID)

  );