#This table for associate list screen 

DROP TABLE IF EXISTS `ASSOCIATE_MARKET_PLACE_LIST`;
CREATE TABLE `ASSOCIATE_MARKET_PLACE_LIST`(
ID BIGINT NOT NULL AUTO_INCREMENT,
ASSOCIATE_NAME VARCHAR(10) DEFAULT NULL,
COMPANY_NAME VARCHAR(50) DEFAULT NULL,
RELOCATE_TO VARCHAR(50) DEFAULT NULL,
NUMBER_OF_ITEMS INT(10) DEFAULT NULL,
REASON_FOR_RELOCATION VARCHAR(500) DEFAULT NULL,
CREATED_ON DATETIME,
PRIMARY KEY (`ID`)
);



#This table for Product list screen

DROP TABLE IF EXISTS `PRODUCTION_LIST`;
CREATE TABLE `PRODUCTION_LIST`(
ID BIGINT NOT NULL AUTO_INCREMENT,
PRODUCT_NAME VARCHAR(10) DEFAULT NULL,
DESCRIPTION VARCHAR(500) DEFAULT NULL,
PRODUCT_COST INT(10) DEFAULT NULL,
CONTACT_PERSON VARCHAR(10) DEFAULT NULL,
IMAGE LONGBLOB DEFAULT NULL,
PRIMARY KEY (`ID`)
);


# This table for add products

DROP TABLE IF EXISTS `ADD_PRODUCTS`;
CREATE TABLE `ADD_PRODUCTS`(
ID BIGINT NOT NULL AUTO_INCREMENT,
PRODUCT_CODE VARCHAR(10) DEFAULT NULL,
PRODUCT_TYPE VARCHAR(10) DEFAULT NULL,
CATEGORY VARCHAR(50) DEFAULT NULL,
PRICE INT(10) DEFAULT NULL,
PRIORITY VARCHAR(50) DEFAULT NULL,
STATUS VARCHAR(10) DEFAULT NULL,
NOTIFY_TO VARCHAR(10) DEFAULT NULL,
PUBLIC_OR_PRIVATE BOOLEAN DEFAULT NULL,
SHARE_DETAILS BOOLEAN DEFAULT NULL,
PRODUCT_DESCRIPTION VARCHAR(50) DEFAULT NULL,
ATTACHMENT BLOB DEFAULT NULL,
PRIMARY KEY (`ID`)
);


