#Mail Account Settings
DROP TABLE IF EXISTS `sourcelead`.`EMAIL_ACCOUNT_SETTINGS`;
CREATE TABLE `sourcelead`.`EMAIL_ACCOUNT_SETTINGS` (
 ID BIGINT NOT NULL AUTO_INCREMENT,
  USER_ID BIGINT,
  EMAIL VARCHAR(100) DEFAULT NULL,
  PASSWORD VARCHAR(100) DEFAULT NULL,
  RECIEVE_SERVER_NAME VARCHAR(100) DEFAULT NULL,
  RECIEVE_PORT VARCHAR(100) DEFAULT NULL,
  RECIEVE_EMAIL VARCHAR(100) DEFAULT NULL,
  RECIEVE_SSL VARCHAR(100) DEFAULT NULL,
  SEND_SERVER_NAME VARCHAR(100) DEFAULT NULL,
  SEND_PORT VARCHAR(100) DEFAULT NULL,
  SEND_EMAIL VARCHAR(100) DEFAULT NULL,
  SEND_SSL VARCHAR(100) DEFAULT NULL,
  EMAIL_TYPE VARCHAR(20) DEFAULT NULL,
  CREATED_DATE DATE,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATE,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(USER_ID) REFERENCES `sourcelead`.`USER`(ID)
) ;