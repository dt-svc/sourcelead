SDI_SUI FLOAT DEFAULT NULL,
LOCAL FLOAT DEFAULT NULL,
DEDS FLOAT DEFAULT NULL,
NET FLOAT DEFAULT NULL,
FROM_DATE DATETIME,
TO_DATE DATETIME,
BATCH_NUMBER VARCHAR(100),
