
DROP TABLE IF EXISTS `EMPLOYER_PAYROLL_COST`;
CREATE TABLE `EMPLOYER_PAYROLL_COST` (
ID BIGINT NOT NULL AUTO_INCREMENT,
ORG_LOCATION_ID BIGINT DEFAULT NULL,
EMPLOYEE_ID VARCHAR(100) DEFAULT NULL,
EMPLOYEE_NAME VARCHAR(250) DEFAULT NULL,
SSN VARCHAR(250),
TOTAL_HRS VARCHAR(250),
GROSS_WAGES FLOAT DEFAULT NULL,
FICA FLOAT DEFAULT NULL,
FUTA FLOAT DEFAULT NULL,
SUI FLOAT DEFAULT NULL,
ER_LOCALS FLOAT DEFAULT NULL,
WC_COST FLOAT DEFAULT NULL,
ADMIN_FEE FLOAT DEFAULT NULL,
TOTAL_ER_COST FLOAT DEFAULT NULL,
FROM_DATE DATETIME,
TO_DATE DATETIME,
BATCH_NUMBER VARCHAR(100),
STATUS VARCHAR(20),
CREATED_DATE DATETIME,
CREATED_BY VARCHAR(10),
UPDATED_DATE DATETIME,
UPDATED_BY VARCHAR(10),
PRIMARY KEY (`ID`),
FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
);


