DROP TABLE IF EXISTS `CANDIDATE`;
CREATE TABLE `CANDIDATE` (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORG_LOCATION_ID BIGINT,
  FIRST_NAME VARCHAR(100)  DEFAULT NULL,
  LAST_NAME VARCHAR(100)  DEFAULT NULL,
  EMAIL VARCHAR(100) DEFAULT NULL,
  ALTERNATE_EMAIL VARCHAR(100) DEFAULT NULL,
  MOBILE_PHONE VARCHAR(20) DEFAULT NULL,
  ALTERNATE_MOBILE_PHONE VARCHAR(20) DEFAULT NULL,
  COUNTRY VARCHAR(50) DEFAULT NULL,
  STATE VARCHAR(50) DEFAULT NULL,
  CITY VARCHAR(50) DEFAULT NULL,
  ADDRESS VARCHAR(250) DEFAULT NULL,
  EXPERIENCE_YEARS VARCHAR(2) DEFAULT NULL,
  EXPERIENCE_MONTHS VARCHAR(2) DEFAULT NULL,
  DESIGNATION VARCHAR(250) DEFAULT NULL,
  DESIGNATION_TYPE VARCHAR(250) DEFAULT NULL, 
  CURRENT_RATE VARCHAR(250) DEFAULT NULL,
  CURRENT_RATE_CURRENCY VARCHAR(20) DEFAULT NULL,
  EXPECTED_RATE VARCHAR(250) DEFAULT NULL,
  EXPECTED_RATE_CURRENCY VARCHAR(20) DEFAULT NULL,
  SUMMARY VARCHAR(5000) DEFAULT NULL,
  DOC_FILE MEDIUMBLOB,
  FILE_CONTENT_TYPE VARCHAR(50),
  FILE_NAME VARCHAR(50),
  STATUS VARCHAR(20),
  INVITATION_STATUS VARCHAR(20),  
  CREATED_DATE DATETIME,
  CREATED_BY VARCHAR(10),
  UPDATED_DATE DATETIME,
  UPDATED_BY VARCHAR(10),
  PRIMARY KEY (`ID`),
  FOREIGN KEY(ORG_LOCATION_ID) REFERENCES `ORG_LOCATIONS`(ID)
) ;



