package com.bis.sourcelead.reportsDTO;

public class ApplicantsBySourceDTO {

	private String category;
	
	private Integer applicantsCount;
	
	private Integer shortlistedCount;
	
	private Integer interviewsCount;
	
	private Integer offeredCount;
	
	private Integer offerAcceptedCount;
	
	private Integer offerRejectedCount;
	
	private Integer backoutCount;
	
	private Integer rejectedCount;
	
	

	public String getCategory() {
		return category;
	}

	public void setCategory(String category) {
		this.category = category;
	}

	public Integer getApplicantsCount() {
		return applicantsCount;
	}

	public void setApplicantsCount(Integer applicantsCount) {
		this.applicantsCount = applicantsCount;
	}

	public Integer getShortlistedCount() {
		return shortlistedCount;
	}

	public void setShortlistedCount(Integer shortlistedCount) {
		this.shortlistedCount = shortlistedCount;
	}

	public Integer getInterviewsCount() {
		return interviewsCount;
	}

	public void setInterviewsCount(Integer interviewsCount) {
		this.interviewsCount = interviewsCount;
	}

	public Integer getOfferedCount() {
		return offeredCount;
	}

	public void setOfferedCount(Integer offeredCount) {
		this.offeredCount = offeredCount;
	}

	public Integer getOfferAcceptedCount() {
		return offerAcceptedCount;
	}

	public void setOfferAcceptedCount(Integer offerAcceptedCount) {
		this.offerAcceptedCount = offerAcceptedCount;
	}

	public Integer getBackoutCount() {
		return backoutCount;
	}

	public void setBackoutCount(Integer backoutCount) {
		this.backoutCount = backoutCount;
	}

	public Integer getRejectedCount() {
		return rejectedCount;
	}

	public void setRejectedCount(Integer rejectedCount) {
		this.rejectedCount = rejectedCount;
	}

	public Integer getOfferRejectedCount() {
		return offerRejectedCount;
	}

	public void setOfferRejectedCount(Integer offerRejectedCount) {
		this.offerRejectedCount = offerRejectedCount;
	}
	
	
}
