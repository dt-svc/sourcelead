package com.bis.sourcelead.reportsDTO;

public class TimeToFillDTO {

	private String month;
	
	private String fillCount;
	
	private Integer year;
	
	private String monthStr;
	
	private double fillCountValue;
	

	public String getMonth() {
		return month;
	}

	public void setMonth(String month) {
		this.month = month;
	}

	public String getFillCount() {
		return fillCount;
	}

	public void setFillCount(String fillCount) {
		this.fillCount = fillCount;
	}

	public Integer getYear() {
		return year;
	}

	public void setYear(Integer year) {
		this.year = year;
	}

	public String getMonthStr() {
		return monthStr;
	}

	public void setMonthStr(String monthStr) {
		this.monthStr = monthStr;
	}

	public double getFillCountValue() {
		return fillCountValue;
	}

	public void setFillCountValue(double fillCountValue) {
		this.fillCountValue = fillCountValue;
	}

	
	
}
