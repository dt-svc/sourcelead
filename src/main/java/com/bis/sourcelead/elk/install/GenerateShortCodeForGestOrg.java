package com.bis.sourcelead.elk.install;

import java.beans.PropertyVetoException;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.Statement;

import javax.sql.DataSource;

import org.apache.commons.lang.RandomStringUtils;
import org.springframework.context.ApplicationContext;
import org.springframework.context.annotation.AnnotationConfigApplicationContext;

import com.bis.sourcelead.db.DatabaseConnectionConfig;
import com.bis.sourcelead.db.PropertyPathConfiguration;
import com.mchange.v2.c3p0.ComboPooledDataSource;

public class GenerateShortCodeForGestOrg {
private ComboPooledDataSource comboPooledDataSource;
ApplicationContext ctx = new AnnotationConfigApplicationContext(PropertyPathConfiguration.class);
DatabaseConnectionConfig dbconfig = ctx.getBean(DatabaseConnectionConfig.class);

private void GenerateAutoGeneratedShortCodeForGestOrg() {
	 DataSource dataSource = comboPooledDataSource();
	 try (Connection con = dataSource.getConnection()) {
		 	Statement stmt = con.createStatement();
		 	Statement stmt1 = con.createStatement();
		 	Statement stmt2 = con.createStatement();
			PreparedStatement pstmt = null;
			String orgShortCode = null;
			String orgLocations = "SELECT * FROM "+dbconfig.getSchema()+".ORG_LOCATIONS where GENERATED_USER_ID IS NULL ";
			ResultSet location = stmt.executeQuery(orgLocations);
			while(location.next()){
					Long locationId  = location.getLong("ID");
				 	Long orgId  = location.getLong("ORG_ID");
				 	String orgs = "SELECT * FROM "+dbconfig.getSchema()+".ORG where Id = '"+orgId+"'  ";
				 	ResultSet org = stmt1.executeQuery(orgs);
				 	while(org.next()){
				 		Boolean validateShortCode = true;
				 		while(validateShortCode){
				 			 orgShortCode = RandomStringUtils.randomAlphabetic(4);
				 			 String validateGeneratedUserId = "Select * FROM "+dbconfig.getSchema()+".ORG_LOCATIONS where GENERATED_USER_ID = '"+orgShortCode+"'";
				 			 ResultSet validateGeneratedUser = stmt2.executeQuery(validateGeneratedUserId);
				 			 if(validateGeneratedUser.next()){
				 					validateShortCode = true;
				 				}else {
				 					validateShortCode = false;
				 				}
				 		 }
						 String query = "update "+dbconfig.getSchema()+".ORG_LOCATIONS set GENERATED_USER_ID = ? where ID = ? ";
						 pstmt = con.prepareStatement(query); 
					     pstmt.setString(1,orgShortCode.toUpperCase());
					     pstmt.setLong(2, locationId);
					     pstmt.executeUpdate();
				 	}
			}
	 }catch(Exception e) {
		 e.printStackTrace(); 
	 }
}
	
private DataSource comboPooledDataSource() {
    this.comboPooledDataSource = new ComboPooledDataSource();
    try {
        comboPooledDataSource.setDriverClass(dbconfig.getDriverClass());
    } catch (PropertyVetoException e) {
        throw new RuntimeException(e);
    }
    comboPooledDataSource.setJdbcUrl(dbconfig.getJdbcUrl());
    comboPooledDataSource.setUser(dbconfig.getUser());
    comboPooledDataSource.setPassword(dbconfig.getPassword());
    return comboPooledDataSource;
}	
		
public static void main(String[] args) {
	GenerateShortCodeForGestOrg alertExpenseCode = new GenerateShortCodeForGestOrg();
	alertExpenseCode.GenerateAutoGeneratedShortCodeForGestOrg();
}
	
}